# ============================================================ формат частей
def T(s):
    """Обычный текст-связка (разметки не получает)."""
    return ("t", s)


def E(s, type_, form, note=None, cat="canonical"):
    """Размеченная величина."""
    return ("e", s, type_, form, note, cat)


def parts_text(parts):
    """Склейка частей в строку — для самопроверки генератора."""
    return "".join(p[1] for p in parts)


