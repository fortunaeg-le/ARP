def _amount_round(rnd):
    """Круглая сумма: 10 000 / 250 000 / 2 000 000 …"""
    return rnd.choice([1, 2, 3, 5, 7, 10, 15, 25, 100, 250, 500]) * \
        rnd.choice([1000, 10000, 100000])


def m_digits_words_kop(rnd):
    """10 000 (Десять тысяч) рублей 00 копеек"""
    n = _amount_round(rnd)
    kop = rnd.choice([0, 0, 0, 50])
    s = "%s (%s) %s %02d %s" % (group3(n), cap(spell_int(n, "nom", "m")),
                                plural(n, RUBLE), kop, plural(kop, KOPEK))
    return [E(s, "MONEY", "money.digits_words_kop",
              "цифры + расшифровка прописью в скобках + копейки")]


def m_digits_frac_words_all(rnd):
    """123 456,78 (сто двадцать три тысячи четыреста пятьдесят шесть рублей
    семьдесят восемь копеек)"""
    n = rnd.randint(10000, 999999)
    kop = rnd.randint(1, 99)
    s = "%s,%02d (%s %s %s %s)" % (
        group3(n), kop,
        spell_int(n, "nom", "m"), plural(n, RUBLE),
        spell_int(kop, "nom", "f"), plural(kop, KOPEK))
    return [E(s, "MONEY", "money.digits_frac_words_all",
              "дробная сумма цифрами, вся расшифровка внутри скобок, строчными")]


