# -*- coding: utf-8 -*-
"""
values.py — формулировки НОВЫХ видов данных корпуса V2:
суммы (MONEY), проценты (PERCENT), сроки (TERM), транши (TRANCHE).

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Главный риск сессии: генератор пишет и текст, и эталон.
Если сумма порождается одним способом, детектор научится одному способу и
покажет отличные цифры, которые ничего не значат. Поэтому виды записи собраны
здесь в ЯВНЫЙ реестр форм, каждая порождённая величина помечена
идентификатором формы (`form`), а тест `tests/test_corpus_v2_form_diversity.py`
считает число РАЗНЫХ форм на вид данных и краснеет, если их стало мало.

ЧТО ТАКОЕ «ФОРМА». Форма — это ОБЛИК РАЗМЕЧЕННОГО СПАНА, а не облик
предложения вокруг него. Два спана одинакового вида в разных предложениях
получают ОДИН идентификатор формы: иначе разнообразие можно было бы накрутить
переписыванием окружения, ничего не меняя в самой величине.

ОТКУДА ФОРМУЛИРОВКИ. Все перечисленные виды записи заданы техническим
заданием сессии CORPUS-V2 (подборка из открытых источников). Они НЕ сочинялись
здесь и НЕ подгонялись под то, что умеет находить детектор: этот файл ничего
не знает об устройстве детектора.

ГРАНИЦА СПАНА (контракт корпуса V2, действует для всех новых видов):
  * спан покрывает величину ЦЕЛИКОМ вместе с единицей измерения и с расшифровкой
    в скобках: «10 000 (Десять тысяч) рублей 00 копеек» — один спан;
  * ограничитель, который меняет падеж или смысл величины, ВХОДИТ в спан:
    «не более 2 000 000 (Двух миллионов) рублей», «не позднее 01.11.2025»;
  * спаны НИКОГДА не пересекаются. Если одна формулировка несёт две величины
    («включая НДС 22% в размере 1 803 (Одна тысяча восемьсот три) рубля»),
    каждая размечается своим спаном, а связки между ними — обычный текст.

ТРАНШИ — СЛАБОЕ МЕСТО, ЧИТАТЬ ОБЯЗАТЕЛЬНО. Договорных формулировок транша в
открытых источниках найти не удалось; есть только описательные обороты
(«первый транш», «график выдачи траншей»). Здесь порождаются именно они.
Числовых величин в них нет. Метрикам по TRANCHE доверять нельзя — вид данных
в корпусе беднее прочих, и это НЕ лечится добавлением вхождений.
"""

