def m_mismatch(rnd):
    """Состязательный случай: цифры и пропись НЕ совпадают.

    ТЗ: «9 500 000, а прописью: девять пятьсот тысяч рублей». Такое встречается
    в реальных договорах. Пропись здесь намеренно неграмматична и обозначает
    ДРУГУЮ величину — это не опечатка генератора."""
    a = rnd.randint(1, 9)
    b = rnd.choice([200, 300, 500, 700, 900])
    digits = "%s" % group3(a * 1000000 + b * 1000)
    words = "%s %s тысяч рублей" % (_UNITS_NOM["m"][a], _HUND_NOM[b // 100])
    return [
        E(digits, "MONEY", "money.mismatch_digits",
          "цифровая часть суммы, расходящейся с прописью", cat="adversarial"),
        T(", а прописью: "),
        E(words, "MONEY", "money.mismatch_words",
          "пропись, не совпадающая с цифрами (и неграмматичная)", cat="adversarial"),
    ]


