def plural_index(n):
    """0 -> «рубль», 1 -> «рубля», 2 -> «рублей» (обычное русское согласование)."""
    n1, n2 = n % 10, n % 100
    if n1 == 1 and n2 != 11:
        return 0
    if 2 <= n1 <= 4 and not 12 <= n2 <= 14:
        return 1
    return 2


def plural(n, forms, case="nom"):
    return (forms[0] if case == "nom" else forms[1])[plural_index(n)]


def _triple(n, case, gender):
    """0 < n < 1000 -> слова."""
    out = []
    h, rest = divmod(n, 100)
    if h:
        out.append((_HUND_NOM if case == "nom" else _HUND_GEN)[h])
    t, u = divmod(rest, 10)
    if t == 1:
        out.append((_TEENS_NOM if case == "nom" else _TEENS_GEN)[u])
    else:
        if t:
            out.append((_TENS_NOM if case == "nom" else _TENS_GEN)[t])
        if u:
            out.append((_UNITS_NOM if case == "nom" else _UNITS_GEN)[gender][u])
    return out


def spell_int(n, case="nom", gender="m"):
    """Целое число прописью. case: nom|gen. gender — род ЕДИНИЦ (рубль -> m)."""
    if n == 0:
        return "ноль" if case == "nom" else "нуля"
    words = []
    for value, sc_gender, f_nom, f_gen in reversed(_SCALES):
        cnt, n = divmod(n, value)
        if not cnt:
            continue
        words += _triple(cnt, case, sc_gender)
        words.append(plural(cnt, (f_nom, f_gen), case))
    if n:
        words += _triple(n, case, gender)
    return " ".join(words)


def cap(s):
    return s[:1].upper() + s[1:]


def group3(n):
    """1234567 -> «1 234 567» (неразрывных пробелов НЕ ставим: это корпус V2,
    невидимые символы — предмет отдельных состязательных приёмов)."""
    s = str(n)
    out = []
    while s:
        out.insert(0, s[-3:])
        s = s[:-3]
    return " ".join(out)


