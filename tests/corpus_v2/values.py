def _percent_body(k, off, rnd, frac, bind, limit):
    """Тело процента без потолка: строка + набор признаков."""
    ax = {"дробь ставки": frac}
    if frac != "нет":
        # D6: величина задана дробью, знака % нет вовсе.
        body = "%s ключевой ставки ЦБ РФ" % frac
    else:
        rec = axis("PERCENT", "запись", k, off)
        ax["запись"] = rec
        if rec == "15%":
            body = "%d%%" % rnd.choice([5, 9, 12, 15, 18, 20, 21])
            ax["пропись"] = "нет"          # D7: расшифровывать нечего
        elif rec == "10 (десять) процентов":
            n = rnd.choice([5, 7, 10, 15, 20])
            body = "%d (%s) %s" % (n, spell_int(n, "nom", "m"), plural(n, PERCENT_W))
            # D7: пропись уже внутри записи, отдельной осью не считается
        else:
            v = _DECIMALS[(k + off) % len(_DECIMALS)]
            pr = axis("PERCENT", "пропись", k, off)
            ax["пропись"] = pr
            tail = " %" if rec == "0,1 %" else " процента"
            if pr == "нет":
                body = v + tail
            elif pr == "(одной десятой) род.":
                body = "%s (%s)%s" % (v, _DECIMAL_GEN[v], tail)
            else:
                body = "%s (%s)%s" % (v, _DECIMAL_NOM[v], tail)
    ax["привязка"] = bind
    ax["ограничение"] = limit
    return body + " " + _BIND_TEXT[bind], ax


def percent(k, off, rnd):
    frac = axis("PERCENT", "дробь ставки", k, off)
    bind = axis("PERCENT", "привязка", k, off)
    limit = axis("PERCENT", "ограничение", k, off)
    body, ax = _percent_body(k, off, rnd, frac, bind, limit)
    out = [E(body, "PERCENT", form_id("PERCENT", ax), "процент", axes=ax)]
    if limit != "нет":
        # Потолок несёт СВОЙ процент -> собственный спан, связка между ними —
        # обычный текст (спаны не пересекаются).
        #
        # Потолок собирается ТЕМ ЖЕ механизмом осей, а не отдельным литералом
        # «20%». Иначе каждый потолок добавлял бы одно и то же значение оси
        # «запись», и на сотне потолков ось перекосило бы: значение «15%»
        # заняло бы больше половины вхождений — ровно та бедность, от которой
        # уходит этот этап. Привязка у потолка закреплена — она часть
        # формулировки ограничения из ТЗ.
        cbody, cax = _percent_body(k + 7, off, rnd, "нет", "от цены Договора", "нет")
        out += [T(", но не более "),
                E(cbody, "PERCENT", form_id("PERCENT", cax),
                  "потолок ответственности", axes=cax)]
    return out


