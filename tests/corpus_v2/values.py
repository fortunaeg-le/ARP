# Порядок осей в идентификаторе формы. Фиксирован, чтобы идентификатор был
# стабилен между прогонами и сравним между отчётами.
AXIS_ORDER = {k: list(v) for k, v in AXES.items()}

# ---------------------------------------------------------- значения-нейтрали
# ТЗ этапа требует: «ни одно значение не занимает больше половины вхождений
# вида данных». Правило написано про СПОСОБЫ ЗАПИСИ, и для них оно исполняется
# без оговорок. Но четыре оси устроены иначе: они не «как записано», а
# «есть ли необязательный признак вообще». Их выключенное значение — не способ
# записи, а обычное положение дел.
#
# Загнать эти четыре значения под половину означало бы: у половины договоров
# корпуса неустойка с потолком, половина сроков задана датой, половина ставок
# выражена дробью ключевой ставки ЦБ, а в половине документов место под сумму
# не заполнено. Это не разнообразие, это неправдоподобный корпус, подогнанный
# под формулировку проверки. Поэтому для перечисленных значений действует
# отдельное правило (см. tests/test_corpus_v2_axis_coverage.py): потолок выше,
# зато ВКЛЮЧЁННАЯ часть оси обязана быть заметной, а не следовой.
#
# Список закрытый и короткий НАМЕРЕННО: любое пополнение — это ослабление
# проверки, и оно обязано объясняться здесь же.
NEUTRAL = {
    ("MONEY", "заполненность"): "значение",
    ("PERCENT", "ограничение"): "нет",
    ("PERCENT", "дробь ставки"): "нет",
    ("TERM", "вместо срока — дата"): "нет",
}


def form_id(type_, axes):
    """Идентификатор формы = комбинация значений осей.

    Именно ПРОИЗВЕДЕНИЕ осей, а не номер функции в списке: «сколько разных
    форм» в отчёте теперь считает реально встреченные комбинации.
    Неприменимые оси в идентификатор не входят — иначе «неприменимо» стало бы
    молчаливым значением и раздуло бы счёт форм пустотой.
    """
    parts = [type_.lower()]
    for name in AXIS_ORDER[type_]:
        if name in axes:
            parts.append("%s=%s" % (name, axes[name]))
    return "|".join(parts)


# ---------------------------------------------------------------- раздача осей
# ЗДЕСЬ БЫЛА ОШИБКА, И ОНА СТОИТ ОБЪЯСНЕНИЯ: осям раздавали значения формулой
# «(k * шаг + смещение) % длина», по счётчику k, общему для всех осей. Шаг
# подбирался взаимно простым с длиной, поэтому КАЖДАЯ ОСЬ ПО ОТДЕЛЬНОСТИ
# выглядела равномерной. А ВМЕСТЕ они шли в ногу: ось из 2 значений давала
# (k+смещение) % 2, ось из 4 — (k+смещение) % 4, и первая полностью
# определялась второй. В корпусе это дало ось «пропись», у которой ДВА из
# четырёх значений не встретились НИ РАЗУ, — при том что сама по себе ось
# перебирала все четыре.
#
# Никакая функция ОДНОГО счётчика от этого не спасает: если длины осей имеют
# общий делитель, оси остаются связанными. Поэтому раздача устроена иначе —
# ПЕРЕМЕШАННЫМИ БЛОКАМИ. Последовательность вхождений режется на блоки длиной
# в число значений оси; внутри блока значения идут в порядке случайной
# перестановки, СВОЕЙ у каждой оси и у каждого блока. Отсюда:
#   * равномерность точная — за каждый блок каждое значение ровно один раз;
#   * оси независимы — перестановки порождаются разными ключами;
#   * раздача остаётся детерминированной и не зависит от порядка сборки
#     документов: перестановка вычисляется из (ось, длина, номер блока), а не
#     из состояния генератора.
import random as _random


def _perm(n, key, block):
    r = _random.Random("%s|%d|%d" % (key, n, block))
    p = list(range(n))
    r.shuffle(p)
    return p


def pick(values, k, axis_key, offset):
    n = len(values)
    block, pos = divmod(k + offset, n)
    return values[_perm(n, axis_key, block)[pos]]


# Смеси для осей, где РАВНОМЕРНАЯ раздача неправдоподобна. Значение может
# повторяться в смеси — тогда оно чаще. Ось «заполненность» из двух значений
# при равномерной раздаче дала бы корпус, наполовину состоящий из пустых мест
# под сумму; ось «ограничение» — каждый второй процент с потолком.
_MIX = {
    ("MONEY", "заполненность"): ["значение"] * 4 + ["пропуск подчёркиваниями"],
    ("PERCENT", "ограничение"): ["нет"] * 3 + ["но не более 20% от цены договора"],
    ("PERCENT", "дробь ставки"): ["нет"] * 3 + ["1/300", "1/150", "1/130"],
    ("TERM", "вместо срока — дата"): ["нет"] * 3 + ["не позднее 01.11.2025"],
}


def axis(type_, name, k, offset):
    """Очередное значение оси `name` вида данных `type_`."""
    values = _MIX.get((type_, name)) or AXES[type_][name]
    return pick(values, k, "%s.%s" % (type_, name), offset)


