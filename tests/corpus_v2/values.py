NEW_TYPES = ("MONEY", "PERCENT", "TERM", "TRANCHE", "DOCNUM", "DATE")

# Виды данных, у которых ЕСТЬ числовое значение и к которым поэтому применимы
# состязательные приёмы над числом (задача 3 этапа).
NUMERIC_TYPES = ("MONEY", "PERCENT", "TERM", "DOCNUM")


def _adv_one(type_, k, off, rnd):
    if type_ == "MONEY":
        s, ax = _money_value(k, off, rnd, vat="нет")
        return E(s, "MONEY", form_id("MONEY", ax), "сумма", axes=ax)
    return BUILDERS[type_](k, off, rnd)[0]


def adversarial_source(type_, k, off, rnd, tries=40):
    """Одна величина вида `type_` с ДВУМЯ ЦИФРАМИ ПОДРЯД.

    Нужна задаче 3: все приёмы (гомоглиф, невидимые символы, разрыв
    форматированием, пробелы в цифрах, граница ячейки, перенос строки) рвут
    или подменяют ЧИСЛО, и всем им нужна позиция между двумя цифрами.

    ЧТО ИЗ-ЗА ЭТОГО НЕ ПОКРЫТО, и это ограничение честное, а не скрытое:
    записи, где двух цифр подряд не бывает, под приёмы не попадают вовсе.
    Это «в течение 5 рабочих дней» (однозначное число), «трех» и «Пятнадцать
    миллионов … рублей» (число словом), «0,1 (одной десятой) %» (десятичная
    доля). Их состязательные варианты в корпусе отсутствуют, и метрику по
    приёмам нельзя переносить на них.

    Возвращает РОВНО ОДНУ часть, чтобы приём не разъехался по двум спанам.
    """
    for step in range(tries):
        part = _adv_one(type_, k + step, off, rnd)
        s = part[1]
        if any(s[i].isdigit() and s[i + 1].isdigit() for i in range(len(s) - 1)):
            return part
    raise AssertionError(
        "%s: за %d попыток не нашлось записи с двумя цифрами подряд" % (type_, tries))


