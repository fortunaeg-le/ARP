def T(s):
    """Обычный текст-связка (разметки не получает)."""
    return ("t", s)


def E(s, type_, form, note=None, cat="canonical", axes=None):
    """Размеченная величина."""
    return ("e", s, type_, form, note, cat, axes or {})


def NEG(s, type_, why, form, axes=None):
    """Вхождение вида данных, которое МАСКИРОВАТЬ НЕЧЕГО (значения нет).

    Существует ради задачи 4 этапа: «Без НДС» и пустое место под сумму
    («______ рублей ______ копеек») перечислены в ТЗ среди СУММ, но чисел не
    содержат. Размечать их сущностью — обманывать recall: детектор,
    «нашедший» там сумму, обязан считаться ЛОЖНЫМ СРАБАТЫВАНИЕМ, а не
    находкой. Поэтому они негативы, но НЕГАТИВЫ ТИПИЗИРОВАННЫЕ: вид данных и
    набор признаков у них есть, и в покрытие осей они входят наравне с
    величинами.
    """
    return ("n", s, type_, why, form, axes or {})


def parts_text(parts):
    """Склейка частей в строку — для самопроверки генератора."""
    return "".join(p[1] for p in parts)


