_KOP_DECIMAL = {",00": 2, ",0": 1}       # ось -> сколько знаков после запятой
_KOP_WORD = ("00 копеек", "0 коп.")
_CUR_WORD = ("рублей", "руб.", "рубля")   # с чем сочетаются копейки словом
_CUR_TEXT = {"рублей": "рублей", "руб.": "руб.", "₽": "₽", "RUB": "RUB",
             "рубля": "рубля"}


def _fit_amount(n, cur):
    """D4: подогнать сумму под согласование с выбранной формой слова «рубль».

    «рублей» требует индекса 2 (…5, …0, …11-14), «рубля» — индекса 1 (…2-4).
    Сокращение «руб.», знак ₽ и код RUB согласования не требуют.
    """
    if cur == "рублей":
        while plural_index(n) != 2:
            n += 1
    elif cur == "рубля":
        while plural_index(n) != 1:
            n += 1
    return n


def _money_value(k, off, rnd, vat="нет"):
    """Одна сумма-величина: части + набор признаков. Без оговорки про НДС."""
    ax = {}
    kop = axis("MONEY", "копейки", k, off)
    cur = axis("MONEY", "валюта", k, off)
    propis = axis("MONEY", "пропись", k, off)
    words_only = propis == "вместо цифр"

    # D2: копейки словом живут только со словесной валютой.
    if kop in _KOP_WORD and cur not in _CUR_WORD:
        cur = _CUR_WORD[(k + off) % len(_CUR_WORD)]
    if words_only:
        # D1. Сумма прописью не сочетается ни со знаком ₽, ни с кодом RUB, ни
        # с сокращением «руб.»; копейки при ней пишутся цифрами со словом
        # («…рублей 00 копеек»), а не запятой — запятая после слов невозможна.
        if cur not in ("рублей", "рубля"):
            cur = "рубля" if (k + off) % 2 else "рублей"
        if kop in _KOP_DECIMAL:
            kop = _KOP_WORD[(k + off) % len(_KOP_WORD)]
    # D3: родительная пропись требует ограничителя и не терпит «рубля».
    if propis == "(Двух миллионов) род." and cur == "рубля":
        cur = "рублей"

    n = rnd.randint(10, 999) * rnd.choice([1000, 10000, 100000])
    n = _fit_amount(n, cur)
    prefix = ""

    if words_only:
        # Разряды неприменимы: разделять нечего, число и есть пропись.
        body = "%s %s" % (cap(spell_int(n, "nom", "m")), _CUR_TEXT[cur])
        if kop in _KOP_WORD:
            body += _kop_words(kop, rnd)
    else:
        sep_name = axis("MONEY", "разделитель разрядов", k, off)
        sep = {"пробел": " ", "неразрывный пробел": NBSP, "слитно": ""}[sep_name]
        ax["разделитель разрядов"] = sep_name
        digits = group3(n, sep)
        if kop in _KOP_DECIMAL:
            nd = _KOP_DECIMAL[kop]
            digits += "," + ("%0*d" % (nd, rnd.randint(0, 10 ** nd - 1)))
        body = digits
        if propis == "(Двух миллионов) род.":
            prefix = "не более " if (k + off) % 2 else "не менее "
            body += " (%s)" % cap(spell_int(n, "gen", "m"))
        elif propis == "(Десять тысяч)":
            body += " (%s)" % cap(spell_int(n, "nom", "m"))
        elif propis == "(десять тысяч)":
            body += " (%s)" % spell_int(n, "nom", "m")
        body += " " + _CUR_TEXT[cur]
        if kop in _KOP_WORD:
            body += _kop_words(kop, rnd)

    ax["копейки"] = kop
    ax["валюта"] = cur
    ax["пропись"] = propis
    ax["заполненность"] = "значение"
    ax["НДС"] = vat
    return prefix + body, ax


def _kop_words(kop, rnd):
    if kop == "00 копеек":
        c = rnd.choice([0, 0, 50])
        return " %02d %s" % (c, plural(c, KOPEK))
    return " %d коп." % rnd.choice([0, 0, 5])


# Пустое место под сумму. Обе записи взяты из ТЗ дословно.
_BLANK_FORMS = [
    "цена Контракта составляет ______ рублей ______ копеек",
    "____ руб. (_____)_____ коп., включая НДС ___ руб. (_____)_____ коп.",
]


def money(k, off, rnd):
    """Сумма со всеми осями. Возвращает список частей."""
    fill = axis("MONEY", "заполненность", k, off)
    vat = axis("MONEY", "НДС", k, off)

    if fill == "пропуск подчёркиваниями":
        # D5: значения нет вовсе -> типизированный негатив.
        s = _BLANK_FORMS[k % len(_BLANK_FORMS)]
        ax = {"заполненность": fill}
        return [NEG(s, "MONEY", "место под сумму не заполнено: маскировать нечего, "
                                "срабатывание детектора здесь — ложное",
                    form_id("MONEY", ax), ax)]

    if vat == "Без НДС":
        # Задача 4 этапа. «Без НДС» перечислено ТЗ среди сумм, но числа не
        # содержит: сама сумма рядом размечена как величина, а «Без НДС» —
        # негатив. Раньше это была СУЩНОСТЬ MONEY без единой цифры.
        s, ax = _money_value(k, off, rnd, vat=vat)
        return [E(s, "MONEY", form_id("MONEY", ax), "сумма с оговоркой «Без НДС»",
                  axes=ax),
                T(", "),
                NEG("Без НДС", "MONEY", "указание на отсутствие НДС: числового "
                                        "значения не содержит",
                    form_id("MONEY", {"НДС": "Без НДС"}), {"НДС": "Без НДС"})]

    s, ax = _money_value(k, off, rnd, vat=vat)
    head = E(s, "MONEY", form_id("MONEY", ax), "сумма", axes=ax)

    if vat == "нет":
        return [head]
    if vat == "включая НДС N% в размере N":
        # ДВЕ величины в одной формулировке -> два непересекающихся спана
        # плюс отдельный спан ставки.
        rate = 20 if k % 2 else 22
        pax = {"запись": "15%"}
        s2, ax2 = _money_value(k + 3, off, rnd, vat="нет")
        return [head, T(", включая НДС "),
                E("%d%%" % rate, "PERCENT", form_id("PERCENT", pax),
                  "ставка НДС", axes=pax),
                T(" в размере "),
                E(s2, "MONEY", form_id("MONEY", ax2), "сумма НДС", axes=ax2)]
    if vat == "в т.ч. НДС 18%":
        pax = {"запись": "15%"}
        return [head, T(", в т.ч. НДС "),
                E("18%", "PERCENT", form_id("PERCENT", pax), "ставка НДС", axes=pax)]
    return [head, T(", " + vat)]


