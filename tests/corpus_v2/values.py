# Номер договора — НЕ ПДн, поэтому вхождения типизированные НЕГАТИВЫ. Ось у
# них есть, и она проверяется наравне с осями величин: детектор, срабатывающий
# на «01Ф-00034/16-124Д», портит точность ровно так же, как пропуск портит
# полноту.
def docnum(k, off, rnd):
    fmt = axis("DOCNUM", "формат", k, off)
    if fmt == "17595/001-сс":
        s = "%05d/%03d-сс" % (rnd.randint(10000, 99999), rnd.randint(1, 999))
    elif fmt == "2/17":
        s = "%d/%02d" % (rnd.randint(1, 9), rnd.randint(10, 25))
    elif fmt == "01Ф-00034/16-124Д":
        s = "%02dФ-%05d/%02d-%03dД" % (rnd.randint(1, 99), rnd.randint(1, 99999),
                                       rnd.randint(10, 25), rnd.randint(1, 999))
    elif fmt == "27/16":
        s = "%02d/%02d" % (rnd.randint(10, 99), rnd.randint(10, 25))
    else:
        s = "%d/%d-%s" % (rnd.randint(1, 99), rnd.choice([2023, 2024, 2025]),
                          rnd.choice("ПАСКД"))
    ax = {"формат": fmt}
    return [NEG(s, "DOCNUM", "номер договора — не ПДн", form_id("DOCNUM", ax), ax)]


