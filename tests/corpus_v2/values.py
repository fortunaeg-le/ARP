def declared_form_ids(seed=0):
    """{вид данных -> множество идентификаторов форм}, снятое с самого реестра.

    Идентификаторы формы записаны внутри порождающих функций, поэтому реестр
    опрашивается вызовом: каждая функция зовётся один раз и объявляет, какие
    спаны она делает. Значения чисел от `rnd` не зависят — идентификатор формы
    у функции всегда один и тот же, меняется только величина.

    Нужно тесту разнообразия, чтобы сверять МНОЖЕСТВА форм, а не только их
    количество: подмена одной формы на другую количество не меняет.
    """
    import random
    out = {}
    rnd = random.Random(seed)
    for forms in ALL_FORMS.values():
        for f in forms:
            for p in f(rnd):
                if p[0] == "e":
                    out.setdefault(p[2], set()).add(p[3])
    return out
