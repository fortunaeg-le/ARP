class TestMechanism1bCollectiveRole:
    """Механизм 1b: голое имя за АББРЕВИАТУРОЙ, чья вершина — МНОЖЕСТВЕННОЕ
    нарицательное (коллектив-роль), не якорит ORG. Реальный промах договора:
    «…Закона об АО Акционеры договорились…» — «АО» ссылка на закон, «Акционеры» —
    роль-коллектив; проход 2 тиражировал её по всему документу."""

    def test_ao_akcionery_law_reference_not_org(self):
        orgs = _orgs(
            "в соответствии со статьёй 7 Закона об АО Акционеры договорились "
            "предусмотреть порядок. Акционеры пользуются преимущественным правом. "
            "Права Акционеров защищены.")
        assert orgs == [], orgs

    def test_plural_collective_after_form_not_org(self):
        """Однозначно множественный коллектив за формой — не название. (Форма «Стороны»
        для pymorphy неоднозначна: род.ед. «стороны» перевешивает им.мн., поэтому её
        в реальном договоре гасят другие ветви — spelled-pattern-B/определение — а не
        эта; здесь берём недвусмысленно множественные роли.)"""
        assert _orgs("АО Участники голосуют. Участники подписали протокол.") == []
        assert _orgs("Как сказано, ПАО Акционеры возражают. Акционеры несогласны.") == []

    def test_singular_common_noun_org_kept(self):
        """Компания сингулярна: «ПАО Василёк»/«ООО Восход» — нарицательные, но
        ЕДИНСТВЕННОГО числа: остаются ORG (демоушен только для множественного)."""
        assert any("Василёк" in o for o in
                   _orgs("Поставщик — ПАО Василёк. Василёк отгрузит товар.")), "Василёк потерян"
        assert any("Восход" in o for o in
                   _orgs("Арендатор ООО Восход. Восход арендует помещение.")), "Восход потерян"


class TestRecallPreserved:
    def test_abbreviation_bare_name_kept(self):
        """«ПАО Сбербанк» — аббревиатура + голое имя, ОСТАЁТСЯ ORG (демоушен только
        для развёрнутых форм)."""
        orgs = _orgs("Кредитор — ПАО Сбербанк. Сбербанк предоставляет кредит.")
        assert any("Сбербанк" in o for o in orgs), orgs

    def test_quoted_org_with_form_kept(self):
        orgs = _orgs("ООО «Меркурий» поставляет товар. Меркурий надёжен.")
        assert any("Меркурий" in o for o in orgs), orgs

    def test_org_named_before_inn_kept(self):
        """Бескавычное имя + ИНН юрлица (10 цифр) — по-прежнему ORG (сильный признак,
        не тронут механизмом 1)."""
        orgs = _orgs("Поставщик Ромашка ИНН 7701234567 обязуется поставить товар.")
        assert any("Ромашка" in o for o in orgs), orgs


