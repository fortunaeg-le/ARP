class TestMechanism1SpelledFormDemoted:
    def test_obshestvo_zakazchik_not_org(self):
        """«Общество Заказчик» — роль-термин, не название (развёрнутая форма-слово
        «Общество» + заглавное слово). Не ORG; проход 2 не тиражирует «Общество»."""
        orgs = _orgs("Общество Заказчик передаёт Обществу Исполнителю права. "
                     "Общество вправе требовать. Общества обязаны.")
        assert orgs == [], orgs

    def test_akcionernoe_obshestvo_bare_not_org(self):
        orgs = _orgs("Акционерное общество вправе. Общество Заказчик обязано.")
        assert orgs == [], orgs

    def test_otvetstvennost_prose_not_org(self):
        """«ответственность За Неисполнение» — проза, форма-слово матчит
        «ответственност…» из развёрнутого класса; демоушен снимает ложный ORG."""
        orgs = _orgs("Ответственность За Неисполнение обязательств наступает по закону.")
        assert orgs == [], orgs


