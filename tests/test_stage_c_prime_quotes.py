"""Этап C′ — УЖЕСТОЧЕНИЕ ЯКОРЯ КАВЫЧЕК/ФОРМЫ (anchor_registry.OrgAnchorDetector).

ПРОБЛЕМА (реальный корпоративный договор, синтетика её не содержит): в разделе
ОПРЕДЕЛЕНИЙ термины вводятся конструкцией в кавычках («"Сторона" означает …»,
«именуемое в дальнейшем «Общество»»), а РАЗВЁРНУТАЯ форма-слово («Общество
Заказчик») грабила голое имя в реестр ORG — проход 2 тиражировал роль-термин по всем
падежам (документ → «решето», метки до ORG_37).

ДВА МЕХАНИЗМА (оба структурные, БЕЗ списков слов):
  1. Развёрнутая форма-СЛОВО больше не якорит голое бескавычное имя (только
     аббревиатура ООО/ПАО/АО/… это делает). Кавычки/ИНН-ОГРН регистрируют ORG как и
     прежде.
  2. Конструкция определения «"X" означает / — это / под "X" понимается / имеет
     значение» — АНТИ-ЯКОРЬ: ядро в кавычках не регистрируется.

ЗЕРКАЛО приёмки — детектор РАЗЛИЧАЕТ:
  (+) «ООО «Ромашка», именуемое в дальнейшем «Исполнитель»» → «Ромашка» ORG,
      «Исполнитель» (РОЛЬ) НЕ регистрируется;
  (−) «"Сторона" означает …» → НЕ ORG вообще.
"""
import os

from models import SourceDocument, TextSegment
from anchor_registry import detect_structural
from regex_detector import detect_regex

CFG = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "entity_types.yaml")


def _doc(*paras):
    return SourceDocument(
        segments=[TextSegment(id="p%d" % i, text=t, source_type="docx_paragraph",
                              metadata={"paragraph_index": i})
                  for i, t in enumerate(paras)],
        source_format="docx", source_path="x.docx")


def _orgs(*paras):
    doc = _doc(*paras)
    rx = detect_regex(doc, CFG)
    ents = detect_structural(doc, regex_entities=rx)
    return [e.original_text for e in ents if e.entity_type == "ORG"]


# --------------------------------------------------------------------------- #
#            ЗЕРКАЛО (обязательное для приёмки): (+) vs (−)                    #
# --------------------------------------------------------------------------- #
class TestMirrorPlusMinus:
    def test_plus_real_org_kept_role_alias_not_registered(self):
        """(+) «ООО «Ромашка», именуемое в дальнейшем «Исполнитель»»: «Ромашка» —
        ORG (есть org-форма), «Исполнитель» — РОЛЬ, отдельной сущностью НЕ
        регистрируется (ни как якорь, ни проходом 2 по лемме «исполнитель»)."""
        orgs = _orgs(
            "ООО «Ромашка», именуемое в дальнейшем «Исполнитель», с одной стороны.",
            "Исполнитель обязуется выполнить работы. Ромашка несёт ответственность.",
        )
        assert any("Ромашка" in o for o in orgs), orgs
        assert not any("Исполнитель" in o for o in orgs), (
            "РОЛЬ «Исполнитель» не должна регистрироваться как ORG: %s" % orgs)

    def test_minus_definition_term_not_org(self):
        """(−) «"Сторона" означает …» — ОПРЕДЕЛЕНИЕ ТЕРМИНА, не сущность. Ни само
        ядро, ни падежные вхождения (Стороны/Сторону) не должны стать ORG."""
        orgs = _orgs(
            "«Сторона» означает любую из сторон настоящего Договора.",
            "Стороны договорились. Сторона обязана уведомить другую Сторону.",
        )
        assert orgs == [], "Термин «Сторона» не должен быть ORG: %s" % orgs


