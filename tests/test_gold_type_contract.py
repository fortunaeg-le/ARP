# -*- coding: utf-8 -*-
"""
ЭТАП GATE-2, линия 5 — КОНТРАКТ ЭТАЛОНА: генератор и gold.json не разошлись.

ЧТО ОХРАНЯЕТСЯ И ПОЧЕМУ ЭТОГО НЕ ОХРАНЯЛО НИЧТО.
Этап T-GOLD-A переклассифицировал 648 денежных сумм: из НЕГАТИВОВ («текст,
похожий на данные, но данными не являющийся») они стали эталонными сущностями
типа SUM, потому что владелец решил суммы маскировать. Границы не менялись —
записи `negatives` с `why == "сумма — не ПДн"` перенесены в `entities` как есть
(tests/corpus/reclassify_sum.py).

Генератор корпуса `tests/corpus/generate.py` при этом НЕ МЕНЯЛСЯ и по-прежнему
размечает суммы негативами (`d.N(money(rnd), "сумма — не ПДн")`, строки 595 и
721). То есть повторный запуск генератора молча вернёт эталон в прежнее
состояние: 648 сущностей SUM исчезнут, столько же негативов появится обратно.
Последствие — не «неудобство», а разворот метрики на 180°: каждое ПРАВИЛЬНОЕ
срабатывание системы на сумме снова начнёт считаться ЛОЖНЫМ (на HEAD это было
635 ложных срабатываний из 648), FP по негативам подскочит с 16 до ~650,
precision[SUM] исчезнет вместе с типом, а гейт покажет это как деградацию
детекции, которой не было.

Защиты не было никакой — только договорённость в отчёте этапа. Этот тест —
защита: он краснеет и говорит, ЧТО именно произошло и что делать.

ПОЧЕМУ ТЕСТ НЕ ЗАПРЕЩАЕТ ЗАПУСК ГЕНЕРАТОРА. Генератор — законный инструмент, и
корпус может понадобиться пересобрать. Запрещено не пересобирать, а пересобрать
и НЕ ЗАМЕТИТЬ, что решение владельца о суммах откатилось. Правильный порядок
после генерации — прогнать `tests/corpus/reclassify_sum.py` (он идемпотентен),
затем validate.py и пересборку baseline.
"""
import json
import os

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GOLD = os.path.join(ROOT, "tests", "corpus", "gold.json")
GENERATOR = os.path.join(ROOT, "tests", "corpus", "generate.py")

#: Точная формулировка причины из разметки этапа 1 — та же константа, по которой
#: reclassify_sum.py искал записи (SUM_WHY). Сравнение полное, не по префиксу.
SUM_WHY = "сумма — не ПДн"
SUM_TYPE = "SUM"

#: Сколько сумм перенесено этапом T-GOLD-A. Число проверяется не «на равенство
#: ради равенства»: оно отличает «тип на месте» от «тип формально есть, но в нём
#: осталось три записи», то есть от частичного отката.
EXPECTED_SUM_ENTITIES = 648


@pytest.fixture(scope="module")
def gold():
    with open(GOLD, encoding="utf-8") as f:
        return json.load(f)


def test_sums_are_entities_not_negatives(gold):
    """Ни одной суммы среди негативов. Красный здесь = эталон откатился."""
    offenders = [
        (d["doc_id"], n["text"])
        for d in gold for n in d.get("negatives", [])
        if n.get("why") == SUM_WHY
    ]
    assert not offenders, (
        "ЭТАЛОН ОТКАТИЛСЯ: в gold.json снова есть негативы «%s» — %d штук "
        "(например %s). Так размечает суммы ГЕНЕРАТОР tests/corpus/generate.py; "
        "скорее всего он был запущен и перезаписал решение этапа T-GOLD-A "
        "(суммы маскируются и являются эталонными сущностями типа %s). "
        "Пока это так, каждое ПРАВИЛЬНОЕ срабатывание детектора сумм харнесс "
        "считает ЛОЖНЫМ, а FP по негативам вырастает с 16 до ~650. "
        "Что делать: venv/Scripts/python.exe tests/corpus/reclassify_sum.py "
        "(идемпотентен), затем validate.py и пересборка baseline."
        % (SUM_WHY, len(offenders), offenders[:3], SUM_TYPE)
    )


def test_sum_entities_are_present_in_full(gold):
    """Обратная сторона той же монеты: тип SUM обязан быть НА МЕСТЕ и в полном
    составе. Тест выше молчал бы и на пустом эталоне (нет негативов — нет
    нарушения), поэтому наличие проверяется отдельно."""
    n_sum = sum(1 for d in gold for e in d["entities"] if e["type"] == SUM_TYPE)
    assert n_sum == EXPECTED_SUM_ENTITIES, (
        "Сущностей типа %s в эталоне %d, ожидалось %d. Либо эталон перегенерирован "
        "без reclassify_sum.py, либо состав корпуса изменён осознанно — во втором "
        "случае обновите EXPECTED_SUM_ENTITIES вместе с пересборкой baseline."
        % (SUM_TYPE, n_sum, EXPECTED_SUM_ENTITIES)
    )


def test_generator_still_marks_sums_as_negatives_so_the_guard_is_needed():
    """Тест-обоснование: он фиксирует ПРИЧИНУ, по которой два теста выше не
    являются формальностью. Если генератор однажды научат размечать суммы
    сущностями, этот тест покраснеет — и тогда охрану выше можно упростить,
    зная, что расхождение закрыто в источнике, а не в договорённости."""
    with open(GENERATOR, encoding="utf-8") as f:
        src = f.read()
    assert SUM_WHY in src, (
        "Генератор больше не размечает суммы негативом «%s». Значит расхождение "
        "«генератор vs эталон», ради которого заведён этот файл, закрыто в "
        "источнике: перечитайте tests/corpus/generate.py и обновите этот файл — "
        "охрана могла устареть." % SUM_WHY
    )
