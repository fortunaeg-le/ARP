# -*- coding: utf-8 -*-
"""scope_exclusions.py — МАНИФЕСТ ИСКЛЮЧЕНИЙ ИЗ ЛИНИЙ ГЕЙТА (этап V1-SCOPE).

ЗАЧЕМ. Корпус v1 заморожен вместе со своей РАЗМЕТКОЙ, а разметка несёт
ОПРЕДЕЛЕНИЯ («номер договора — не персональные данные»). Когда владелец
принимает противоположное определение, детектор начинает работать верно, а
замороженная разметка объявляет каждое верное срабатывание ложным. Это
столкновение двух определений, а не регресс — и лечится оно не допуском
(допуск прощает ЛЮБОЙ рост, в том числе настоящий) и не пересборкой планки
(она спрятала бы расхождение в новый ноль), а ЯВНЫМ, ИМЕНОВАННЫМ и УЗКИМ
исключением: один тип, одна линия, один корпус, с письменным обоснованием.

ОПАСНОСТЬ, КОТОРУЮ ЭТОТ ФАЙЛ ОБЯЗАН ДЕРЖАТЬ САМ. Список исключений — самая
удобная дорога спрятать неудобное: через три этапа сюда уедет всё, что мешает
зелёному гейту. Поэтому здесь ТРИ замка, и ни один не является обещанием:

  1. `validate()` роняет сборку, если у записи нет автора или обоснования
     (короче `_MIN_REASON` знаков), если линия или корпус не из закрытого
     списка, если запись дублирует уже существующую (тип+линия+корпус).
     Зовётся при импорте модуля — то есть при КАЖДОМ прогоне гейта и тестов;
  2. исключение НЕ прячет цифру: гейт печатает её отдельной видимой строкой
     (`gate.print_scope_exclusions`), а не заменяет нулём;
  3. исключение УЗКОЕ по построению: оно снимает тип с ОДНОЙ названной линии
     ОДНОГО корпуса. Все прочие линии (утечка, порча документа, границы,
     обратимость) и весь корпус v2 продолжают мерить тип полностью — это
     проверяется стражами `tests/test_scope_exclusions.py`, а не доверием.

Образец замка — `promote_baseline.py` (единственная санкционированная дорога к
движению планки: `--author` + `--reason`, запись в журнал). Разница в том, что
там решение записывается в журнал прогонов, а здесь — в код, потому что оно
действует на каждом будущем прогоне, а не однократно.
"""

#: Линии гейта, с которых вообще разрешено снимать тип. Закрытый список:
#: линия «б» (утечка ПДн) и линия «в» (обратимость) сюда не входят и не
#: войдут — исключить тип из измерения утечки значит перестать защищать данные.
LINES = {
    "а": "точность (precision по типу): TP на эталоне своего типа против FP на "
         "объявленном негативе",
    "FP": "условие 3: суммарное число масок, легших на объявленный негатив",
}

#: Корпуса, к которым применимо исключение.
CORPORA = {"v1", "v2"}

#: Обоснование короче этого — не обоснование, а отписка.
_MIN_REASON = 120


class ScopeExclusionError(SystemExit):
    """Ошибка манифеста исключений: текст — человеку, код возврата 1."""

    def __init__(self, msg):
        super().__init__("ОШИБКА МАНИФЕСТА ИСКЛЮЧЕНИЙ\n" + msg)


#: ЖУРНАЛ ИСКЛЮЧЕНИЙ. Дописывается только сверху вниз; запись не удаляется, а
#: закрывается (`closed`) — иначе история решений теряется ровно так же, как
#: терялась бы история движений планки.
EXCLUSIONS = [
    {
        "type": "CONTRACT_NO",
        "line": "а",
        "corpus": "v1",
        "date": "2026-08-08",
        "author": "владелец продукта",
        "stage": "V1-SCOPE",
        "reason": (
            "Корпус v1 размечен под определение «номер договора — не "
            "персональные данные» и заморожен навсегда. Владелец принял "
            "обратное решение: номер договора маскируется. Детектор работает "
            "верно, разметка отражает противоположное определение — 315 "
            "«ложных» срабатываний это столкновение двух определений, а не "
            "ошибка детектора. Мерить новый тип разметкой, сделанной под "
            "другое определение, — измерение негодным прибором. Тип "
            "исключается из точности v1 явно, с этой записью; на корпусе v2 "
            "меряется полностью."
        ),
        # Число на дату решения. Хранится, чтобы отчёт печатал не только «тип
        # исключён», но и ЦЕНУ исключения, и чтобы расхождение с фактическим
        # счётом было видно (см. gate.print_scope_exclusions).
        "known_count": 315,
        "closed": None,
    },
]

#: ЭТАП MARKUP-V2 (2026-08-09, владелец). Разметка корпуса v2 (не заморожена,
#: в отличие от v1) реклассифицирована под то же решение владельца: записи
#: DOCNUM (номер договора) в `tests/corpus_v2/gold_v2.json` перенесены из
#: `negatives` в `entities` (`tests/corpus_v2/values.py::docnum`), точность
#: CONTRACT_NO на v2 с этого момента меряется ПО НОВОЙ (правильной) разметке
#: без какого-либо исключения — это не запись в EXCLUSIONS, а фиксация факта,
#: что для v2 исключение никогда не требовалось и не появится: корпус v2
#: не заморожен и меняется вместе с решением владельца.
#: ИСКЛЮЧЕНИЕ ПО v1 ВЫШЕ (line="а", corpus="v1") ЭТИМ НЕ ЗАТРОНУТО и остаётся
#: постоянным — v1 заморожен навсегда со старым определением, см. reason выше.


def validate(records=None):
    """ЗАМОК. Роняет сборку на неполной или подозрительной записи.

    Зовётся при импорте (ниже) — значит на каждом прогоне гейта и на каждом
    прогоне тестов. Добавить исключение «по-тихому» нельзя: без автора и
    обоснования модуль не импортируется, а без модуля не запускается гейт.
    """
    records = EXCLUSIONS if records is None else records
    seen = set()
    for i, r in enumerate(records):
        where = "запись №%d (%s)" % (i + 1, r.get("type") or "без типа")
        if not r.get("type"):
            raise ScopeExclusionError(
                "%s: не указан тип. Исключение всегда именное — «какой-нибудь "
                "шумный тип» исключать нельзя." % where)
        if r.get("line") not in LINES:
            raise ScopeExclusionError(
                "%s: линия «%s» не из закрытого списка %s. Линия «б» (утечка) и "
                "линия «в» (обратимость) в списке отсутствуют НАМЕРЕННО: снять "
                "тип с измерения утечки — значит перестать защищать данные."
                % (where, r.get("line"), sorted(LINES)))
        if r.get("corpus") not in CORPORA:
            raise ScopeExclusionError(
                "%s: корпус «%s» неизвестен (%s)." % (where, r.get("corpus"),
                                                      sorted(CORPORA)))
        if not r.get("date"):
            raise ScopeExclusionError("%s: нет даты решения." % where)
        if not (r.get("author") or "").strip():
            raise ScopeExclusionError(
                "%s: НЕТ АВТОРА. Исключение типа из линии гейта — решение, у "
                "решения есть тот, кто его принял. Тот же порядок, что у "
                "promote_baseline.py (--author)." % where)
        reason = (r.get("reason") or "").strip()
        if len(reason) < _MIN_REASON:
            raise ScopeExclusionError(
                "%s: НЕТ ОБОСНОВАНИЯ (или оно короче %d знаков, сейчас %d). "
                "Напишите, ПОЧЕМУ разметка негодна для этого типа, — иначе "
                "через три этапа сюда уедет всё неудобное. Тот же порядок, "
                "что у promote_baseline.py (--reason)."
                % (where, _MIN_REASON, len(reason)))
        key = (r["type"], r["line"], r["corpus"])
        if key in seen:
            raise ScopeExclusionError(
                "%s: повтор записи %s. Одно исключение — одна запись; вторая "
                "означала бы, что первую переписали, не убрав." % (where, key))
        seen.add(key)
    return records


def active(line, corpus):
    """Записи, действующие на этой линии этого корпуса (закрытые — не в счёт)."""
    return [r for r in EXCLUSIONS
            if r["line"] == line and r["corpus"] == corpus and not r.get("closed")]


def excluded_types(line, corpus):
    """Множество имён типов, снятых с линии. Ровно это множество и пропускает
    гейт — ни типом больше."""
    return {r["type"] for r in active(line, corpus)}


validate()
