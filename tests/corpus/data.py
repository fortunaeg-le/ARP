def _sur_forms(sur, gender):
    if gender == "m":
        if sur.endswith(("ов", "ев", "ёв", "ин", "ын")):
            return dict(gen=sur + "а", dat=sur + "у", ins=sur + "ым")
        if sur.endswith("ий"):
            return dict(gen=sur[:-2] + "ого", dat=sur[:-2] + "ому", ins=sur[:-2] + "им")
        # согласная (Мороз, Коваль, Кисель, Дед, Мельник)
        if sur.endswith("ь"):
            return dict(gen=sur[:-1] + "я", dat=sur[:-1] + "ю", ins=sur[:-1] + "ем")
        return dict(gen=sur + "а", dat=sur + "у", ins=sur + "ом")
    else:
        if sur.endswith("а") and sur[-2:] in ("ва", "на"):
            return dict(gen=sur[:-1] + "ой", dat=sur[:-1] + "ой", ins=sur[:-1] + "ой")
        if sur.endswith("а"):  # Синица, Сорока — не склоняем по-адъективному
            return dict(gen=sur[:-1] + "ы", dat=sur[:-1] + "е", ins=sur[:-1] + "ой")
        return dict(gen=sur, dat=sur, ins=sur)


def make_person(rnd, gender=None, exotic=False, word_surname=False):
    if exotic:
        p = dict(rnd.choice(EXOTIC))
        p["exotic"] = True
        return p
    gender = gender or rnd.choice(["m", "f"])
    if word_surname:
        sur = rnd.choice(WORD_SUR_M if gender == "m" else WORD_SUR_F)
    else:
        sur = rnd.choice(M_SUR if gender == "m" else F_SUR)
    if gender == "m":
        nm, pt = rnd.choice(M_NAME), rnd.choice(M_PATR)
        ng, nd, ni = _M_NAME_GEN[nm], _M_NAME_DAT[nm], _M_NAME_INS[nm]
        pg, pd, pi = pt + "а", pt + "у", pt + "ем"
    else:
        nm, pt = rnd.choice(F_NAME), rnd.choice(F_PATR)
        ng, nd, ni = _F_NAME_GEN[nm], _F_NAME_DAT[nm], _F_NAME_INS[nm]
        pg, pd, pi = pt[:-1] + "ы", pt[:-1] + "е", pt[:-1] + "ой"
    sf = _sur_forms(sur, gender)
    return dict(
        nom="%s %s %s" % (sur, nm, pt),
        gen="%s %s %s" % (sf["gen"], ng, pg),
        dat="%s %s %s" % (sf["dat"], nd, pd),
        ins="%s %s %s" % (sf["ins"], ni, pi),
        short="%s %s. %s." % (sur, nm[0], pt[0]),
        short_tight="%s.%s.%s" % (nm[0], pt[0], sur),
        initials="%s. %s. %s" % (nm[0], pt[0], sur),
        sur=sur, name=nm, patr=pt, gender=gender, exotic=False,
    )


