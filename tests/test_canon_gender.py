# -*- coding: utf-8 -*-
"""Канон ФИО и род (`MFIX-CANON-FEMSURN`, решение владельца).

Восстановление подставляет КАНОН сущности. Канон строился так: взять разбор с
наибольшим score и склонить в именительный. Женская фамилия в именительном
омонимична мужской в родительном, разбор «Кузнецова» отдаёт `masc,gent` со
score 0.5 против верного `femn,nomn` со score 0.333 — и канон получался
«Кузнецов». Пользователь получал восстановленный документ, где женщина названа
мужской фамилией: это порча имени стороны сделки.

Тесты держат обе стороны правила: женское не превращается в мужское И
склонение косвенных форм не отключилось заодно (первая редакция починки ровно
это и сломала — «Марии» разбирается как именительный МНОЖЕСТВЕННОГО).
"""
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))

import anchor_registry as AR  # noqa: E402


def canon(text):
    _s, _n, _p, _i, c = AR._per_signature(text)
    return " ".join(x for x in (c.get("surn"), c.get("name"), c.get("patr")) if x)


@pytest.mark.parametrize("text, expected", [
    # СУТЬ НАХОДКИ: женская фамилия остаётся женской
    ("Кузнецова Мария Дмитриевна", "Кузнецова Мария Дмитриевна"),
    ("Петрова Анна Ивановна", "Петрова Анна Ивановна"),
    # ЗЕРКАЛО: склонение косвенных форм работает по-прежнему
    ("Кузнецовой Марии Дмитриевне", "Кузнецова Мария Дмитриевна"),
    ("Новиковой Ольги Егоровны", "Новикова Ольга Егоровна"),
    ("Петровой Анны Ивановны", "Петрова Анна Ивановна"),
    # мужские формы не задеты ни в прямой, ни в косвенной
    ("Смирнов Артём Сергеевич", "Смирнов Артём Сергеевич"),
    ("Беляеву Олегу Олеговичу", "Беляев Олег Олегович"),
])
def test_canon_keeps_the_person(text, expected):
    assert canon(text) == expected


def test_case_normalized_form_gives_the_same_canon():
    """Строчная форма (регистровая нормализация) даёт тот же канон — иначе
    один человек получил бы два разных имени при восстановлении."""
    assert canon("кузнецовой марией дмитриевной") == "Кузнецова Мария Дмитриевна"


def test_gender_comes_from_name_and_patronymic_not_from_surname():
    """Род спана берётся у имени/отчества: ради фамилии всё и считается."""
    assert AR._span_gender("Кузнецова Мария Дмитриевна") == "femn"
    assert AR._span_gender("Беляев Олег Олегович") == "masc"
    # только фамилия и инициалы — рода нет, догадка хуже воздержания
    assert AR._span_gender("Иванова И. И.") is None


def test_nominative_singular_is_left_alone_but_plural_is_not():
    """Правило «уже именительный — не склоняем» обязано требовать ЕДИНСТВЕННОГО
    числа. Без этого «Марии» (именительный мн. ч.) осталось бы «Марии»."""
    assert AR._nominative_word("Кузнецова", "surn", "femn") == "Кузнецова"
    assert AR._nominative_word("Марии", "name", "femn") == "Мария"
    assert AR._nominative_word("Егоровны", "patr", "femn") == "Егоровна"


def test_price_of_the_rule_is_stated_not_hidden():
    """ЦЕНА ПРАВИЛА, названная владельцем в решении. Без подсказки рода
    «Иванова» (родительный от мужской «Иванов») остаётся «Иванова». Владелец
    выбрал эту сторону: женская именительная форма не должна проигрывать
    мужской родительной. Тест держит факт на виду, а не прячет его."""
    assert AR._nominative_word("Иванова", "surn", None) == "Иванова"
    # с подсказкой рода омонимия снимается в обе стороны
    assert AR._nominative_word("Иванова", "surn", "masc") == "Иванов"
    assert AR._nominative_word("Иванова", "surn", "femn") == "Иванова"
