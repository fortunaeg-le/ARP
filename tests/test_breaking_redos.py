"""Этап 3 (BREAKING) — попытка СЛОМАТЬ систему, а не добрать граничных случаев.

Направление 4/5: очень длинная строка / DoS по времени обработки regex.

Находка B1 (КРИТИЧНО, полный отказ): паттерн SUM из entity_types.yaml
    \\d[\\d  ]*[.,]?\\d*\\s?(руб...|USD|...)
содержит два перекрывающихся квантификатора по одному и тому же классу цифр
(`[\\d  ]*` и `\\d*`, оба матчат \\d). На длинной строке цифр/пробелов БЕЗ
завершающего слова валюты движок re уходит в супер-линейный (квадратичный и хуже)
перебор разбиений. Это ReDoS на стороне ENCRYPT: detect_regex гоняет этот паттерн
по КАЖДОМУ сегменту, поэтому одна длинная числовая строка в документе подвешивает
`encrypt` на десятки секунд (а строка в несколько МБ — практически навсегда),
без вывода и без ошибки. Реальный триггер: пользователь скармливает документ, где
в одну строку попал длинный числовой блок (выгрузка, склеенная таблица чисел,
испорченная OCR-строка, вставленный длинный ID/номер).

НЕ дублирует этап 1/2 и FINDINGS.md (там ReDoS не рассматривался).
Тесты кода не чинят — только воспроизводят дефект.
"""
import time

import pytest

from extractor import extract
from regex_detector import detect_regex

CONFIG = None  # заполняется фикстурой config_path через аргумент теста


def _detect_time(text, tmp_path, config_path):
    """Прогоняет regex-детектор по .txt из одной строки `text`, возвращает секунды."""
    p = tmp_path / "long.txt"
    p.write_text(text, encoding="utf-8")
    doc = extract(str(p))
    t0 = time.perf_counter()
    detect_regex(doc, config_path)
    return time.perf_counter() - t0


# --------------------------------------------------------------------------- #
# B1 — КРИТИЧНО: ReDoS в паттерне SUM подвешивает encrypt на длинной числовой
#      строке. Корректная (линейная) реализация обрабатывает такую строку за
#      миллисекунды; 2.0 с — запас в сотни раз. Сейчас ~1000 цифр это НЕ
#      укладывается (эмпирически ~5 с), поэтому тест помечен xfail(strict).
# --------------------------------------------------------------------------- #
class TestSumRegexReDoS:
    def test_long_digit_line_encrypt_finishes_in_budget(self, tmp_path, config_path):
        """1000 цифр в одну строку. Корректно (после B1-фикса): детект < 2 c.

        РЕГРЕСС-СТРАЖ ReDoS: паттерн SUM переписан без перекрытия квантификаторов
        (целая часть [\\d ]*+ possessive/атомарна, дробная ([.,]\\d+)? начинается с
        разделителя), поэтому катастрофического перебора нет — на 1000 цифр детект
        занимает единицы миллисекунд. Порог 2.0 c даёт запас в сотни раз: если в
        будущем паттерн опять станет уязвим к ReDoS, тест сразу упадёт по времени,
        а не только при ручном замере. Используем time.monotonic() (не зависит от
        подстроек системных часов) для измерения именно интервала."""
        line = "Итого " + ("1" * 1000) + " конец"
        p = tmp_path / "long.txt"
        p.write_text(line, encoding="utf-8")
        doc = extract(str(p))
        t0 = time.monotonic()
        detect_regex(doc, config_path)
        elapsed = time.monotonic() - t0
        assert elapsed < 2.0, f"detect_regex занял {elapsed:.2f} c на 1000-значной строке (ReDoS-регресс)"

    def test_large_digit_line_stays_fast(self, tmp_path, config_path):
        """До B1-фикса этот тест доказывал СУПЕР-линейность (удвоение длины давало
        рост x7-8 — хуже квадратичного, признак ReDoS). После фикса перекрытия
        квантификаторов больше нет, поэтому тест перевёрнут в свою противоположность:
        даже крупный числовой блок (4000 цифр) обрабатывается практически мгновенно.
        Абсолютный порог на большом входе — устойчивый (не флакующий) индикатор того,
        что комбинаторный перебор не вернулся: при ReDoS 4000 цифр висели бы минуты."""
        line = "1" * 4000
        elapsed = _detect_time(line, tmp_path, config_path)
        assert elapsed < 2.0, (
            f"detect_regex занял {elapsed:.2f} c на 4000-значной строке — "
            "признак возврата супер-линейного перебора (ReDoS-регресс)"
        )


# --------------------------------------------------------------------------- #
# Контроль: НОРМАЛЬНАЯ денежная сумма (с валютой) детектится мгновенно — чтобы
# было видно, что тормозит именно патологический вход без слова валюты, а не
# регулярка вообще.
# --------------------------------------------------------------------------- #
class TestNormalSumIsFast:
    def test_real_money_sum_is_instant(self, tmp_path, config_path):
        line = "Стоимость работ составляет 1 000 000 руб без НДС"
        elapsed = _detect_time(line, tmp_path, config_path)
        assert elapsed < 0.5, f"нормальная сумма детектится за {elapsed:.3f}c"
