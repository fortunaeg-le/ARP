def _masks_of(text, wanted):
    seg = TextSegment(id="s0", text=text, source_type="txt_line", metadata={})
    doc = SourceDocument(segments=[seg], source_format="txt", source_path="<addrb>")
    ents = run_detection(doc, _CFG)
    _anon, final = tokenize(doc, ents, _CFG)
    return [e.original_text for e in final if e.entity_type == wanted]


def test_plus_clean_birthdate_is_still_detected():
    """Контроль к xfail ниже: на неиспорченной дате детектор работает — значит
    красный сосед именно про омоглифы, а не про сломанный BIRTHDATE вообще."""
    assert _masks_of("Дата рождения: 21.01.1960", "BIRTHDATE") == ["21.01.1960"]


@pytest.mark.xfail(
    strict=True,
    reason="ОБНАЖЁННАЯ ДЫРА этапа ADDR-B (класс B4/Stage4-B, нормализатор). Дата "
           "рождения с кириллическими омоглифами вместо цифр («21.0І.196О») "
           "детектором BIRTHDATE не берётся: нормализатор НАМЕРЕННО не сводит "
           "одиночные буквы внутри чисел (защита «кв. 2б»). До этапа значение "
           "случайно пряталось под ПЕРЕБОРОМ адреса — жадный ADDRESS-спан "
           "перелезал через перенос строки, съедал метку «Дата рождения:» и "
           "закрывал дату. Убрав перебор, этап обнажил дыру: services_0001__"
           "m1337_combo, +1 к leak_v2 BIRTHDATE. Снять метку, когда нормализатор "
           "научится сводить омоглифы в датах.",
)
def test_birthdate_with_homoglyphs_is_masked():
    assert _masks_of("Дата рождения: 21.0І.196‍О", "BIRTHDATE")


