# -*- coding: utf-8 -*-
"""Этап ADDR-B — границы адресных масок, ЗЕРКАЛА обеих сторон.

ЦЕНА ДВУХ ОШИБОК РАЗНАЯ, и тесты здесь разделены по ней же:

  НЕДОБОР  (маска КОРОЧЕ эталона) — часть адреса осталась открытым текстом.
           Это утечка ПДн. Тесты (+): маска ОБЯЗАНА закрыть названный кусок.
  ПЕРЕБОР  (маска ДЛИННЕЕ эталона) — захвачен лишний текст. Документ читается
           хуже, данные защищены. Тесты (−): маска обязана НЕ захватывать метку
           поля / не разрастаться от новых правил.

Без второй половины первая — приглашение «маскировать всё подряд»: расширить
границы так, чтобы недобор упал, тривиально, и без зеркал (−) правка выглядела
бы улучшением. Поэтому каждый механизм этапа проверен с обеих сторон.
"""
import os

import pytest

import ner_detector as ND
from models import SourceDocument, TextSegment
from pipeline import run_detection
from tokenizer import tokenize

_CFG = os.path.join(os.path.dirname(__file__), "..", "entity_types.yaml")


def _addr_masks(text: str):
    """Тексты ADDRESS-масок, которые система реально поставит на строке."""
    seg = TextSegment(id="s0", text=text, source_type="txt_line", metadata={})
    doc = SourceDocument(segments=[seg], source_format="txt", source_path="<addrb>")
    ents = run_detection(doc, _CFG)
    _anon, final = tokenize(doc, ents, _CFG)
    return [e.original_text for e in final if e.entity_type == "ADDRESS"]


def _covers(text: str, part: str) -> bool:
    return any(part in m for m in _addr_masks(text))


# ===========================================================================
#  Механизм 1. АББРЕВИАТУРА = усечение полного адресного слова
# ===========================================================================

class TestAbbrevRule:
    """Правило, а не список: токен с точкой, являющийся строгим началом полного
    адресного слова, — тот же маркер, что это слово."""

    @pytest.mark.parametrize("abbrev,cat", [
        ("бул", "street"),        # бульвар
        ("просп", "street"),      # проспект
        ("шос", "street"),        # шоссе
        ("пло", "street"),        # площадь
        ("рай", "locality"),      # район
        ("хут", "locality"),      # хутор
        ("зда", "premise"),       # здание
        ("квар", "premise"),      # квартира (и квартал — категория первой находки)
    ])
    def test_plus_truncation_is_recognised(self, abbrev, cat):
        assert ND._addr_abbrev_cat(abbrev) is not None
        # категорию проверяем мягко: «квар» — начало и «квартиры», и «квартала»
        assert ND._addr_abbrev_cat(abbrev) in ("street", "premise", "locality")

    @pytest.mark.parametrize("word", [
        "тел", "руб", "экз", "прил", "прим", "изм", "согл",
        "см", "рф", "им",          # реальные двухбуквенные сокращения корпуса
    ])
    def test_minus_ordinary_abbreviation_is_not_a_marker(self, word):
        """(−) Обычные сокращения делового текста маркерами НЕ становятся —
        иначе правило превратилось бы в «любое слово с точкой — адрес»."""
        assert ND._addr_abbrev_cat(word) is None

    @pytest.mark.parametrize("short", ["у", "т", "к", "г", "д"])
    def test_minus_one_letter_stays_on_the_explicit_list(self, short):
        """(−) Однобуквенные огрызки правилу НЕ подчиняются: «т.», «у.», «к.» —
        это и предлог, и инициал, и «т. е.». Они живут на явном списке, где у
        каждого своё условие («д.» перед числом — дом, перед именем — деревня)."""
        assert ND._addr_abbrev_cat(short) is None

    def test_minus_dot_is_required(self):
        """(−) Без точки это обычное слово, а не аббревиатура."""
        assert ND._addr_dotted_abbrev_cat("бул") is None
        assert ND._addr_dotted_abbrev_cat("бул.") == "street"

    def test_minus_full_word_is_not_its_own_truncation(self):
        """(−) Усечение строгое: полное слово правилом не «подтверждается»
        повторно (полные слова и так в наборах)."""
        assert ND._addr_abbrev_cat("бульвар") is None
        assert ND._addr_abbrev_cat("проспект") is None

    @pytest.mark.parametrize("text,address", [
        ("630099, Республика Татарстан, г. Новосибирск, бул. Кутузовский, вл. 69",
         "630099, Республика Татарстан, г. Новосибирск, бул. Кутузовский, вл. 69"),
        ("603000, Тверская обл., г. Нижний Новгород, просп. Ленина, вл. 7",
         "603000, Тверская обл., г. Нижний Новгород, просп. Ленина, вл. 7"),
        ("Адрес: просп. Кирова, д. 57, с. Ивановское",
         "просп. Кирова, д. 57, с. Ивановское"),
    ])
    def test_plus_address_is_closed_whole(self, text, address):
        """(+) НЕДОБОР. До этапа точка в «бул.»/«просп.» читалась как конец
        предложения, спан рвался НАДВОЕ, и одна из половин (индекс+город ИЛИ
        улица+дом) оставалась ОТКРЫТОЙ. Проверяем именно ЦЕЛОСТНОСТЬ: маска
        обязана закрыть адрес одним куском, а не «хоть чем-то попасть»."""
        assert _covers(text, address), _addr_masks(text)


# ===========================================================================
#  Механизм 2. Обрезка краёв не режет сквозь «а/я»
# ===========================================================================

class TestPoBox:

    @pytest.mark.parametrize("text", [
        "а/я 27, г. Одинцово, 143000",
        "А/Я 70, г. Красногорск, 143400",
        "а/я 44, г. Нижний Новгород, 603000",
    ])
    def test_plus_po_box_is_inside_the_mask(self, text):
        """(+) НЕДОБОР. «а» и «я» — два односимвольных слова, обрезка краёв
        принимала их за метку и снимала. Номер ящика — часть адреса."""
        assert _covers(text, text.split(",")[0]), _addr_masks(text)

    def test_minus_label_before_po_box_is_still_stripped(self):
        """(−) ПЕРЕБОР. Защита ящика не должна вернуть метку поля: режем ДО «а/я»,
        а не до начала спана."""
        masks = _addr_masks("Почтовый адрес: а/я 27, г. Одинцово, 143000")
        assert masks and all("адрес" not in m for m in masks), masks
        assert any(m.lower().startswith("а/я") for m in masks), masks


# ===========================================================================
#  Механизм 3. Хвостовая точка принадлежит аббревиатуре, а не предложению
# ===========================================================================

class TestTrailingDot:

    def test_plus_abbreviation_keeps_its_dot(self):
        """(+) НЕДОБОР (границы, не утечка): эталон «…, Московская обл.» содержит
        точку, а маска обрывалась на «обл» — masking B считала эталон незакрытым."""
        masks = _addr_masks("Московская обл., г. Химки, ул. Мира, д. 7, Московская обл.")
        assert masks and masks[0].rstrip().endswith("обл."), masks

    def test_minus_sentence_dot_after_house_number_stays_outside(self):
        """(−) ПЕРЕБОР. Точка после НОМЕРА — конец предложения, а не часть
        аббревиатуры; захватывать её нельзя (иначе правило станет «глотаем любую
        точку справа»)."""
        masks = _addr_masks("Адрес: г. Химки, ул. Мира, д. 7. Стороны договорились.")
        assert masks, masks
        assert not masks[0].rstrip().endswith("7."), masks
        assert all("Стороны" not in m for m in masks), masks


# ===========================================================================
#  Механизм 4. Двоеточие — конец метки поля
# ===========================================================================

class TestLabelCut:

    # Метка попадает в спан НЕ на изолированной строке (там левое расширение
    # упирается в строчное «адрес:»), а в МНОГОСТРОЧНОЙ ячейке реквизитов, где
    # сырой кандидат NER/yargy начинается прямо с заглавной метки. Тест
    # воспроизводит именно эту форму — иначе он «зелёный» и без правки.
    _CELL = ("ООО «Атлант»\n{label}Москва, Мира 68\n"
             "Почтовый адрес: Химки Баумана 75/3 кв 69\nИНН 0763201410")

    @pytest.mark.parametrize("label", [
        "Юридический адрес: ", "Юридический Адрес: ", "Место нахождения: ",
    ])
    def test_minus_label_is_not_captured(self, label):
        """(−) ПЕРЕБОР. Метка с ЗАГЛАВНОЙ буквы выглядела для обрезки краёв
        топонимом и попадала в маску (35 масок корпуса)."""
        masks = _addr_masks(self._CELL.format(label=label))
        assert masks, masks
        assert all(":" not in m for m in masks), masks
        assert any("Химки Баумана 75/3 кв 69" in m for m in masks), masks

    def test_plus_cut_never_destroys_the_address(self):
        """(+) НЕДОБОР. Если после двоеточия якоря не остаётся, спан НЕ режем:
        потеря детекции дороже лишней метки."""
        text = "Адрес: г. Химки, ул. Мира, д. 7"
        assert _covers(text, "ул. Мира, д. 7"), _addr_masks(text)

    def test_minus_address_itself_has_no_colon(self):
        """(−) Основание правила: двоеточие в САМОМ адресе не встречается.
        Тест сторожит допущение — если в эталоне появится адрес с двоеточием,
        правило придётся пересмотреть, а не молча резать значение."""
        import json
        gold_path = os.path.join(os.path.dirname(__file__), "corpus", "gold.json")
        with open(gold_path, encoding="utf-8") as f:
            gold = json.load(f)
        with_colon = [e["text"] for d in gold for e in d["entities"]
                      if e["type"] == "ADDRESS" and ":" in e["text"]]
        assert not with_colon, with_colon[:5]


# ===========================================================================
#  Механизм 5. Маркер требует значения (регистр значения не решает)
# ===========================================================================

class TestMarkerNeedsItsValue:

    # Каждый пример ФАЛЬСИФИЦИРОВАН: при отключённом правиле маска обрывается на
    # «пом.», теряет «просп. ленинградская» слева либо не ставится вовсе (у спана
    # без строчного названия улицы не набирается сильный якорь).
    @pytest.mark.parametrize("text,tail", [
        ("141400, московская обл., г. химки, пер. тверская, вл. 83, стр. 2, пом. vii",
         "пом. vii"),
        ("просп. ленинградская, д. 72, г. Нижний Новгород",
         "просп. ленинградская"),
        ("г. химки, пер. тверская, вл. 83", "пер. тверская, вл. 83"),
    ])
    def test_plus_lowercase_value_belongs_to_its_marker(self, text, tail):
        """(+) НЕДОБОР. Классификация края смотрела на РЕГИСТР, поэтому на
        документе с испорченным регистром адрес рвался посреди конструкции
        «тип + значение»: «пом.» без своего номера, «просп.» без названия улицы."""
        assert _covers(text, tail), _addr_masks(text)

    def test_minus_only_one_token_is_taken(self):
        """(−) ПЕРЕБОР. Маркер требует ОДНОГО значения, а не хвоста прозы."""
        masks = _addr_masks("г. Химки, ул. мира подписан сторонами договора")
        assert masks, masks
        assert all("подписан" not in m for m in masks), masks

    def test_minus_comma_ends_the_component(self):
        """(−) ПЕРЕБОР. Запятая заканчивает компонент адреса: слово ЗА запятой
        уже не значение предыдущего маркера."""
        text = "г. Химки, ул, отгрузка товара покупателю"
        end = text.index("ул") + 2
        assert ND._expand_addr_right(text, end) == end, text[end:]

    def test_minus_left_side_does_not_grab_prose(self):
        """(−) ПЕРЕБОР, левый край. Строчное слово впитывается, только если
        ВПЛОТНУЮ слева от него стоит адресное типовое слово."""
        text = "услуги по договору ул. Мира, д. 5"
        start = text.index("Мира")
        assert ND._expand_addr_left(text, start) == text.index("ул.")


