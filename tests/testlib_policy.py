# -*- coding: utf-8 -*-
"""ЭТАП T1 — вспомогательное для тестов: пришпилить набор типов «Максимум».

ОТДЕЛЬНЫЙ модуль, а не функция в `tests/conftest.py`, по конкретной причине:
в проекте ДВА conftest.py (корневой и `tests/`), и при полном прогоне
`import conftest` из теста отдаёт КОРНЕВОЙ (он импортируется первым и занимает
имя `conftest` в sys.modules) — помощник «пропадал» с AttributeError, хотя при
запуске одного файла всё работало. Уникальное имя модуля эту ловушку снимает.
"""
import json
from pathlib import Path


def pin_all_types(home_dir):
    """Записать в подменённый HOME файл настроек с набором «Максимум».

    С этапа T1 набор ПО УМОЛЧАНИЮ — «только персональные данные»: реквизиты
    (ИНН/ОГРН/КПП/БИК/счета) и организации найдены, но не маскируются. Тест,
    который спрашивает «замаскировался ли ИНН», спрашивает про ДЕТЕКТОР, а не
    про настройку пользователя, и потому обязан задать набор явно — иначе он
    молча начнёт мерить умолчание (та же причина, по которой замер и гейт зовут
    токенизацию с `type_policy.MAXIMUM`, см. tests/corpus/run_measurement.py).

    Пришпиливание идёт через НАСТОЯЩИЙ файл настроек, а не через хук в коде:
    тест обязан ходить тем же путём, что пользователь.
    """
    d = Path(home_dir) / ".shifrator"
    d.mkdir(parents=True, exist_ok=True)
    path = d / "settings.json"
    path.write_text(json.dumps({"profile": "maximum"}), encoding="utf-8")
    return path
