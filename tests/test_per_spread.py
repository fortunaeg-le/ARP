# -*- coding: utf-8 -*-
"""Этап PER-SPREAD — распространение НАЙДЕННОЙ фамилии на прочие её упоминания.

Механизм распространения (реестр документа + проход 2 по леммам) существовал с
этапа B; этап чинит ТРИ его разрыва, из-за которых человек оставался открыт:

  F1 «слот фамилии» — фамилии-омониму нарицательного (Синица, Пчела, Коваль,
     Кисель, Мельник, Белка) и иностранной (Ким) pymorphy не даёт пометы `Surn`,
     ключа реестра нет, и человек открыт ВО ВСЕХ упоминаниях сразу. Слот фамилии
     определяется ПОЗИЦИОННО — слово вплотную СЛЕВА от пары «имя + отчество».
  F2 «голая фамилия в ячейке» — сегмент, состоящий целиком из зарегистрированной
     фамилии, отвергался проверкой «начало предложения».
  F3 «перебег прогона» — спан ФИО перебегал через перенос строки на СЛЕДУЮЩУЮ
     фамилию, оставляя её имя и отчество открытыми.

Тесты держат и ВЫИГРЫШ, и ЦЕНУ: рядом с каждым «стало закрыто» стоит проба на
ложное срабатывание, потому что цена правки — именно ложные маски.
"""
import os
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_SRC = os.path.join(_ROOT, "src")
if _SRC not in sys.path:
    sys.path.insert(1, _SRC)

from models import SourceDocument, TextSegment  # noqa: E402
from pipeline import run_detection  # noqa: E402

_CFG = os.path.join(_ROOT, "entity_types.yaml")


def _detect(text):
    """Каждая непустая строка — отдельный сегмент (как .txt-извлечение)."""
    segs = [
        TextSegment(id="l%d" % i, text=line, source_type="txt_line", metadata={})
        for i, line in enumerate(text.split("\n")) if line.strip()
    ]
    doc = SourceDocument(segments=segs, source_format="txt", source_path="<t>")
    return run_detection(doc, _CFG)


def _per(ents):
    return [e.original_text for e in ents if e.entity_type == "PERSON"]


def _masked(ents, fragment):
    return any(fragment in e.original_text for e in ents
               if e.entity_type == "PERSON")


# --------------------------------------------------------------------------- #
#            F1 — слот фамилии: человек, чью фамилию не метит морфология        #
# --------------------------------------------------------------------------- #
_SINICA = (
    "ДОГОВОР ОКАЗАНИЯ УСЛУГ\n"
    "ООО «Логистик Групп», именуемое в дальнейшем «Агент», в лице генерального "
    "директора Синицы Татьяны Михайловны, действующего на основании устава, "
    "с одной стороны, заключили настоящий договор.\n"
    "Уполномоченный представитель: Синица Татьяна Михайловна\n"
    "Агент: Т. М. Синица\n"
    "Подписи сторон: _______________ /Синица Т. М./\n"
)


def test_f1_surname_without_morph_tag_is_anchored_and_spread():
    """Фамилия-омоним нарицательного («синица») не имеет пометы Surn, но стоит в
    слоте перед парой «имя + отчество» — человек закрывается ЦЕЛИКОМ: и полное
    ФИО в косвенном падеже, и «Имя-инициалы + фамилия», и «фамилия + инициалы»."""
    ents = _detect(_SINICA)
    per = _per(ents)
    assert any("Синицы Татьяны Михайловны" in p for p in per), per
    assert any("Синица Татьяна Михайловна" in p for p in per), per
    assert any("Т. М. Синица" in p for p in per), per
    assert any("Синица Т. М." in p for p in per), per


def test_f1_all_caps_fio_uses_the_slot_too():
    """ALL-CAPS-запись ФИО — тот же слот: регистр кандидата СОГЛАСОВАН с прогоном."""
    ents = _detect(
        "ОТВЕТСТВЕННЫЙ: КИСЕЛЬ ЕГОР ПЕТРОВИЧ\n"
        "Заёмщик: Кисель Е. П.\n"
    )
    assert _masked(ents, "КИСЕЛЬ ЕГОР ПЕТРОВИЧ"), _per(ents)


def test_f1_role_word_does_not_take_the_surname_slot():
    """ЦЕНА ПРАВКИ, проба 1. «в лице директора Ивана Ивановича» — фамилии в тексте
    НЕТ вовсе, слева стоит РОЛЬ. Роль в слот не пускается: замаскировать «директора»
    значило бы испортить документ пользователю."""
    ents = _detect(
        "ООО «Восход», в лице директора Ивана Ивановича, заключило договор.\n"
    )
    assert not _masked(ents, "директор"), _per(ents)
    assert not _masked(ents, "Директор"), _per(ents)


def test_f1_status_word_does_not_take_the_surname_slot():
    """ЦЕНА ПРАВКИ, проба 2. «Индивидуальный предприниматель Иван Иванович» —
    слева статус физлица, не фамилия."""
    ents = _detect("Индивидуальный предприниматель Иван Иванович, ИНН 366822495272\n")
    assert not _masked(ents, "предприниматель"), _per(ents)


def test_f1_orgform_word_does_not_take_the_surname_slot():
    """ЦЕНА ПРАВКИ, проба 3. Развёрнутая org-форма в слот не пускается."""
    ents = _detect("Общество Иван Иванович подписало акт.\n")
    assert not _masked(ents, "Общество"), _per(ents)


def test_f1_right_slot_is_not_taken():
    """ЦЕНА ПРАВКИ, проба 4. ПРАВЫЙ слот («Имя Отчество Фамилия») НЕ берётся: в
    карточке реквизитов справа от ФИО стоят названия соседних полей («Адрес
    регистрации», «Дата рождения»), и на замере корпуса правый слот дал 91 мусор
    против одной настоящей фамилии."""
    ents = _detect(
        "Агент: Волков Николай Михайлович Дата рождения: 21.05.1990\n"
        "Принципал: Беляев Олег Олегович Адрес регистрации: Казань, Лесная 5\n"
    )
    assert not _masked(ents, "Дата"), _per(ents)
    assert not _masked(ents, "Адрес"), _per(ents)


def test_f1_street_namesake_is_not_a_person():
    """ЦЕНА ПРАВКИ, проба 5. Адресный тип-маркер слева — улица-однофамилец."""
    ents = _detect("Адрес: ул. Мельник Иван Иванович не проживает.\n")
    assert not _masked(ents, "ул. Мельник"), _per(ents)


# --------------------------------------------------------------------------- #
#                 F2 — голая фамилия, занимающая сегмент ЦЕЛИКОМ               #
# --------------------------------------------------------------------------- #
def test_f2_bare_registered_surname_alone_in_a_cell_is_masked():
    """Ячейка вложенной таблицы, состоящая ЦЕЛИКОМ из фамилии, — карточка
    реквизитов, а не начало предложения прозы. Фамилия в реестре, все прочие её
    упоминания закрыты, а эта уходила открытой (labor_0004, сегмент t1_r1_c0)."""
    ents = _detect(
        "Работник: Беляев Владимир Олегович, паспорт 43 15 415582\n"
        "Беляев\n"
    )
    assert sum(1 for p in _per(ents) if p.strip() == "Беляев") == 1, _per(ents)


def test_f2_sentence_start_homonym_is_still_not_masked():
    """ЦЕНА ПРАВКИ, проба 6. Послабление УЗКОЕ: одиночное слово в начале
    ПРЕДЛОЖЕНИЯ (а не в отдельном сегменте) по-прежнему не метится — иначе
    «Мороз ударил ночью» стало бы человеком."""
    ents = _detect(
        "Исполнитель: Мороз Иван Петрович, паспорт 43 15 415582\n"
        "Мороз ударил ночью, и работы были приостановлены.\n"
    )
    assert not any(p.strip() == "Мороз" for p in _per(ents)), _per(ents)


# --------------------------------------------------------------------------- #
#                    F3 — прогон ФИО не перебегает на соседа                   #
# --------------------------------------------------------------------------- #
def test_f3_run_stops_before_the_next_surname():
    """Две подряд идущие записи одного человека в ячейке: спан не имеет права
    захватить фамилию ВТОРОЙ записи, оставив её имя и отчество открытыми."""
    ents = _detect("Кузнецова Татьяна Сергеевна Кузнецова Татьяна Сергеевна\n")
    per = _per(ents)
    assert per, per
    assert all("Сергеевна Кузнецова" not in p for p in per), per
    assert sum(1 for p in per if p.strip() == "Кузнецова Татьяна Сергеевна") == 2, per


def test_f3_ambiguous_token_does_not_cut_a_real_fio():
    """ЦЕНА ПРАВКИ, проба 7. «Роман» несёт пометы и Name, и Surn. Обрыв прогона
    на таком токене распустил бы «Макаров Роман Дмитриевич» на «Роман Дмитриевич»
    и завёл бы в реестре ключ ('роман',) — поймано сравнением реестров до/после."""
    ents = _detect(
        "Арендатор: Макаров Роман Дмитриевич, паспорт 43 15 415582\n"
    )
    assert any(p.strip() == "Макаров Роман Дмитриевич" for p in _per(ents)), _per(ents)


def test_f3_double_surname_in_one_token_survives():
    """Дефисная двойная фамилия — ОДИН токен, обрывом её не задеть."""
    ents = _detect(
        "Продавец: Иванова-Петрова Алла Юрьевна, паспорт 43 15 415582\n"
    )
    assert any("Иванова-Петрова Алла Юрьевна" in p for p in _per(ents)), _per(ents)
