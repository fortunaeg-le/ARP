# --- ЭТАП ADDR-B: аббревиатура = УСЕЧЕНИЕ полного адресного слова -------------
#
# ПРИЧИНА (разбор 30 худших случаев, experiments/stage_addr_b): «бул.» и «просп.»
# не опознавались адресными маркерами НИГДЕ — ни в категоризации токена, ни в
# границе предложения, ни в расширении краёв. Следствие было не косметическим:
# «630099, Республика Татарстан, г. Новосибирск, бул. Кутузовский, вл. 69» ->
# маска «Кутузовский, вл. 69…», а индекс, регион и город оставались ОТКРЫТЫМИ
# (51 символ ПДн), потому что точка после «бул» читалась как граница предложения,
# а слева расширение упиралось в «незнакомое строчное слово».
#
# Наборы выше уже содержали РУЧНЫЕ усечения («переул», «набережн», «помещен»,
# «строен») — то есть механизм был, но заполнялся поимённо и потому дырявый.
# Здесь он заменён ПРАВИЛОМ: русская аббревиатура — это начало слова, обрезанное
# точкой. Токен, за которым СТОИТ ТОЧКА и который является СТРОГИМ началом
# полного адресного слова, — тот же маркер, что это слово.
#
# Ограничения правила названы явно (иначе оно ловило бы прозу):
#   * только при точке следом — без точки это обычное слово, не аббревиатура;
#   * длина >= _ADDR_ABBR_MIN (2): ОДНОбуквенные («г.», «д.», «к.», «т.»)
#     остаются на прежнем ЯВНОМ списке — одна буква с точкой это и предлог, и
#     инициал, и «т. е.», правилу её отдавать нельзя. Порог именно 2, а не 3,
#     потому что «вл.» (владение) встречается в корпусе 128 раз и без него
#     адрес, КОНЧАЮЩИЙСЯ на «вл. 7», терял хвост. Риск порога 2 измерен по
#     тексту корпуса: двухбуквенных токенов с точкой девять видов — «кв. рф.
#     см. вл. ул. оф. уч. им. рп.», из них началом полного адресного слова
#     являются только адресные же («кв.», «вл.», «ул.», «оф.», «уч.»);
#   * полное слово — длиной >= _ADDR_FULL_MIN (5), иначе «кра.» от «край» и
#     «сел.» от «село» делали бы маркер из трёхбуквенного огрызка почти любого
#     слова;
#   * усечение СТРОГОЕ (короче полного слова) — полные слова уже в наборах.
_ADDR_ABBR_MIN = 2
_ADDR_FULL_MIN = 5


def _full_words(*sets):
    """Полные (не усечённые) слова наборов — база для правила аббревиатуры."""
    return frozenset(w for s in sets for w in s
                     if len(w) >= _ADDR_FULL_MIN and w.isalpha())


_ADDR_FULL_BY_CAT = (
    ("street", _full_words(_ADDR_STREET_MK)),
    ("premise", _full_words(_ADDR_PREMISE_MK)),
    ("locality", _full_words(_ADDR_LOCALITY_MK)),
)


def _addr_abbrev_cat(core: str):
    """Категория маркера для АББРЕВИАТУРЫ core (без точки, в нижнем регистре):
    строгое начало полного адресного слова -> категория этого слова, иначе None.
    Вызывающий обязан сам убедиться, что за токеном стоит точка."""
    if len(core) < _ADDR_ABBR_MIN or not core.isalpha():
        return None
    for cat, words in _ADDR_FULL_BY_CAT:
        for w in words:
            if len(core) < len(w) and w.startswith(core):
                return cat
    return None


def _addr_dotted_abbrev_cat(tok: str):
    """То же для токена «как он в тексте»: маркер, только если токен КОНЧАЕТСЯ
    точкой («бул.»). Нужен расширению краёв, где токен приходит вместе с точкой."""
    if not tok.endswith("."):
        return None
    return _addr_abbrev_cat(tok.strip(" \t.,;:()«»\"'").lower())


def _addr_marker_cat(tok: str, next_is_digit: bool, had_dot: bool):
    """Категория адресного маркера токена: 'street'|'premise'|'locality'|None.
    «д.» перед числом — дом (premise), «д.» перед именем — деревня (locality); «к.»
    перед числом — корпус. Короткие маркеры требуют точку СЛЕДОМ (форма «г.»)."""
    core = tok.strip(" \t.,;:()«»\"'").lower().replace(".", "")
    if not core:
        return None
    if core in _ADDR_SHORT_MK and not had_dot:
        return None                      # «с»/«в»/«ш» без точки — не маркер
    if core == "д":
        return "premise" if next_is_digit else "locality"
    if core == "к":
        return "premise" if next_is_digit else None
    if core in _ADDR_STREET_MK:
        return "street"
    if core in _ADDR_PREMISE_MK:
        return "premise"
    if core in _ADDR_LOCALITY_MK:
        return "locality"
    return _addr_abbrev_cat(core) if had_dot else None


def _addr_scan_tokens(text: str, s: int, e: int):
    """Токенизирует [s,e) для якоря: список (tok_start, tok_end, word, cat, is_num,
    is_cap). cat — категория маркера (или None), is_num — токен-число, is_cap —
    слово-ТОПОНИМ: Titlecase (первая заглавная, НЕ целиком заглавное). ALL-CAPS
    аббревиатуры («ГОСТ», «Р», «ОВД») is_cap НЕ считаются — иначе «ГОСТ Р 52044»
    прошёл бы как «Город Улица Дом»."""
    toks = list(_ADDR_WORD_RE.finditer(text, s, e))
    out = []
    for k, m in enumerate(toks):
        w = m.group(0)
        nxt = toks[k + 1].group(0) if k + 1 < len(toks) else ""
        next_is_digit = bool(nxt) and nxt[0].isdigit()
        had_dot = m.end() < len(text) and text[m.end()] == "."
        cat = _addr_marker_cat(w, next_is_digit, had_dot)
        is_num = w[0].isdigit()
        core = w.strip(" \t.,;:()«»\"'")
        is_cap = (bool(core) and core[0].isupper() and not core.isupper()
                  and cat is None and not is_num)
        out.append((m.start(), m.end(), w, cat, is_num, is_cap))
    return out


_ADDR_HOUSE_GAP = frozenset(" \t.,")


def _addr_house_pattern(text, toks) -> bool:
    """Безмаркерный якорь «улица+дом»: Titlecase-топоним ВПЛОТНУЮ перед коротким
    номером дома («Ленина 5», «Светланская 22», «Мира 68»), И в прогоне >=2 топонима
    (город+улица). «Вплотную» = между ними только пробелы/запятые/точки (не «№»/слова).
    Отсекает «Статья 5» (1 топоним), «ГОСТ Р 52044» (не Titlecase, длинный номер),
    «Приложение № 1 … Договору» («№» между), «Комната переговоров 5» (строчное перед
    числом)."""
    ncap = sum(1 for (_, _, _, _, _, cap) in toks if cap)
    if ncap < 2:
        return False
    for k in range(len(toks) - 1):
        _, e_k, _, _, _, cap = toks[k]
        s_n, e_n, w_n, _, is_num, _ = toks[k + 1]
        gap = text[e_k:s_n]
        # номер-дома НЕ должен быть началом ДАТЫ/десятичной дроби («Москвы 14.05.2015»):
        # если сразу за ним «.цифра» — это дата, не дом (даты — не часть адреса, ТЗ п.2).
        date_tail = re.match(r"\.\d", text[e_n:e_n + 2])
        # За номером дома НЕ должна идти ЕЩЁ группа цифр («Паспорт 43 15 415582» —
        # это реквизит, а не «улица дом»: настоящий номер дома одиночный).
        nn = toks[k + 2] if k + 2 < len(toks) else None
        num_run = nn is not None and nn[4] and all(
            ch in _ADDR_HOUSE_GAP for ch in text[e_n:nn[0]])
        if (cap and is_num and _ADDR_HOUSENUM_RE.match(w_n) and not date_tail
                and not num_run and all(ch in _ADDR_HOUSE_GAP for ch in gap)):
            return True
    return False


# «а/я 15» (абонентский ящик) — премис-эквивалент.
_ADDR_PO_BOX_RE = re.compile(r"(?i)а\s*/\s*я\s*\d")


def _addr_valid_index(text, toks) -> bool:
    """Почтовый индекс как якорь — ТОЛЬКО когда 6-значная группа ВПЛОТНУЮ (через
    пробелы/запятые) прилегает к городу/локальности/топониму: «420111, г. Казань»,
    «Одинцово, 143000». Голая 6-значная группа паспорта/кода подразделения к городу
    не прилегает («…подразделения 770091», «412957, выдан …») — не якорь. Так индекс
    возвращает адреса «город+индекс» без улицы, НЕ воскрешая паспортные FP."""
    for k, (s_k, e_k, w_k, cat_k, is_num_k, cap_k) in enumerate(toks):
        if not (is_num_k and _ADDR_INDEX_RE.fullmatch(w_k)):
            continue
        # сосед слева/справа — локальность-маркер ИЛИ Titlecase-топоним, вплотную
        for j in (k - 1, k + 1):
            if not (0 <= j < len(toks)):
                continue
            s_j, e_j, w_j, cat_j, is_num_j, cap_j = toks[j]
            lo, hi = (e_j, s_k) if j < k else (e_k, s_j)
            gap = text[lo:hi]
            if (cat_j in ("locality", "street", "premise") or cap_j) and \
                    all(ch in _ADDR_HOUSE_GAP for ch in gap):
                return True
    return False


def _addr_span_strong(text: str, s: int, e: int) -> bool:
    """Сильный адресный якорь на спане [s,e). Локальность-одиночка и ГОЛЫЙ ИНДЕКС
    (не прилегающий к городу) НЕ якорь: 6-значная группа паспорта/кода подразделения —
    ложный «индекс». Якорь =
      * УЛИЦА с топонимом/номером рядом («ул. Ленина», «ш. Тверская»); ИЛИ
      * ПОМЕЩЕНИЕ с номером («д. 18», «кв. 5», «а/я 15»); ИЛИ
      * БЕЗМАРКЕРНЫЙ «улица+дом» (Titlecase-топоним + номер, >=2 топонима); ИЛИ
      * ИНДЕКС, ПРИЛЕГАЮЩИЙ к городу/топониму («420111, г. Казань»)."""
    toks = _addr_scan_tokens(text, s, e)
    cats = {c for (_, _, _, c, _, _) in toks if c}
    has_num = any(n for (_, _, _, _, n, _) in toks)
    has_cap = any(c for (_, _, _, _, _, c) in toks)
    if "street" in cats and (has_cap or has_num):
        return True
    if "premise" in cats and has_num:
        return True
    if _ADDR_PO_BOX_RE.search(text[s:e]):
        return True
    if _addr_house_pattern(text, toks):
        return True
    if _addr_valid_index(text, toks):
        return True
    return False


# Граница предложения внутри адресного кандидата: «Федерации. Стороны» — точка после
# слова-НЕ-аббревиатуры, за которой (через пробелы) заглавная. «д. 18»/«стр. 1» —
# точка после адресной аббревиатуры, НЕ граница. Перенос строки — всегда граница.
_ADDR_ABBR_BEFORE_DOT = (
    _ADDR_STREET_MK | _ADDR_PREMISE_MK | _ADDR_LOCALITY_MK | _ADDR_SHORT_MK
)


def _addr_split_sentences(text: str, s: int, e: int):
    """Дробит [s,e) по границам предложений (перенос строки; точка/!/? после
    слова-не-аббревиатуры перед заглавной). Возвращает список подспанов."""
    parts = []
    cut = s
    i = s
    while i < e:
        ch = text[i]
        boundary = False
        if ch in "\n\r":
            boundary = True
            end_here = i
        elif ch in ".!?":
            # токен непосредственно слева (слово ИЛИ число)
            j = i - 1
            while j >= s and (text[j].isalnum() or text[j] == "-"):
                j -= 1
            word = text[j + 1:i].lower().replace(".", "")
            k = i + 1
            while k < e and text[k] in " \t":
                k += 1
            nxt_upper = k < e and text[k].isupper()
            # граница, если слева НЕ адресная аббревиатура (обычное слово ИЛИ число —
            # «…кв. 5. Покупателю»: точка после номера дома завершает адрес), а справа
            # заглавная. Одиночная БУКВА слева — инициал/аббревиатура («В.О.», «А.С.»),
            # не конец предложения. Пустой токен (двойная пунктуация) — не граница.
            is_abbr = (
                (word in _ADDR_ABBR_BEFORE_DOT and not word.isdigit())
                or (len(word) == 1 and word.isalpha())
                # ЭТАП ADDR-B: усечение полного адресного слова — такая же
                # аббревиатура, как явно перечисленные («бул.», «просп.»).
                # Без этого точка в «бул. Кутузовский» рвала адрес пополам, и
                # левая половина (индекс+регион+город) оставалась открытой.
                or _addr_abbrev_cat(word) is not None
            )
            if word and not is_abbr and nxt_upper:
                boundary = True
                end_here = i + 1
        if boundary:
            if end_here > cut:
                parts.append((cut, end_here))
            cut = i + 1
        i += 1
    if e > cut:
        parts.append((cut, e))
    return parts


# Лениентный набор маркерных слов для ОБРЕЗКИ КРАЁВ (без требования точки к коротким):
# ведущее «г»/«д»/«ул» — часть адреса, не обрезаем; ведущее «по»/«адресу»/«место» — метка.
_ADDR_MARKER_ANY = (
    _ADDR_STREET_MK | _ADDR_PREMISE_MK | _ADDR_LOCALITY_MK | _ADDR_SHORT_MK
)


def _addr_is_marker_word(tok: str) -> bool:
    core = tok.strip(" \t.,;:()«»\"'").lower().replace(".", "")
    return core in _ADDR_MARKER_ANY


def _addr_strip_edges(text: str, s: int, e: int) -> tuple[int, int]:
    """Обрезает ТОЛЬКО ведущие метки/предлоги («по адресу:», «Реквизиты») и краевую
    пунктуацию. Внутренность и правый край НЕ трогаем: _build_address_spans уже
    останавливает расширение на стоп-словах, а над-закрытие метки золотой контракт
    допускает. Ведущий строчный токен снимаем, лишь если он НЕ маркер, НЕ топоним
    (Titlecase), НЕ число — то есть предлог/метка/глагол.

    ЭТАП ADDR-B, две правки — обе про НЕДОБОР (маска короче эталона = утечка):

    (1) АБОНЕНТСКИЙ ЯЩИК. «а/я 27, г. Одинцово, 143000» -> обрезка снимала «а/я »
        (114 адресов корпуса): её токенизатор видит «а» и «я» как два отдельных
        односимвольных слова — не маркер, не топоним, не число, — и честно
        принимал их за метку. Правило то же, по которому а/я СЧИТАЕТСЯ ЯКОРЕМ в
        _addr_span_strong (_ADDR_PO_BOX_RE): раз конструкция признана адресной,
        обрезка не имеет права резать сквозь её начало.

    (2) ТОЧКА АББРЕВИАТУРЫ НА ХВОСТЕ. «…, Московская обл.» -> обрезка снимала
        точку (187 адресов), эталон её содержит, и маска оказывалась короче на
        символ: ПДн это не раскрывает, но masking B (границы) считает эталон
        незакрытым. Точка возвращается ТОЛЬКО когда она принадлежит адресной
        аббревиатуре («обл.», «стр.»); после НОМЕРА («…, д. 5.») точка остаётся
        снаружи — там она конец предложения, ровно как её читает
        _addr_split_sentences."""
    toks = _addr_scan_tokens(text, s, e)
    i = 0
    while i < len(toks):
        _, _, w, cat, is_num, is_cap = toks[i]
        if cat or is_num or is_cap or _addr_is_marker_word(w):
            break
        i += 1
    ns = toks[i][0] if i < len(toks) else s
    box = _ADDR_PO_BOX_RE.search(text, s, e)
    if box is not None and box.start() < ns:
        ns = box.start()                      # (1) не режем сквозь «а/я»
    elif i >= len(toks):
        return s, s
    ne = e
    while ne > ns and text[ne - 1] in " \t.,;:":
        ne -= 1
    if ne < e and text[ne] == ".":            # (2) точка адресной аббревиатуры
        tail = _addr_scan_tokens(text, ns, ne)
        if tail and tail[-1][3] is not None and tail[-1][1] == ne:
            ne += 1
    return ns, ne


def _addr_cut_label(text: str, s: int, e: int) -> tuple[int, int]:
    """ЭТАП ADDR-B, ПЕРЕБОР. Срезает ведущую МЕТКУ ПОЛЯ по двоеточию.

    _addr_strip_edges снимает ведущий токен, только если он строчный: метка с
    заглавной («Почтовый адрес: Химки Баумана 75/3 кв 69») выглядит для неё
    топонимом, и 35 масок корпуса начинались с метки. Признак структурный, а не
    словарный: двоеточие — конец имени поля, а в САМОМ адресе его не бывает
    (проверено на эталоне: 0 из 1308 адресов содержат ':').

    Режем по ПОСЛЕДНЕМУ двоеточию и только если остаток САМ держит сильный якорь:
    иначе спан осыпался бы в ничто, а потеря детекции дороже лишней метки."""
    k = text.rfind(":", s, e)
    if k < 0:
        return s, e
    ns = k + 1
    while ns < e and text[ns] in " \t":
        ns += 1
    if ns >= e or not _addr_span_strong(text, ns, e):
        return s, e
    return ns, e


def _finalize_address_spans(text, raw_spans, occupied):
    """Этап C: из сырых адресных спанов (LOC∪yargy, кластеризованных/расширенных)
    оставляет только НАСТОЯЩИЕ адреса. Каждый спан: режем по границам предложений →
    обрезаем края до якорного содержимого → ПОДРЕЗАЕМ к барьерам ORG/PER/реквизитов
    → пропускаем ТОЛЬКО при сильном якоре. Барьеры подрезаются ДО проверки якоря:
    иначе «Паспорт 43 15 415582, выдан…» проходит через ложный house-pattern
    «Паспорт 43», а подрезка паспорта оставляет ложный адресный хвост «, выдан …»."""
    out = []
    for rs, re_ in raw_spans:
        for ss, se in _addr_split_sentences(text, rs, re_):
            ts, te = _addr_strip_edges(text, ss, se)
            if ts >= te:
                continue
            if occupied:
                ts, te = _clip_edges(ts, te, occupied)
                ts, te = _addr_strip_edges(text, ts, te)   # снять край, оголённый подрезкой
            if ts < te:
                ts, te = _addr_cut_label(text, ts, te)
            if ts < te and _addr_span_strong(text, ts, te):
                out.append((ts, te))
    return out


def _overlaps_any(s: int, e: int, spans) -> bool:
    """True, если [s, e) пересекается хотя бы с одним интервалом из spans."""
    return any(max(s, os) < min(e, oe) for os, oe in spans)


def _addr_transparent(text: str, s: int, e: int) -> bool:
    """True, если интервал [s, e) — это АДРЕСНЫЙ ХВОСТ, ошибочно помеченный NER как
    PER/ORG (напр. «Советская 12», «Свободы 46»: улица + номер дома NER часто тэггит
    ORG). Такой спан НЕ должен быть барьером для адреса — адрес обязан его закрыть.
    Отличаем от НАСТОЯЩЕГО соседа (ФИО «Иванов Иван Иванович», «ООО «Ромашка»») по
    номеру дома: адресный хвост несёт цифру-номер И состоит целиком из адресно-
    классифицируемых токенов; ФИО/ORG-название номера дома не имеют. regex-реквизиты
    сюда НЕ попадают (проверяются отдельно и всегда остаются барьером — иначе утечка)."""
    toks = _ADDR_TOKEN_RE.findall(text[s:e])
    if not toks:
        return False
    if not any(any(ch.isdigit() for ch in tk) for tk in toks):
        return False                              # нет номера дома — это не адресный хвост
    return all(_classify_addr_token(tk) == "addr" for tk in toks)


def _address_barriers(
    text: str,
    ner_spans: list[tuple[int, int]],
    regex_spans: list[tuple[int, int]],
    org_spans: list[tuple[int, int]] = (),
) -> list[tuple[int, int]]:
    """Занятая территория, на которую расширение адреса НЕ наступает: все regex-реквизиты
    (всегда) + все структурные ORG-спаны движка anchor_registry (всегда, этап A' —
    это уже подтверждённый якорем/реестром реальный ORG, не сырая догадка NER, поэтому
    _addr_transparent к ним не применяется) + те Natasha PER/ORG, что НЕ являются
    адресным хвостом (_addr_transparent). Общая для основного прохода и граничного
    (B3) — геометрия барьеров одна."""
    barriers = list(regex_spans) + list(org_spans)
    barriers += [(s, e) for s, e in ner_spans if not _addr_transparent(text, s, e)]
    return barriers


def _clip_edges(s: int, e: int, occupied) -> tuple[int, int]:
    """Обрезает КРАЯ адресного спана до границы чужой сущности. Нужно потому, что сам
    yargy иногда включает соседнее ФИО/ORG в адресный парс («д. 8 Иванов»): расширение
    тут ни при чём, спан «грязный» с самого начала. Режем только край, упирающийся в
    occupied (внутренние пересечения — редки и добираются обрезкой в _resolve_overlaps);
    середину адреса не трогаем. Адрес закрывается вплотную ДО чужой сущности — это НЕ
    сужение: та территория покрыта своим токеном, ничего не утекает."""
    changed = True
    while changed and s < e:
        changed = False
        for os_, oe in occupied:
            if os_ > s and os_ < e <= oe:        # occ накрывает правый край, слева есть адрес
                e = os_
                changed = True
            elif oe < e and os_ <= s < oe:       # occ накрывает левый край, справа есть адрес
                s = oe
                changed = True
    return s, e


def _classify_addr_token(tok: str) -> str:
    """Классифицирует токен на границе адреса: 'addr' (часть адреса — продолжать
    расширение), 'skip' (пустой/пунктуация — пройти, но не расширять), 'stop'
    (незнакомое слово в нижнем регистре — мы вышли из адреса)."""
    core = tok.strip(" \t.,;:()«»\"'")
    if not core:
        return "skip"
    if any(ch.isdigit() for ch in core):
        return "addr"                         # индекс/дом/«22-й»/«132/3»/«6А»
    low = core.lower().rstrip(".")
    if low in _ADDR_MARKER_WORDS:
        return "addr"                         # адресный маркер (тип улицы/дома/поселения)
    if _addr_dotted_abbrev_cat(tok) is not None:
        return "addr"                         # усечение полного адресного слова («бул.»)
    if core[0].isupper():
        return "addr"                         # топоним / название улицы (имя собственное)
    return "stop"                             # слово нижнего регистра, не маркер — конец адреса


def _addr_token_is_type_word(tok: str) -> bool:
    """Токен — АДРЕСНОЕ ТИПОВОЕ СЛОВО (улица/помещение/поселение), полное или
    усечённое точкой. Уже: не всякий «адресный» токен, а именно тот, за которым
    по построению стоит ЗНАЧЕНИЕ (название или номер). Страна/«рф»/цифры сюда
    НЕ входят — иначе правило «маркер требует значения» ниже разрешило бы
    впитывать слово после чего угодно."""
    core = tok.strip(" \t.,;:()«»\"'")
    if not core or any(ch.isdigit() for ch in core):
        return False
    low = core.lower().rstrip(".")
    if low in _ADDR_STREET_MK or low in _ADDR_PREMISE_MK or low in _ADDR_LOCALITY_MK:
        return True
    if low in _ADDR_SHORT_MK and tok.rstrip(" ,").endswith("."):
        return True
    return _addr_dotted_abbrev_cat(tok) is not None


# ЭТАП ADDR-B: МАРКЕР ТРЕБУЕТ ЗНАЧЕНИЯ.
#
# ПРИЧИНА. Классификация края смотрит на РЕГИСТР: строчное незнакомое слово —
# «конец адреса». На документах с испорченным регистром (мутации case/combo, а в
# жизни — просто набранный строчными реквизит) это рвало адрес прямо посреди
# конструкции «тип + значение»: «…, стр. 2, пом. vii» -> маска обрывалась на
# «пом», «пом. vii» оставалось открытым; «просп. ленинградская» -> название
# улицы открыто.
#
# ПРАВИЛО. Значение непосредственно ПОСЛЕ адресного типового слова принадлежит
# адресу независимо от регистра и алфавита: «пом.» без своего номера бессмысленно.
# Ограничения, чтобы правило не стало «глотаем ещё одно слово всегда»:
#   * ровно ОДИН токен — маркер требует одного значения, а не хвоста прозы;
#   * между маркером и значением НЕ должно быть запятой (запятая заканчивает
#     компонент адреса: «обл., дмитровский р-н» — «дмитровский» уже не значение
#     «обл.»);
#   * типовым словом считается только улица/помещение/поселение
#     (_addr_token_is_type_word), не страна и не число.
_ADDR_ARG_SEP = ","


def _addr_tail_type_word_end(text: str, end: int) -> int | None:
    """Конец АДРЕСНОГО ТИПОВОГО СЛОВА, если спан обрывается сразу на нём
    («…, стр. 2, пом» -> позиция после «пом»). Иначе None."""
    last = None
    for m in _ADDR_TOKEN_RE.finditer(text, max(0, end - 24), end):
        last = m
    if last is None or last.end() != end:
        return None
    return end if _addr_token_is_type_word(last.group(0)) else None


def _expand_addr_right(text: str, end: int, occupied=()) -> int:
    """Тянет правый край адреса по адресным токенам, НИКОГДА не сужая.
    Останавливается на первом не-адресном слове, на пределе _ADDR_EXPAND_MAX
    или ВПЛОТНУЮ ДО начала чужой сущности (occupied): расширение не наступает на
    территорию, уже занятую regex/PER/ORG-токеном — там ничего не утекает, зона
    покрыта другим токеном. Асимметрия «при сомнении шире» действует только на
    свободном тексте между концом адреса и началом чужой сущности.

    Исключение — «маркер требует значения» (см. блок выше): один токен после
    адресного типового слова берём, даже если он строчный/латинский."""
    p = end
    limit = min(len(text), end + _ADDR_EXPAND_MAX)
    marker_end = _addr_tail_type_word_end(text, end)
    while p < len(text):
        m = _ADDR_TOKEN_FWD_RE.match(text, p)
        if m is None or m.start(1) >= limit:
            break
        if _overlaps_any(m.start(1), m.end(1), occupied):
            break                                 # уткнулись в чужую сущность — стоп
        tok = m.group(1)
        cls = _classify_addr_token(tok)
        if cls == "stop":
            if marker_end is None or _ADDR_ARG_SEP in text[marker_end:m.start(1)]:
                break
            cls = "addr"                          # значение своего маркера
        p = m.end(1)
        if cls == "addr":
            end = p
        if cls != "skip":                         # «.» между «пом» и «vii» — не сброс
            marker_end = m.end(1) if _addr_token_is_type_word(tok) else None
    return end


# Левое расширение УЖЕ правого: тянем влево только ведущий индекс/регион/страну
# (то, что грамматика yargy роняет слева: «Российская Федерация, 101000, …»). НЕ
# грабим произвольное слово с заглавной буквы — иначе съедаем метку ячейки («Адрес:»,
# «Юридический адрес:») в токен, теряя контекст для LLM. Асимметрия слева слабее:
# страна/регион — наименее идентифицирующая часть, её недозакрытие не утечка дома/кв.
_ADDR_LEFT_WORDS = frozenset(
    "россия российская российской российскую федерация федерации рф".split()
)


def _classify_addr_left_token(tok: str) -> str:
    """Классификатор ЛЕВОГО расширения (уже правого: левый край не должен съедать
    метку ячейки «Адрес:» в токен). Три исхода:
      'commit' — цифра (индекс) / адресный маркер / форма страны: фиксируем сюда;
      'pass'   — пустой ИЛИ слово с ЗАГЛАВНОЙ (метка/регион-прилагательное): проходим
                 сквозь, но не фиксируем — впитается, лишь если левее есть 'commit';
      'stop'   — слово нижнего регистра не-маркер: вышли из адреса влево."""
    core = tok.strip(" \t.,;:()«»\"'")
    if not core:
        return "pass"
    if any(ch.isdigit() for ch in core):
        return "commit"
    low = core.lower().rstrip(".")
    if low in _ADDR_MARKER_WORDS or low in _ADDR_LEFT_WORDS:
        return "commit"
    if _addr_dotted_abbrev_cat(tok) is not None:
        return "commit"                       # усечение полного адресного слова («просп.»)
    if core[0].isupper():
        return "pass"
    return "stop"


def _expand_addr_left(text: str, start: int, occupied=()) -> int:
    """Тянет левый край адреса влево по индексу/региону/маркерам, НИКОГДА не сужая.
    Заглавное слово впитывается, лишь если левее нашёлся фиксируемый адресный токен —
    так «обл. Московская,»/«Российская Федерация,» входят, а метка «Адрес:» нет.
    Останавливается ВПЛОТНУЮ ПОСЛЕ чужой сущности (occupied): расширение влево не
    заходит на территорию regex/PER/ORG-токена (симметрично правому расширению)."""
    bound = max(0, start - _ADDR_EXPAND_MAX)
    prefix = text[bound:start]
    new_start = start
    toks = list(_ADDR_TOKEN_RE.finditer(prefix))
    for i in range(len(toks) - 1, -1, -1):
        m = toks[i]
        abs_s, abs_e = bound + m.start(), bound + m.end()
        if _overlaps_any(abs_s, abs_e, occupied):
            break                                 # уткнулись в чужую сущность — стоп
        cls = _classify_addr_left_token(m.group(0))
        if cls == "stop":
            # «маркер требует значения», зеркально правому расширению: слово
            # слева-вплотную от которого стоит адресное типовое слово — это его
            # ЗНАЧЕНИЕ («просп. ленинградская»), и регистр тут ни при чём.
            # Не фиксируем ('pass'): войдёт, только если сам маркер левее
            # окажется 'commit' — так одиночное строчное слово границу не двигает.
            left = toks[i - 1] if i else None
            if (left is None
                    or not _addr_token_is_type_word(left.group(0))
                    or _ADDR_ARG_SEP in prefix[left.end():m.start()]):
                break
            cls = "pass"
        if cls == "commit":
            new_start = abs_s
        # 'pass': идём влево, не фиксируя (впитается ретроспективно при commit)
    return new_start


def _filter_suspect_yargy(
    text: str,
    yargy_spans: list[tuple[int, int]],
    ner_spans: list[tuple[int, int]],
    loc_spans: list[tuple[int, int]],
) -> list[tuple[int, int]]:
    """Отбрасывает yargy-спаны, похожие на ложное срабатывание на ФИО/названии: они
    ПЕРЕКРЫВАЮТ уже найденную PER/ORG-сущность и при этом НЕ подкреплены ни LOC, ни
    адресным маркером внутри себя. yargy иногда принимает последовательность заглавных
    (имя) за топоним; такой обрывок, склеенный кластеризацией с настоящим адресом рядом,
    затянул бы ФИО и метку («адрес:») в ADDRESS-токен (человек мислейбелится адресом,
    своего PERSON-токена не получает). LOC/маркеры/расширение восстанавливают настоящий
    адрес и без этого спана, поэтому его снятие безопасно для полноты (проверено GOLDEN)."""
    if not ner_spans:
        return yargy_spans
    kept: list[tuple[int, int]] = []
    for s, e in yargy_spans:
        overlaps_ner = any(max(s, ns) < min(e, ne) for ns, ne in ner_spans)
        overlaps_loc = any(max(s, ls) < min(e, le) for ls, le in loc_spans)
        has_marker = _ADDR_ANCHOR_RE.search(text[s:e]) is not None
        if overlaps_ner and not overlaps_loc and not has_marker:
            continue
        kept.append((s, e))
    return kept


def _build_address_spans(
    text: str,
    raw_spans: list[tuple[int, int]],
    occupied: list[tuple[int, int]] = (),
) -> list[tuple[int, int]]:
    """Собирает финальные адресные спаны из «сырых» хитов (LOC ∪ yargy):
    кластеризует по близости, расширяет края по адресным токенам, повторно
    склеивает пересечения, возникшие от расширения. Полнота спана важнее точности
    границ (см. асимметрию цены).

    occupied — интервалы уже найденных ЧУЖИХ сущностей (regex-реквизиты, PER/ORG):
    расширение края останавливается вплотную до них, не поглощая соседнее поле
    (иначе следующая сущность теряет свой токен, а при regex-хвосте — утечка ПДн)."""
    spans = sorted({(s, e) for s, e in raw_spans if 0 <= s < e})
    if not spans:
        return []

    clusters: list[tuple[int, int]] = []
    cs, ce = spans[0]
    for s, e in spans[1:]:
        if s - ce <= _ADDR_CLUSTER_GAP:
            ce = max(ce, e)
        else:
            clusters.append((cs, ce))
            cs, ce = s, e
    clusters.append((cs, ce))

    expanded = [
        (_expand_addr_left(text, s, occupied), _expand_addr_right(text, e, occupied))
        for s, e in clusters
    ]

    expanded.sort()
    merged = [expanded[0]]
    for s, e in expanded[1:]:
        ps, pe = merged[-1]
        if s <= pe:
            merged[-1] = (ps, max(pe, e))
        else:
            merged.append((s, e))

    # Обрезаем края спанов до границ чужих сущностей (yargy мог захватить соседнее поле).
    if occupied:
        clipped = []
        for s, e in merged:
            s, e = _clip_edges(s, e, occupied)
            if s < e:
                clipped.append((s, e))
        return clipped
    return merged


def _load_ner_config(config_path: str) -> tuple[dict, list[str]]:
    """Читает entity_types.yaml и возвращает:
      - ner_label_map: {метка Natasha -> entity_type} для записей method: ner с ner_label
        (напр. {"PER": "PERSON", "ORG": "ORG"});
      - addr_types: список entity_type для записей method: ner с ner_extractor: addr
        (обычно ["ADDRESS"]).
    Записи с enabled: false пропускаются. Файл обязан существовать — иначе FileNotFoundError.
    """
    with open(config_path, encoding="utf-8") as f:
        config = yaml.safe_load(f)

    ner_label_map: dict[str, str] = {}
    addr_types: list[str] = []

    for entity_type, spec in config["entity_types"].items():
        if not isinstance(spec, dict) or spec.get("method") != "ner":
            continue
        if spec.get("enabled", True) is False:
            continue

        ner_label = spec.get("ner_label")
        ner_extractor = spec.get("ner_extractor")

        if ner_extractor == "addr":
            addr_types.append(entity_type)
        elif ner_label is not None:
            ner_label_map[ner_label] = entity_type
        else:
            print(
                f"ПРЕДУПРЕЖДЕНИЕ: тип {entity_type} (method: ner) без ner_label и без "
                f"ner_extractor: addr — пропущен",
                file=sys.stderr,
            )

    return ner_label_map, addr_types


def _expand_person_span(text: str, start: int, end: int) -> tuple[int, int]:
    """Расширяет спан PERSON инициалами "И.И." в обе стороны независимо.
    Возвращает новые (start, end)."""
    right = _INITIALS_RIGHT.match(text[end:])
    if right is not None:
        end = end + right.end()

    left = _INITIALS_LEFT.search(text[:start])
    if left is not None:
        start = left.start()

    return start, end


def _glue_address_matches(text: str, matches: list) -> list[tuple[int, int]]:
    """Склеивает соседние Match'и AddrExtractor в цепочки-адреса.
    Соседние склеиваются, если разрыв между match_i.stop и match_{i+1}.start
    не длиннее 6 символов и целиком состоит из [ ,.\\u00A0] (без букв).
    Возвращает список (start, end) итоговых спанов."""
    if not matches:
        return []

    ordered = sorted(matches, key=lambda m: (m.start, m.stop))

    spans: list[tuple[int, int]] = []
    cur_start = ordered[0].start
    cur_end = ordered[0].stop

    for m in ordered[1:]:
        gap = text[cur_end:m.start]
        glue = (
            0 <= len(gap) <= _ADDR_GAP_MAXLEN
            and all(ch in _ADDR_GAP_CHARS for ch in gap)
        )
        if glue:
            cur_end = m.stop
        else:
            spans.append((cur_start, cur_end))
            cur_start = m.start
            cur_end = m.stop

    spans.append((cur_start, cur_end))
    return spans


# --------------------------------------------------------------------------- #
#   ЭТАП E′ — «расплетающий» вид адреса (сборка рваных мутациями кандидатов)   #
# --------------------------------------------------------------------------- #
# Мутации рвут адрес ВНУТРИ слова переносом строки («Ленинградск\nая 36») или
# NBSP/невидимым («Мир\xa0а 18», «ОДИНЦO\xadВО») — yargy/LOC/house-pattern не
# видят целых токенов, адрес не собирается (116 позиций утечки-долга гейта D).
# Решение ЭТАПА C НЕ ослабляется: строим ОТДЕЛЬНЫЙ поисковый вид, где разрыв
# внутри слова СКЛЕЕН, и прогоняем по нему ТОТ ЖЕ конвейер (LOC/yargy → строгий
# якорь → обрезка). Решение «адрес или нет» принимает прежний гейт — сборка лишь
# отдаёт ему целый текст. Правила расплетания:
#   * разрывающий символ МЕЖДУ буквами -> ВЫРЕЗАТЬ (слово склеивается);
#   * разрывающий символ МЕЖДУ цифрами -> ВЫРЕЗАТЬ (индекс «1430 00»);
#     — но для \n/\r ТОЛЬКО если склейка даёт 6-значный индекс (ЭТАП S3);
#   * \n/\r, НЕ склеенный по правилам выше, -> остаётся '\n' (ЭТАП S3, см. ниже);
#   * прочие невидимые/NBSP вне слова -> ' ' (они и в исходном тексте разделитель);
#   * ОДИНОЧНЫЙ обычный пробел между цифровыми группами, дающими РОВНО 6 цифр,
#     -> вырезать («420 111» -> «420111»: рваный мутацией digit_spaces индекс;
#     паспортные группы 2+2+6/серия 4+6 шестёрку не образуют и не склеиваются).
#
# ЭТАП S3 (регрессия M-2: over-mask прозы по ADDRESS 3 -> 86). Изначально E′
# заменял НЕсклеенный \n пробелом — «перенос между словами = обычный
# разделитель». Но \n в штатном проходе это ГРАНИЦА ПРЕДЛОЖЕНИЯ
# (_addr_split_sentences), и её исчезновение в виде РОЖДАЛО кандидатов, которых
# в исходном тексте не было: кластеризация сшивала конец одной строки с началом
# следующей, и адресная маска уползала на НОМЕР ПУНКТА договора («3.2»), на
# ЯРЛЫК реквизита соседней строки («ИНН», «Паспорт», «ОГРНИП», «КПП»), на метку
# («Почтовый адрес:») и на паспортный хвост. Компенсаторы
# (_addr_split_at_newlines/_addr_trim_tail_lines) работали ПОСЛЕ проверки якоря
# и по слабому предикату «в хвосте есть цифра» — номер пункта его проходит.
# Теперь вид ЧИНИТ ТОЛЬКО РАЗРЫВ ВНУТРИ СЛОВА/ЧИСЛА, а всякая другая граница
# строки остаётся ровно там, где была: тот же _addr_split_sentences режет по ней
# ДО проверки сильного якоря, и каждый кусок обязан держать якорь сам.
# ИНВАРИАНТ: вид отличается от исходного текста ТОЛЬКО в точках склейки, поэтому
# кандидат, которого не было в исходном тексте, не может появиться иначе как
# через склейку (а эмит и без того требует склейку внутри спана).
# АНТИ-СКЛЕЙКА (зеркало −): два РАЗНЫХ адреса в столбик, разделённые \n, в виде
# больше не становятся соседями — граница предложения сохранена. Страховка
# _addr_split_at_newlines оставлена вторым рубежом (делит спан, накрывший бывший
# \n, если обе половины держат якорь сами).
_ADDR_BREAKING = frozenset("\n\r\xad​⁠‌‍ \xa0")
# Максимальный цифро-пробельный прогон («420 111», «143 0 00»); в коде ниже
# склеивается, только если В СУММЕ ровно 6 цифр (почтовый индекс) и был пробел.
_SIX_DIGIT_GLUE_RE = re.compile(r"\d[\d ]*\d")


_INDEX_DIGITS = 6           # почтовый индекс — ровно столько цифр


def _digits_around_make_index(out: list[str], base: str, j: int) -> bool:
    """ЭТАП S3: даёт ли склейка цифр через ПЕРЕНОС СТРОКИ почтовый индекс.
    Считаем цифровой прогон слева (в уже собранном виде) и справа (в исходном
    тексте с позиции j) — вместе ровно _INDEX_DIGITS."""
    left = 0
    k = len(out) - 1
    while k >= 0 and out[k].isdigit():
        left += 1
        k -= 1
    right = 0
    k = j
    while k < len(base) and base[k].isdigit():
        right += 1
        k += 1
    return left + right == _INDEX_DIGITS


def _addr_deweave(base: str) -> tuple[str, list[int], bool]:
    """(view, idx, changed): view — расплетённая копия base, idx[k] — позиция
    view[k] в base (строго возрастает), changed — были ли СКЛЕЙКИ (вырезания).
    Замена \\n->' ' сама по себе changed не поднимает (эквивалентна пробелу для
    конвейера) — но наличие \\n в base учитывает вызывающий (поведение
    сентенс-сплита меняется)."""
    out: list[str] = []
    idx: list[int] = []
    changed = False
    n = len(base)
    for i, ch in enumerate(base):
        if ch not in _ADDR_BREAKING:
            out.append(ch)
            idx.append(i)
            continue
        prev = out[-1] if out else ""
        j = i + 1
        while j < n and base[j] in _ADDR_BREAKING:
            j += 1
        nxt = base[j] if j < n else ""
        if prev.isalpha() and nxt.isalpha():
            # Для \n/\r склейка ТОЛЬКО при СТРОЧНОМ продолжении: рваное слово
            # продолжается строчными («Ленинградск|ая», «Нов|осибирская»), а
            # настоящая граница строк сшивала бы два РАЗНЫХ токена («…пом.
            # VII|ИНН…» на чистом документе — мусорная склейка через стык B3).
            # Невидимые/NBSP внутри слова склеиваем без этого требования (мутация
            # вставляет их в середину слова, регистр продолжения любой).
            if ch in "\n\r" and not nxt.islower():
                pass
            else:
                changed = True          # разрыв внутри слова — склеить
                continue
        if prev.isdigit() and nxt.isdigit():
            # ЭТАП S3: для \n/\r — только если склейка даёт ПОЧТОВЫЙ ИНДЕКС
            # (ровно 6 цифр). У буквенной ветки признак «это одно слово» есть
            # (строчное продолжение), у числовой его нет, и правило приваривало
            # конец строки к номеру пункта следующей: «…вл. 63\n3.2. Уведомления»
            # -> «633.2» — ложный «дом 63/индекс», из которого и росла маска
            # «3.2» (50 шт. на корпусе). Индекс — единственный числовой токен,
            # ради которого строится адресный вид (E′: «420 111», «1430 00»);
            # остальные числа адреса короткие и рвутся не по строкам.
            # Невидимые/NBSP внутри числа склеиваем без этого условия — они
            # вставлены мутацией ВНУТРЬ токена, границей строк не бывают.
            if ch in "\n\r" and not _digits_around_make_index(out, base, j):
                pass
            else:
                changed = True      # разрыв внутри числа (индекса) — склеить
                continue
        # ЭТАП S3: не склеили — значит это НЕ разрыв слова, а настоящая граница.
        # \n/\r сохраняем как \n: граница предложения обязана дожить до
        # _addr_split_sentences, иначе вид рождает кандидатов, которых в исходном
        # тексте не было (номер пункта/ярлык соседней строки под адресной маской).
        out.append("\n" if ch in "\n\r" else " ")
        idx.append(i)

    # одиночные ОБЫЧНЫЕ пробелы внутри цифровой группы, дающей ровно 6 цифр
    # (рваный индекс «420 111»/«143 0 00») — вырезать. Скан по уже собранному out.
    s = "".join(out)
    drop: set[int] = set()
    for m in _SIX_DIGIT_GLUE_RE.finditer(s):
        frag = m.group(0)
        digits = frag.replace(" ", "")
        if " " in frag and len(digits) == 6:
            for k in range(m.start(), m.end()):
                if s[k] == " ":
                    drop.add(k)
    if drop:
        changed = True
        out2, idx2 = [], []
        for k in range(len(out)):
            if k in drop:
                continue
            out2.append(out[k])
            idx2.append(idx[k])
        out, idx = out2, idx2

    return "".join(out), idx, changed


def _deweave_glue_positions(w_idx: list[int]) -> list[int]:
    """ИСХОДНЫЕ позиции, где deweave ВЫРЕЗАЛ символ(ы): src-индекс последнего
    символа ПЕРЕД вырезкой. Только склейки самого deweave — скачки карты
    normalize (схлопнутые дефисы/невидимые Stage 2) сюда не попадают."""
    return [w_idx[i] for i in range(len(w_idx) - 1) if w_idx[i + 1] - w_idx[i] > 1]


def _span_has_glue(src_s: int, src_e: int, glue_src: list[int]) -> bool:
    """Содержит ли исходный интервал [src_s, src_e) точку склейки deweave."""
    return any(src_s <= g < src_e for g in glue_src)


def _addr_view(segment) -> tuple[str, list[int], list[int]]:
    """Расплетённый НОРМАЛИЗОВАННЫЙ вид сегмента для второго адресного прохода:
    (norm_view, offset_map->segment.text, glue_src). glue_src — ИСХОДНЫЕ позиции
    склеек deweave (пустой список при пустом виде). Пустой norm_view — второй
    проход не нужен. Кэшируется в metadata."""
    md = segment.metadata
    cached = md.get("_addr_view_cache")
    if cached is not None:
        return cached
    base = md.get("detection_text", segment.text)
    woven, w_idx, changed = _addr_deweave(base)
    # ЭТАП S3: без склейки вид ПОБАЙТНО равен штатному (\n больше не заменяется
    # пробелом), поэтому второй проход не может дать ничего нового — а стоит он
    # второго прогона NER на каждом сегменте с переносом (E′: корпус ~1.6×).
    # Раньше условие включало «есть \n», и именно этот путь рождал регрессию M-2.
    need = changed
    if not need:
        result = ("", [], [])
        md["_addr_view_cache"] = result
        return result
    from normalizer import normalize_for_detection
    norm, n_idx = normalize_for_detection(woven)
    offset_map = [w_idx[i] for i in n_idx]
    # glue_src: где deweave СКЛЕИЛ (рваное слово/индекс). Склейка — «сид» запуска
    # yargy (LOC/маркер на рваном тексте молчат) И обязательное условие эмита
    # (спан без склейки полностью покрыт штатным проходом с его \n-границей
    # предложения — видовой эмит без склейки лишь тащит LOC-хиты паспортного
    # хвоста к адресу соседней строки). Скачки карты normalize (дефисы в числах)
    # склейкой НЕ считаются. Якорь не ослабляется: решает прежний _addr_span_strong.
    result = (norm, offset_map, _deweave_glue_positions(w_idx))
    md["_addr_view_cache"] = result
    return result


def _addr_tail_has_value(view: str, s: int, e: int) -> bool:
    """Несёт ли хвост [s,e) адресное ЗНАЧЕНИЕ: цифру (дом/индекс) или адресный
    маркер. Голая метка следующей строки («ИНН», «Телефон») значения не несёт."""
    toks = _addr_scan_tokens(view, s, e)
    return any(is_num or cat for (_, _, _, cat, is_num, _) in toks)


def _addr_trim_tail_lines(view: str, spans, nl_view_positions):
    """Подрезка КРАЁВ, перелезших через бывший \\n на соседнюю строку без
    адресного значения: в расплетённом виде \\n стал пробелом, и расширение
    краёв впитывает метку соседней строки («…кв 33 | ИНН …» -> «…кв 33 ИНН»;
    «…ОГРНИП | 3.2. Место: Москва…» — слева). В штатном проходе \\n рвал
    предложение — возвращаем эту границу с ОБОИХ краёв там, где за ней нет ни
    цифры, ни адресного маркера (адресные продолжения «ая 36», «г. Казань»
    остаются)."""
    if not nl_view_positions:
        return spans
    out = []
    for s, e in spans:
        inner = sorted(p for p in nl_view_positions if s < p < e)
        while inner and not _addr_tail_has_value(view, inner[-1], e):
            e = inner.pop()
        while inner and not _addr_tail_has_value(view, s, inner[0]):
            s = inner.pop(0)
        if s < e:
            out.append((s, e))
    return out


def _addr_split_at_newlines(view: str, spans, nl_view_positions):
    """АНТИ-СКЛЕЙКА двух адресов (зеркало −). Для каждого спана: в каждой
    накрытой позиции бывшего \\n делим, если ОБЕ стороны НЕЗАВИСИМО держат
    сильный якорь (_addr_span_strong). Итеративно слева направо (колонка из
    трёх адресов делится дважды). Рваный ОДИН адрес половинного якоря не имеет —
    остаётся целым."""
    out = []
    for s, e in spans:
        cur = s
        for p in sorted(nl_view_positions):
            if not (cur < p < e):
                continue
            if _addr_span_strong(view, cur, p) and _addr_span_strong(view, p, e):
                out.append((cur, p))
                cur = p
        out.append((cur, e))
    return [(s, e) for s, e in out if s < e]


def _addr_value_spans(seg_text: str, src_s: int, src_e: int):
    """Куски значения для Entity.spans: hull, разбитый по прогонам \\n/\\r
    (края кусков подрезаны от пробелов). Один кусок -> None (однодиапазонная)."""
    spans = []
    for m in re.finditer(r"[^\n\r]+", seg_text[src_s:src_e]):
        piece = m.group(0)
        lead = len(piece) - len(piece.lstrip(" \t"))
        trail = len(piece) - len(piece.rstrip(" \t"))
        s = src_s + m.start() + lead
        e = src_s + m.end() - trail
        if e > s:
            spans.append((s, e))
    return spans if len(spans) > 1 else None


def detect_ner(
    doc: SourceDocument,
    config_path: str,
    regex_entities: list[Entity] | None = None,
    org_entities: list[Entity] | None = None,
    per_entities: list[Entity] | None = None,
) -> list[Entity]:
    """regex_entities — результат detect_regex, ЕСЛИ он уже посчитан вызывающим
    (нормативный путь: реквизиты дают «карту занятой территории» ДО расширения
    адреса, см. shifrator.py). Без него расширение всё равно уступает своим PER/ORG,
    а пересечение с regex-хвостом ловится обрезкой в _resolve_overlaps (страховка).

    org_entities — результат anchor_registry.detect_org, ЕСЛИ он уже посчитан
    вызывающим (этап A': ORG теперь считается ДО detect_ner, см. shifrator.py). Это
    структурный барьер расширения адреса — закрывает A-4 (адрес поглощал обломок
    готового ORG, lease_0008). Без него расширение адреса просто не видит ORG вовсе
    (Natasha-ORG в конфиге выключена, см. этап A).

    per_entities — структурные PER-сущности anchor_registry (этап B): такой же
    безусловный барьер расширения адреса, что ORG. Natasha-PER в конфиге выключена
    (structure-first PER), поэтому адрес больше не видит людей через NER — барьер
    ставит готовый PER-спан, чтобы адрес не заходил на ФИО (подготовка к этапу C)."""
    ner_label_map, addr_types = _load_ner_config(config_path)

    # Карта regex-территории по сегментам: расширение адреса на неё не наступает.
    regex_by_seg: dict[str, list[tuple[int, int]]] = {}
    if regex_entities:
        for e in regex_entities:
            regex_by_seg.setdefault(e.segment_id, []).append((e.start, e.end))

    # Карта структурных ORG-спанов (anchor_registry) по сегментам — тот же
    # безусловный барьер, что regex, см. docstring _address_barriers.
    org_by_seg: dict[str, list[tuple[int, int]]] = {}
    if org_entities:
        for e in org_entities:
            org_by_seg.setdefault(e.segment_id, []).append((e.start, e.end))

    # Структурные PER-спаны (этап B) — тот же безусловный барьер, что ORG.
    per_by_seg: dict[str, list[tuple[int, int]]] = {}
    if per_entities:
        for e in per_entities:
            per_by_seg.setdefault(e.segment_id, []).append((e.start, e.end))

    entities: list[Entity] = []

    for segment in doc.segments:
        orig_text = segment.text
        if not orig_text:
            continue

        # Весь путь детекции (Doc, расширение инициалов, AddrExtractor, склейка окон)
        # работает с НОРМАЛИЗОВАННОЙ копией (этап 2): омоглифы сведены, невидимые
        # сняты, разделители внутри числа схлопнуты, регистр нормализован (через
        # detection_text как базу). Все внутренние спаны (loc/ner/yargy/барьеры) —
        # в координатах ЭТОЙ копии. original_text у каждого Entity вырезается из
        # НАСТОЯЩЕГО segment.text (orig_text), а спан [start,end) отображается из
        # норм-координат в исходные через offset_map при СОЗДАНИИ Entity. На
        # неискажённом тексте нормализация — тождество, поведение прежнее.
        text, offset_map = detection_view(segment)

        # --- NER-тэггер Natasha: PERSON/ORG (по конфигу) + LOC-спаны (для адреса) ---
        # Тэггер нужен и для адреса (LOC — контекстный детектор места), поэтому
        # запускаем его, если сконфигурирован хоть PER/ORG, хоть ADDRESS.
        loc_spans: list[tuple[int, int]] = []
        ner_spans: list[tuple[int, int]] = []   # PER/ORG-спаны для отсева yargy-ФИО-ложняков
        if ner_label_map or addr_types:
            nlp_doc = Doc(text)
            nlp_doc.segment(_segmenter)
            nlp_doc.tag_ner(_ner_tagger)
            for span in nlp_doc.spans:
                if span.type == "LOC":
                    loc_spans.append((span.start, span.stop))
                    continue
                entity_type = ner_label_map.get(span.type)
                if entity_type is None:
                    continue  # метка Natasha не сопоставлена ни одному типу конфига

                start, end = span.start, span.stop
                if span.type == "PER":
                    start, end = _expand_person_span(text, start, end)
                ner_spans.append((start, end))   # норм-координаты (для барьеров)

                src_start, src_end = norm_to_src(offset_map, start, end)
                entities.append(Entity(
                    id=str(uuid.uuid4()),
                    segment_id=segment.id,
                    start=src_start,
                    end=src_end,
                    original_text=orig_text[src_start:src_end],
                    entity_type=entity_type,
                    detector="ner",
                    confidence=1.0,
                ))

        # --- ADDRESS: гибрид «LOC/маркеры детектируют место → yargy-парсер добирает
        # полный спан → консервативное расширение закрывает хвост». yargy НЕ гоняется
        # по сегментам без хита (главный источник ускорения этапа A). ---
        if addr_types:
            if loc_spans or _addr_has_seed(text):
                # yargy — только здесь (окрестность хита), не по всему тексту
                yargy_spans = _glue_address_matches(text, list(_addr_extractor(text)))
                # Структурные ORG/PER-спаны (anchor_registry, этапы A/B) в координатах
                # норм-текста — нужны и для ОТСЕВА yargy-ложняков (ниже), и как барьеры
                # расширения. regex/ORG/PER хранятся в ИСХОДНЫХ координатах.
                regex_src = regex_by_seg.get(segment.id, [])
                regex_norm = [src_to_norm(offset_map, s, e) for s, e in regex_src]
                org_src = org_by_seg.get(segment.id, [])
                org_norm = [src_to_norm(offset_map, s, e) for s, e in org_src]
                per_src = per_by_seg.get(segment.id, [])
                per_norm = [src_to_norm(offset_map, s, e) for s, e in per_src]
                # Отсев yargy-ложняков на ФИО/названиях (перекрывают PER/ORG без LOC/
                # маркера): иначе кластеризация затянула бы имя и метку в ADDRESS-токен.
                # ЭТАП B: Natasha-PER/ORG выключены, поэтому ner_spans почти пуст —
                # источник «занятых» ФИО/ORG-спанов теперь СТРУКТУРНЫЙ движок (per/org_norm).
                # Без них yargy-ложняк на «Иванов» сшивается с реальным адресом и тянет
                # метку «адрес:» в токен (регресс, вскрытый отключением Natasha-PER).
                name_spans = list(ner_spans) + list(org_norm) + list(per_norm)
                yargy_spans = _filter_suspect_yargy(text, yargy_spans, name_spans, loc_spans)
                # Сам адрес подтверждают LOC и/или yargy (маркер — лишь триггер запуска):
                # маркерные позиции в «сырьё» НЕ кладём, иначе список маркеров стал бы
                # самостоятельным детектором. Расширение краёв использует маркеры как
                # линейку, но стартует только от подтверждённых LOC/yargy-спанов.
                occupied = _address_barriers(
                    text, ner_spans, regex_norm, list(org_norm) + list(per_norm)
                )
                raw_addr = _build_address_spans(
                    text, loc_spans + yargy_spans, occupied
                )
                # ЭТАП C: строгий якорь + обрезка краёв поверх сырых спанов yargy/LOC.
                for start, end in _finalize_address_spans(text, raw_addr, occupied):
                    src_start, src_end = norm_to_src(offset_map, start, end)
                    for addr_type in addr_types:
                        entities.append(Entity(
                            id=str(uuid.uuid4()),
                            segment_id=segment.id,
                            start=src_start,
                            end=src_end,
                            original_text=orig_text[src_start:src_end],
                            entity_type=addr_type,
                            detector="ner",
                            confidence=1.0,
                        ))

            # --- ЭТАП E′: ВТОРОЙ адресный проход по «расплетённому» виду ---
            # Только если вид отличается от штатного (склейка рваных слов/индексов
            # или \n в сегменте). Тот же конвейер, тот же строгий якорь; плюс
            # анти-склейка двух адресов по позициям бывших \n (зеркало −). Дубли
            # со штатным проходом схлопывает разрешение пересечений блока 4.
            view, vmap, glue_src = _addr_view(segment)
            if view:
                v_doc = Doc(view)
                v_doc.segment(_segmenter)
                v_doc.tag_ner(_ner_tagger)
                v_loc = [(sp.start, sp.stop) for sp in v_doc.spans if sp.type == "LOC"]
                if v_loc or _addr_has_seed(view) or glue_src:
                    v_yargy = _glue_address_matches(view, list(_addr_extractor(view)))
                    regex_v = [src_to_norm(vmap, s, e)
                               for s, e in regex_by_seg.get(segment.id, [])]
                    org_v = [src_to_norm(vmap, s, e)
                             for s, e in org_by_seg.get(segment.id, [])]
                    per_v = [src_to_norm(vmap, s, e)
                             for s, e in per_by_seg.get(segment.id, [])]
                    name_v = list(org_v) + list(per_v)
                    v_yargy = _filter_suspect_yargy(view, v_yargy, name_v, v_loc)
                    occ_v = _address_barriers(view, [], regex_v, name_v)
                    raw_v = _build_address_spans(view, v_loc + v_yargy, occ_v)
                    final_v = _finalize_address_spans(view, raw_v, occ_v)
                    # позиции бывших \n в координатах вида (для анти-склейки):
                    # символ вида, чей исходный символ — \n/\r (заменён пробелом)
                    base_txt = segment.metadata.get("detection_text", orig_text)
                    nl_pos = [k for k, si in enumerate(vmap)
                              if base_txt[si] in "\n\r"]
                    final_v = _addr_split_at_newlines(view, final_v, nl_pos)
                    final_v = _addr_trim_tail_lines(view, final_v, nl_pos)
                    for start, end in final_v:
                        src_start, src_end = norm_to_src(vmap, start, end)
                        # эмитим ТОЛЬКО спан, содержащий точку СКЛЕЙКИ deweave:
                        # на не-склеенной многострочной ячейке видовой проход
                        # лишь сливает строки (пропадает сентенс-граница \n) —
                        # кластеризация тащит LOC-хиты паспортного хвоста («выдан
                        # ОУФМС России по…») к реальному адресу соседней строки,
                        # и обрезка блока 4 рождает хвост-маску на ЧИСТОМ
                        # документе (35 шт. в замере). Скачки карты normalize
                        # (дефисы «358-877») склейкой НЕ считаются. Всё
                        # не-склеенное покрывает штатный проход.
                        if not _span_has_glue(src_start, src_end, glue_src):
                            continue
                        # крайние \n/пробелы (бывшие границы строк) в hull не берём
                        while src_start < src_end and orig_text[src_start] in " \t\n\r":
                            src_start += 1
                        while src_end > src_start and orig_text[src_end - 1] in " \t\n\r":
                            src_end -= 1
                        if src_start >= src_end:
                            continue
                        for addr_type in addr_types:
                            entities.append(Entity(
                                id=str(uuid.uuid4()),
                                segment_id=segment.id,
                                start=src_start,
                                end=src_end,
                                original_text=orig_text[src_start:src_end],
                                entity_type=addr_type,
                                detector="ner",
                                confidence=1.0,
                                spans=_addr_value_spans(orig_text, src_start, src_end),
                            ))

    # Инвариант блока 3: original_text строго равен срезу сегмента по [start:end].
    # ЭТАП O2: здесь пробовалась замена линейного поиска сегмента на карту
    # id -> сегмент (проход O(сущностей x сегментов) -> O(сущностей)). ОТКАЧЕНО:
    # выигрыш на всех трёх нагрузках неотличим от нуля, а построение карты ДО
    # цикла ломает tests/test_wave1_verification.py::
    # test_p4_invariant_violation_raises_under_python_dash_O — тот извлекает блок
    # инварианта ИЗ ЭТОГО ИСХОДНИКА по якорю-строке заголовка цикла ниже и
    # прогоняет под `python -O`, то есть блок обязан быть САМОДОСТАТОЧНЫМ начиная
    # с этой строки. Контракт самодостаточности дороже нулевого выигрыша.
    # (Сам якорь здесь дословно НЕ повторять: source.index найдёт его в
    #  комментарии раньше, чем в коде, и тест начнёт извлекать текст.)
    for e in entities:
        seg = next(s for s in doc.segments if s.id == e.segment_id)
        actual = seg.text[e.start:e.end]
        if e.original_text != actual:
            raise AssertionError(
                f"Нарушен инвариант original_text для {e.entity_type} в {e.segment_id} "
                f"[{e.start}:{e.end}]: ожидалось {e.original_text!r}, получено {actual!r}"
            )

    return entities
