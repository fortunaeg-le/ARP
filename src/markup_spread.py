"""ЭТАП MARKUP-SPREAD — распространение РУЧНОЙ разметки по документу.

ПРОБЛЕМА. Пользователь выделяет пропущенное значение на экране проверки, выбирает
тип, жмёт «применить» — и закрывается РОВНО ОДНО вхождение, то, которое он выделил
мышкой (`app/core.py::_add_missed` кладёт в маску список `occurrences` из ОДНОГО
элемента). Остальные вхождения того же значения — в других падежах, в таблицах, в
колонтитулах — остаются открытыми. Это опаснее обычного пропуска: человек видит
маску на том месте, куда смотрел, считает документ закрытым и отправляет его в
стороннюю LLM с той же фамилией открытой в пяти других местах.

РЕШЕНИЕ. Помеченное человеком значение — это ЯКОРЬ, ровно в том же смысле, в каком
им является структурно опознанная организация в `anchor_registry.py`: тип объявлен
(его выбрал человек — доказательство сильнее любого структурного признака), а
дальше значение гуляет по документу в падежах. Поэтому проход по документу здесь —
ТОТ ЖЕ проход 2 движка якорей, собранный из ЕГО ЖЕ деталей: поисковый вид сегмента
(`per_search_view`/`anchor_search_view` — свод омоглифов, невидимых, переносов
внутри слова), ключ из лемм (`_lemma_first`/`_lemma_set`, pymorphy), карта
координат обратно в исходный текст (`norm_to_src`) и ТЕ ЖЕ процедуры точности
(`_addr_type_left`, `_orgform_left`, `_find_quoted`). Второго механизма морфологии
и второго набора guard-ов не заводится.

ЧЕМ ЭТОТ ПРОХОД ОТЛИЧАЕТСЯ ОТ ПРОХОДА 2 ДВИЖКА — и почему это не «то же самое»:

  1. ЯКОРЬ НЕ ИЩЕТСЯ. Проход 1 (детекторы якорей) здесь не нужен и не запускается:
     якорь принесён снаружи — это спан, который выделил человек.
  2. СПАН НЕ РАСШИРЯЕТСЯ. `AnchorEngine` зовёт `det.expand_match`, добирающий вокруг
     совпавшей фамилии полный прогон ФИО. Здесь этого НЕТ намеренно: границу выбрал
     человек, и расширять её за него — значит молча менять его решение. Пометил
     «Коваль» — закрывается «Коваль»/«Коваля»/«Ковалю», но не «Коваль Иван Петрович»
     целиком. Предсказуемость важнее полноты там, где решение принял не алгоритм.
  3. ЖАНРОВЫЙ КОНТЕКСТ СРАВНИВАЕТСЯ С ЯКОРНЫМ (см. `_context_flags` ниже) — у
     движка якорь по построению стоит в «своём» жанре, у ручной пометки гарантии
     нет.

ЧТО СЧИТАЕТСЯ ТЕМ ЖЕ ЗНАЧЕНИЕМ — два режима, по типу:

  * МОРФОЛОГИЧЕСКИЙ (PERSON, ORG): совпадение ПОСЛЕДОВАТЕЛЬНОСТИ ЛЕММ. «Коваль» →
    «Коваля», «Ковалю», «Ковалём» (лемма всех четырёх — «коваль»). Здесь же
    структурно решается вопрос частичного совпадения: «Ивановский» имеет лемму
    «ивановский», ключ пометки «Иванов» — «иванов», множества не пересекаются, и
    вхождение НЕ берётся. Отдельной проверки «это не подстрока» не нужно:
    сопоставление идёт по ЦЕЛЫМ токенам и по НОРМАЛЬНЫМ ФОРМАМ, а не по символам.
  * БУКВАЛЬНЫЙ (все остальные типы — ИНН, телефон, e-mail, адрес, суммы, даты…):
    точное совпадение строки на границах слова. У реквизита нет падежей, а у
    адреса склоняется город, но не дом; морфология на них дала бы только риск.

ЛОЖНЫЕ — чем закрыты (задача 3 постановки). Опасность распространения в том, что
то же слово в другом месте значит ДРУГОЕ: «Мороз» человек и «мороз» погода,
«Самара» в адресе и «Самара» в названии фирмы. Три процедуры, все — уже
существующие в `anchor_registry`:

  * РЕГИСТР. Вхождение со строчной буквы, когда человек пометил слово с заглавной,
    не берётся. Это ровно первая строка `PerAnchorDetector.guard`: «мороз ударил»
    от «Мороз Иван» отличается именно этим.
  * ЖАНРОВЫЙ КОНТЕКСТ, ОДНОСТОРОННЕ. Вхождение не берётся, если оно ПРИОБРЕЛО
    признак жанра, которого у якоря НЕ БЫЛО: кавычки/org-форма слева (значит,
    здесь это имя фирмы) или адресный тип-маркер слева (значит, здесь это
    топоним). Односторонне — потому что обратное направление законно: якорь
    «ПАО «Восход»» и голое «Восход» в прозе ниже — это одна и та же фирма, и
    терять её нельзя.
  * ДЛИНА КЛЮЧА. Однословный ключ короче трёх букв не распространяется вовсе:
    на таком ключе цена ошибки выше любой пользы.

Модуль НИЧЕГО не мутирует и ничего не знает про сессию: на вход — документ,
занятые (уже закрытые) диапазоны и якорь, на выход — список найденных вхождений.
Решение, что с ними делать, принимает `app/core.py`.
"""

import re

from anchor_registry import (
    _INITIALS_RE,
    _WORD_RE,
    _addr_type_left,
    _find_quoted,
    _lemma_first,
    _lemma_set,
    _orgform_left,
    anchor_search_view,
    per_search_view,
)
from normalizer import norm_to_src, src_to_norm

# Типы, у которых значение СКЛОНЯЕТСЯ и потому ищется по леммам. Остальные —
# буквально (см. модульный docstring). Список намеренно короткий: морфология
# уместна там, где значение это ИМЯ СОБСТВЕННОЕ целиком.
MORPH_TYPES = frozenset({"PERSON", "ORG"})

# Однословный ключ короче этого не распространяется (см. «ДЛИНА КЛЮЧА»).
_MIN_SINGLE_WORD_KEY = 3

# «…2025 г.» — это ГОД, а не город, хотя `_addr_type_left` видит здесь свой
# маркер «г.». В детекторе якорей эта коллизия почти не встречается (там маркер
# проверяется слева от прогона ФИО, а не слева от произвольного помеченного
# человеком спана), здесь же дата документа стоит ровно перед названием стороны
# в шапке договора — замер по корпусу v1 показал 63 ложных отказа на 0 пойманных
# ложных срабатываний ровно из-за этого. Цифра слева от «г» — достаточный и
# однозначный признак года: в адресе перед типом места стоит запятая или начало
# строки, но не цифра.
_YEAR_MARK_RE = re.compile(r"\d\s*г\.?\s{0,2}$")

# Адресный тип-маркер `_addr_type_left` разрешает форму БЕЗ точки («с Ивановка»),
# и тогда обычный ПРЕДЛОГ становится маркером места: в «Договор с Самарой
# подписан» слева от имени стоит «с », детектор читает его как «с.» (село) и
# запрещает распространение законной фирмы. У движка якорей эта поблажка
# оправдана (он проверяет маркер слева от ПРОГОНА ФИО, где предлог почти не
# встречается), здесь — нет. Односложное сокращение места в договоре пишется с
# точкой всегда («г.», «с.», «д.», «ш.»), поэтому маркер длиной 1-2 буквы без
# точки маркером не считается.
_ADDR_MARKER_BODY_RE = re.compile(r"[^\s,.]+\.?\s{0,2}$")

# Закрывающая кавычка сразу за спаном: сопоставление идёт по ТОКЕНАМ, а кавычка
# токеном не является, поэтому «ПАО «ПромСнаб»» совпало бы как «ПАО «ПромСнаб» —
# маска встала бы, оставив в тексте висячую «»». Спан дотягивается до парной
# закрывающей кавычки, если открывающая уже внутри него.
_CLOSING_QUOTES = "»\"'”“"


def _view_for(entity_type: str, seg):
    """Поисковый вид сегмента — ТОТ ЖЕ, что берёт движок якорей для этого типа.
    PER-вид меняет перенос строки на пробел (ключ человека многотокенный и перенос
    ложится на границу слов), ORG-вид вырезает его напрочь (ключ однотокенный и
    перенос рвёт слово изнутри) — разница объяснена в `anchor_registry._strip_breaking`
    и повторять её здесь своим кодом нельзя: разъедется."""
    norm, omap = per_search_view(seg) if entity_type == "PERSON" \
        else anchor_search_view(seg)
    return norm, norm.lower(), omap


def _context_flags(norm: str, low: str, s: int, e: int) -> frozenset:
    """Признаки ЖАНРА позиции, в которой стоит спан [s, e) — тем же аппаратом,
    которым движок якорей отличает фирму от человека и от топонима:

      'org'  — спан внутри кавычек или org-форма («ООО», «ПАО», «общество с …»)
               заканчивается вплотную слева. Здесь имя читается как имя ФИРМЫ.
      'addr' — вплотную слева адресный тип-маркер («г.», «ул.», «пер.»). Здесь
               имя читается как ТОПОНИМ.

    Сравнение флагов якоря и кандидата — единственная защита от ловушки «одно и то
    же слово, разные сущности» («Самара» город против ООО «Самара»)."""
    flags = set()
    for (_open_idx, core_s, core_e, _close_idx) in _find_quoted(norm):
        if core_s <= s and e <= core_e:
            flags.add("org")
            break
    if "org" not in flags and _orgform_left(low, s):
        flags.add("org")
    if _addr_marker_left(low, s):
        flags.add("addr")
    return frozenset(flags)


def _addr_marker_left(low: str, s: int) -> bool:
    """`anchor_registry._addr_type_left` плюс две поправки на то, что здесь он
    смотрит слева от ПРОИЗВОЛЬНОГО помеченного человеком спана, а не слева от
    прогона ФИО: год («2025 г.») и односложный предлог без точки («с Самарой»)
    маркером места не считаются — см. `_YEAR_MARK_RE` и `_ADDR_MARKER_BODY_RE`."""
    if not _addr_type_left(low, s):
        return False
    win = low[max(0, s - 14):s]
    if _YEAR_MARK_RE.search(win):
        return False
    m = _ADDR_MARKER_BODY_RE.search(win)
    body = m.group(0).strip() if m else ""
    return body.endswith(".") or len(body) > 2


def _close_quote(norm: str, ns: int, ne: int) -> int:
    """Правая граница спана с дотянутой парной закрывающей кавычкой (см.
    `_CLOSING_QUOTES`). Дотягиваем ТОЛЬКО если открывающая кавычка уже внутри
    спана — иначе спан съел бы чужую кавычку соседней конструкции."""
    if ne < len(norm) and norm[ne] in _CLOSING_QUOTES:
        for (open_idx, core_s, core_e, close_idx) in _find_quoted(norm):
            if ns <= open_idx and core_e == ne and close_idx == ne + 1:
                return close_idx
    return ne


def _key_of(text: str):
    """Ключ морфологического режима: кортеж канонических лемм слов. Инициалы
    выброшены — ровно как в `anchor_registry._core_key` (инициал «И.» не несёт
    леммы и совпал бы с чем угодно). None — слов нет вовсе."""
    words = [w for w in _WORD_RE.findall(text) if not _INITIALS_RE.match(w)]
    if not words:
        return None
    return tuple(_lemma_first(w) for w in words)


def _overlaps(occupied, seg_id: str, s: int, e: int) -> bool:
    for (a, b) in occupied.get(seg_id, ()):  # исходные координаты
        if max(a, s) < min(b, e):
            return True
    return False


def _is_word_char(ch: str) -> bool:
    return ch.isalnum() or ch == "_"


def find_occurrences(doc, occupied: dict, segment_id: str, start: int, end: int,
                     entity_type: str) -> list[dict]:
    """ВСЕ прочие вхождения помеченного человеком значения в документе.

    doc        — SourceDocument (все сегменты: проза, таблицы, колонтитулы, узлы
                 Word — распространение обязано доставать до каждого, иначе
                 «закрыто» опять окажется неправдой);
    occupied   — {segment_id: [(start, end), …]} уже закрытые диапазоны в ИСХОДНЫХ
                 координатах: туда лезть нельзя, там уже стоит маска;
    segment_id/start/end — ЯКОРЬ, спан, который выделил человек;
    entity_type — тип, который он выбрал.

    Возвращает список {segment_id, start, end, surface} в исходных координатах,
    БЕЗ самого якоря, отсортированный по (segment_id, start). Ничего не мутирует.
    """
    anchor_seg = next((s for s in doc.segments if s.id == segment_id), None)
    if anchor_seg is None:
        return []

    a_norm, a_low, a_omap = _view_for(entity_type, anchor_seg)
    a_ns, a_ne = src_to_norm(a_omap, start, end)
    anchor_text = a_norm[a_ns:a_ne].strip()
    if not anchor_text:
        return []
    anchor_flags = _context_flags(a_norm, a_low, a_ns, a_ne)
    anchor_upper = anchor_text[:1].isupper()

    morph = entity_type in MORPH_TYPES
    key = _key_of(anchor_text) if morph else None
    if morph:
        if key is None:
            morph = False          # слов нет — искать по леммам нечего
        elif len(key) == 1 and len(key[0]) < _MIN_SINGLE_WORD_KEY:
            return []              # слишком короткий однословный ключ
    if not morph and len(anchor_text) < _MIN_SINGLE_WORD_KEY:
        return []
    # Однословный ли ключ — от этого зависит строгость проверки регистра
    # (см. `_accept`).
    single_word = len(key) == 1 if morph else len(_WORD_RE.findall(anchor_text)) <= 1

    out: list[dict] = []
    for seg in doc.segments:
        if not seg.text:
            continue
        if seg.id == segment_id:
            norm, low, omap = a_norm, a_low, a_omap
        else:
            norm, low, omap = _view_for(entity_type, seg)
        spans = _morph_spans(norm, key) if morph else _literal_spans(norm, anchor_text)
        for (ns, ne) in spans:
            if not _accept(norm, low, ns, ne, anchor_flags, anchor_upper, single_word):
                continue
            ne = _close_quote(norm, ns, ne)
            src_s, src_e = norm_to_src(omap, ns, ne)
            if seg.id == segment_id and max(src_s, start) < min(src_e, end):
                continue           # сам якорь
            if _overlaps(occupied, seg.id, src_s, src_e):
                continue           # тут уже стоит маска
            out.append({"segment_id": seg.id, "start": src_s, "end": src_e,
                        "surface": seg.text[src_s:src_e]})
    out.sort(key=lambda o: (o["segment_id"], o["start"]))
    return out


def _morph_spans(norm: str, key):
    """Позиции, где ПОСЛЕДОВАТЕЛЬНОСТЬ токенов даёт последовательность лемм key.
    Дословно тот же критерий, что `AnchorEngine._match_key` (лемма ключа входит в
    МНОЖЕСТВО нормальных форм токена — падежный омоним должен совпасть), но без
    расширения спана: берётся ровно диапазон совпавших токенов."""
    tokens = list(_WORD_RE.finditer(norm))
    klen = len(key)
    if len(tokens) < klen:
        return []
    lemsets = [_lemma_set(t.group(0)) for t in tokens]
    out = []
    i = 0
    while i + klen <= len(tokens):
        if all(key[j] in lemsets[i + j] for j in range(klen)):
            out.append((tokens[i].start(), tokens[i + klen - 1].end()))
            i += klen
        else:
            i += 1
    return out


def _literal_spans(norm: str, value: str):
    """Точные вхождения строки на границах слова. Границы обязательны только там,
    где сама строка кончается словесным символом: «+7 (900) 000-00-00» справа
    кончается цифрой (граница нужна, иначе номер совпал бы с куском длинного
    числа), а «д. 5,» — запятой (граница бессмысленна)."""
    out = []
    need_left = _is_word_char(value[0])
    need_right = _is_word_char(value[-1])
    i = norm.find(value)
    while i != -1:
        j = i + len(value)
        ok = True
        if need_left and i > 0 and _is_word_char(norm[i - 1]):
            ok = False
        if need_right and j < len(norm) and _is_word_char(norm[j]):
            ok = False
        if ok:
            out.append((i, j))
        i = norm.find(value, i + 1)
    return out


def _accept(norm, low, ns, ne, anchor_flags, anchor_upper, single_word) -> bool:
    """Процедуры точности на кандидате (см. «ЛОЖНЫЕ» в модульном docstring)."""
    # РЕГИСТР: человек пометил слово с заглавной — строчное вхождение это другое
    # слово («мороз ударил» против «Мороз Иван»). Проверка только на ОДНОСЛОВНОМ
    # ключе — дословно то же решение и по той же причине, что в
    # `PerAnchorDetector.guard`: многословное совпадение («кузнецовой марией
    # дмитриевной») само по себе есть форма ФИО, омонимом нарицательного она быть
    # не может, и требовать от неё заглавной значит терять целого человека из-за
    # оформления. На корпусе v1 это 21 из 63 ложных отказов guard-а.
    if single_word and anchor_upper and not norm[ns:ns + 1].isupper():
        return False
    # ЖАНР, ОДНОСТОРОННЕ: кандидат не имеет права ПРИОБРЕСТИ признак, которого у
    # якоря не было.
    if _context_flags(norm, low, ns, ne) - anchor_flags:
        return False
    return True
