"""Этап 2 — НОРМАЛИЗАЦИЯ ТЕКСТА ПЕРЕД ДЕТЕКЦИЕЙ.

Крупнейший бакет утечки ПДн — ИСКАЖЁННЫЙ текст: кириллические омоглифы вместо
цифр (телефон «12З-45-67»), латиница вместо кириллицы («ООО» латиницей),
невидимые символы внутри значения (ZWSP/NBSP), реквизиты, сгруппированные
дефисами («770-123-45-67»). Regex по \\d и Natasha такой текст не ловят: цифра
оказывается буквой, а между цифрами — невидимый символ.

Правило корпуса PT-1 запрещает нормализацию НА ИЗВЛЕЧЕНИИ (искажения обязаны
дойти до детектора как есть, а вывод/сессия — в ИСХОДНЫХ координатах). Поэтому
нормализация «символ-на-символ равной длины» — тупик: невидимые так не удалить, а
разделители внутри числа надо СХЛОПНУТЬ (длина меняется). Решение — строить
НОРМАЛИЗОВАННУЮ КОПИЮ текста ПЛЮС КАРТУ ИНДЕКСОВ norm_idx → src_idx:

  * детекторы ищут в normalize_for_detection(base)[0];
  * каждый найденный спан [n_start, n_end) отображается обратно в исходные
    координаты через norm_to_src(); токенизация/сессии/вывод — в исходных
    координатах, как и раньше;
  * нормализованный текст наружу НЕ выходит НИКОГДА.

ИНВАРИАНТ КАРТЫ. Каждый символ нормализованной копии происходит РОВНО ИЗ ОДНОГО
символа исходного текста (все замены строго 1:1; удаления/схлопывания только
ВЫБРАСЫВАЮТ исходные символы, никогда не порождают новый символ из нескольких).
Поэтому карта — это простой список offset_map длины len(norm), где offset_map[k]
— индекс исходного символа, из которого получен norm[k]; список строго
возрастает. Отсюда точное отображение спана:
    src_start = offset_map[n_start]
    src_end   = offset_map[n_end - 1] + 1
Внутренние (между n_start и n_end) выброшенные разделители попадают в исходный
спан естественно, а ведущие/хвостовые выброшенные разделители — нет, что и
требуется (не захватываем лишний дефис за границей матча).

Осознанно НЕ входит в этот этап (см. HANDOFF_STAGE_2): нормализация РЕГИСТРА
(её частично делает detection_text из extractor.py; полный второй проход NER по
регистро-нормализованной копии — под-задача 2b) и разрывы сущности через границу
сегмента (отдельный контракт SplitEntities). База для нормализации —
detection_text (если есть, он равной длины с segment.text) либо сам segment.text,
поэтому индексы карты всегда валидны как смещения в segment.text.
"""

import bisect
import re
import unicodedata


# --- Свод буквы-на-месте-цифры В ЧИСЛОВОМ КОНТЕКСТЕ (О→0 З→3 Ч→4 І→1 б→6 и т.п.) ---
# Кириллические/латинские буквы, визуально неотличимые от цифр. Свод происходит
# ТОЛЬКО внутри цифрового токена (см. normalize_for_detection) — «О» в «Общество»
# нулём не станет. Латинские O/o добавлены: копипаст из PDF часто латинизирует ноль.
_DIGIT_LOOKALIKE = {
    "О": "0", "о": "0", "O": "0", "o": "0",
    "З": "3", "з": "3",
    "Ч": "4", "ч": "4",
    "І": "1", "і": "1",
    "б": "6",
}

# 'б' («кв. 2б», «д. 12б») — самый опасный из омоглифов: это частотная буква и
# суффикс номера квартиры/дома. Своим→6 её разрешено сводить ТОЛЬКО когда она
# ВНУТРИ цифрового токена (цифры с обеих сторон), но не на краю — так «12б»
# (квартира) остаётся адресом, а «7б0» (искажённая середина реквизита) чинится.
_LOOKALIKE_EDGE_UNSAFE = frozenset("бБ")

# ЭТАП A5. «Сильные» двойники — те, которыми в документе печатают ИСКАЖЁННУЮ
# ЦИФРУ: прописные кириллические и латинская O плюс 'б'. Только из них может
# состоять группа реквизита, в которой не осталось ни одной настоящей цифры
# («Ч 068 268 315», «+7 8Ч3 887 77 Чб»). Строчные о/з/ч/і сюда НЕ входят: из них
# складываются частотные короткие слова («об», «за»), и свод испортил бы прозу.
_STRONG_LOOKALIKE = frozenset("ОЗЧІOб")

# Порог цепи: сколько НАСТОЯЩИХ цифр должно быть в разбитом пробелами числе,
# чтобы считать его реквизитом/телефоном, а не номером дома или квартиры.
_CHAIN_DIGIT_MIN = 6

# ЭТАП CHAR-NORM. Порог цепи по НАСТОЯЩИМ цифрам (выше) не берёт целый класс
# испорченных реквизитов: код подразделения паспорта «б22-513» — это шесть
# ЗНАКОВ цифрового вида, но всего пять настоящих цифр, и порог 6 он не набирал
# НИКОГДА; тот же разрыв у хвостовых групп телефона («…-58-бО»: цифр 4).
# Замер по дампу гейта: 19 значений класса ушли в LLM открытыми ровно по этой
# причине. Поэтому цепь признаётся реквизитной ЛИБО по прежнему порогу
# настоящих цифр, ЛИБО по ДЛИНЕ в знаках цифрового вида при минимуме настоящих
# цифр — второе условие обязательно: без него цепь из одних двойников («ОЗЧ»)
# считалась бы числом. Условие только РАСШИРЯЕТ прежний класс (всё, что имело
# >=6 настоящих цифр, имеет и >=6 знаков, и >=2 цифры).
_CHAIN_LEN_MIN = 6
_CHAIN_REAL_MIN = 2

# Длина ЦИФРОВОГО ТОКЕНА (в знаках цифрового вида), при которой 'б' на его краю
# перестаёт быть литерой дома/квартиры и становится искажённой шестёркой:
# «б597769253» (ИНН), «4Ч170335б» (КПП), «408028І057753526867б» (счёт). Литера
# всегда стоит при КОРОТКОМ номере («д. 12б», «кв. 2б») — шестизнакового номера
# дома не бывает, и порог разделяет эти два класса по самому тексту.
_EDGE_TOKEN_MIN = 6

# ЭТАП CHAR-NORM — ОБЫЧНЫЙ пробел ВНУТРИ цифровой группы (класс
# mut:digit_spaces). Одиночный U+0020 между цифрами нормализатор не трогал
# осознанно: его допускают паттерны со свободным разделителем (ИНН/ОГРН/счёт
# «\d(?:[ NBSP]?\d){N}»). Но паттерны с ФИКСИРОВАННОЙ группой его не допускают —
# у паспорта «\d{6}», и «90 14 6170 85» не находился ВООБЩЕ (26 значений в
# дампе гейта). Схлопывать все одиночные пробелы нельзя: «12 000 000» — это
# разряды суммы, и их склейка сломала бы SUM.
#
# Различение берётся из САМОЙ ЗАПИСИ, а не из типа: разрядная группировка
# имеет ровно одну форму — первая группа 1-3 знака, ВСЕ последующие ровно по 3.
# Всё, что этой форме не отвечает, разрядами не является. Три условия сразу:
#   * >= _SPLIT_MIN_GROUPS групп. Порог 4, а не 2, поставлен ЗАМЕРОМ, а не
#     вкусом: на трёх группах схлопывание отняло у мультиспана телефон.
#     `multispan.collect_multispan` собирает PHONE именно из ГРУППИРОВКИ
#     («84б 82б85 1Ч» — три группы, 10 цифр) и НЕПРЕРЫВНЫЙ номер пропускает
#     осознанно («зона штатного паттерна PHONE»), а штатный паттерн требует
#     полной формы из 11 цифр — то есть склейка групп убивала находку целиком
#     (поймано tests/test_stage_e_spans.py::test_minus_two_phones_adjacent…).
#     На четырёх и более группах ни одна запись мультиспана в корпусе не
#     теряется, а весь класс паспорта («NN NN NNN N NN») сохраняется: у него
#     групп всегда >= 4. ЭТО ГРАНИЦА ПО ЗАМЕРУ, и она же — честный остаток:
#     10-значный телефон, разбитый на четыре группы, схлопнется и находкой
#     мультиспана быть перестанет (FINDINGS: CHARNORM-SPLIT-VS-MULTISPAN);
#   * >= _SPLIT_MIN_DIGITS знаков цифрового вида суммарно (короткие номера
#     дома/квартиры/индекса не задеваются);
#   * форма НЕ разрядная.
_SPLIT_MIN_GROUPS = 4
_SPLIT_MIN_DIGITS = 8


def _is_thousands_grouping(groups: list[int]) -> bool:
    """Список длин групп — это разрядная группировка числа («12 000 000»)."""
    return (len(groups) >= 2 and 1 <= groups[0] <= 3
            and all(g == 3 for g in groups[1:]))


# Слабая связка цепи: запятая и точка МЕЖДУ цифровыми токенами. Цепь через них
# продолжается (копейки суммы «73Ч 525,0О» — одно значение, а не два числа), но
# сами эти знаки НИКОГДА не выбрасываются: они несут разряд.
_WEAK_JOIN = frozenset(".,")

# --- Свод АЛФАВИТНЫХ омоглифов латиница → кириллица (для NER/regex/синтаксиса) ---
# Только визуально однозначные пары. Направление латиница→кириллица: корпус —
# русские договоры, Natasha опирается на кириллицу. Свод применяется ТОЛЬКО внутри
# смешанного по алфавиту слова (есть и кириллица, и латиница) — так «Aндрей»
# (латинская A) чинится, а чисто латинское «Microsoft» остаётся нетронутым (иначе
# рост ложных срабатываний NER на настоящей латинице).
_ALPHA_FOLD_PAIRS = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
    "a": "а", "e": "е", "o": "о", "c": "с", "p": "р", "x": "х", "y": "у",
    "k": "к", "m": "м",
}

# ЭТАП A7 — таблица ЗАМЫКАЕТСЯ ПО РЕГИСТРУ (долг Stage2b-A).
# Свод был написан руками и вышел несимметричным: 'B'→'В' есть, 'b'→'В' нет
# (то же у 'h', 't'). Пара регистров одного и того же омоглифа — это ОДИН
# визуальный факт, а не два независимых решения, и пробел в таблице ломал не
# экзотику, а обычный порядок работы конвейера: регистровая нормализация
# (extractor.detection_text) переводит слово смешанного алфавита в нижний
# регистр РАНЬШЕ, чем сюда доходит очередь, и латинская 'B' из «иBаНоB»
# приезжает как 'b' — уже не сводимая. Слово остаётся рваным, ФИО не
# детектируется (утечка ПДн).
# Замыкание строится из тех же пар, новых визуальных решений не принимается:
# для каждой пары добавляются обе регистровые формы, если их ещё нет.
# setdefault — рукописная запись всегда сильнее выведенной.
_ALPHA_FOLD = dict(_ALPHA_FOLD_PAIRS)
for _lat, _cyr in _ALPHA_FOLD_PAIRS.items():
    _ALPHA_FOLD.setdefault(_lat.lower(), _cyr.lower())
    _ALPHA_FOLD.setdefault(_lat.upper(), _cyr.upper())
del _lat, _cyr

# --- Пробельные символы: приводятся к обычному пробелу U+0020 (замена 1:1) ---
# NBSP/narrow-NBSP/thin space и пр. визуально — пробелы. Приводим к обычному, чтобы
# (1) паттерны реквизитов, разрешающие лишь [' ', NBSP], ловили и narrow-NBSP;
# (2) граница слова для NER сохранялась (пробел не удаляем, иначе склеим ФИО).
# \t и \n НЕ трогаем — это структура сегмента (перенос строки в ячейке).
_SPACE_LIKE = frozenset(
    chr(c) for c in (
        0x00A0,  # NO-BREAK SPACE
        0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005, 0x2006,  # en/em/… quads
        0x2007,  # FIGURE SPACE
        0x2008,  # PUNCTUATION SPACE
        0x2009,  # THIN SPACE
        0x200A,  # HAIR SPACE
        0x202F,  # NARROW NO-BREAK SPACE
        0x205F,  # MEDIUM MATHEMATICAL SPACE
        0x3000,  # IDEOGRAPHIC SPACE
    )
)

# --- Дефис-подобные: кандидаты на схлопывание ВНУТРИ числа ---
# Обычный дефис, неразрывный дефис, figure dash, en dash, минус. Em dash (U+2014)
# НАМЕРЕННО не входит — это тире прозы между словами, схлопывать его нельзя.
_HYPHEN_LIKE = frozenset(
    chr(c) for c in (
        0x002D,  # HYPHEN-MINUS
        0x2010,  # HYPHEN
        0x2011,  # NON-BREAKING HYPHEN
        0x2012,  # FIGURE DASH
        0x2013,  # EN DASH
        0x2212,  # MINUS SIGN
    )
)


def _is_ascii_digit(ch: str) -> bool:
    return "0" <= ch <= "9"


def _is_cyrillic(ch: str) -> bool:
    # Кириллический блок U+0400..U+04FF (в т.ч. Ё/ё) — достаточно для признака
    # «слово смешанного алфавита» в своде латиница→кириллица.
    return "Ѐ" <= ch <= "ӿ"


# --------------------------------------------------------------------------- #
#      ЭТАП O2 — БЫСТРЫЙ ПУТЬ ТОЖДЕСТВА (оптимизация, НЕ смена поведения)      #
# --------------------------------------------------------------------------- #
# Функция ниже на неискажённом тексте — ТОЖДЕСТВО (это её задокументированное
# свойство, см. docstring), но узнаёт она об этом, только пройдя четыре
# посимвольных прохода с пятью списками длины текста. Замер O2: 19924 вызова и
# 4.3 c собственного времени на одной крупной фикстуре.
#
# Предикат ниже отвечает на вопрос «может ли хоть один проход что-то изменить»
# ТОЧНО, а не эвристически — по одному разбору каждого прохода:
#   проход 1 меняет текст только на _SPACE_LIKE (Zs) и на символах категории Cf;
#   проход 2 — только если в тексте есть символ из _DIGIT_LOOKALIKE;
#   проход 3 — только на прогоне разделителей между цифрами, а разделитель без
#              _HYPHEN_LIKE и без _SPACE_LIKE — это обычный пробел, и схлопывание
#              требует прогона длиной >= 2 («цифра, >=2 пробела, цифра»);
#   проход 4 — только если есть символ из _ALPHA_FOLD.
# Отсюда: нет ни одного символа перечисленных классов и нет «цифра, >=2 пробела,
# цифра» -> результат побайтно равен входу, а карта — range(len).
#
# Категорию Cf в регулярку не выписываем (её состав зависит от версии Unicode в
# интерпретаторе): её ловит str.isprintable() — по определению False для всех
# 'Other' (Cc/Cf/Cs/Co/Cn) и 'Separator'. Законные \n/\r/\t — это Cc, поэтому
# перед проверкой удаляем именно их; ЛЮБОЙ невидимый Cf после этого сделает
# строку непечатаемой и уведёт на полный путь. Проверка консервативна в
# БЕЗОПАСНУЮ сторону: сомнительный текст идёт полным путём, а не наоборот.
_FAST_TRIGGER_RE = re.compile(
    "["
    + re.escape("".join(sorted(_SPACE_LIKE)))
    + re.escape("".join(sorted(_HYPHEN_LIKE)))
    + re.escape("".join(sorted(_DIGIT_LOOKALIKE)))
    + re.escape("".join(sorted(_ALPHA_FOLD)))
    + "]"
    "|[0-9] {2,}[0-9]"
    # ОСR-артефакт пустой скобки-нуля («2()23», «500 ()()()») — новый проход
    # 1.5 ниже трогает текст ТОЛЬКО при наличии буквального "()"; проверка
    # контекста (цифра рядом) там же, здесь достаточно грубого триггера —
    # консервативно в безопасную сторону, как и остальные альтернативы.
    "|\\(\\)"
)
_DEL_LINE_WS = {ord(c): None for c in "\n\r\t"}


#: прогон ASCII-цифр, разбитый ОДИНОЧНЫМИ обычными пробелами. Проверка формы
#: точная (а не грубый триггер): иначе на быстрый путь перестал бы попадать
#: любой текст с суммой в разрядах, а это почти каждый договор.
_SPLIT_RUN_RE = re.compile(r"[0-9]+(?: [0-9]+)+")


def _has_split_digit_group(base: str) -> bool:
    """Есть ли в тексте цифровая группа, разбитая пробелами НЕ по разрядам.
    Считается по ASCII-цифрам: любой двойник/дефис/типографский пробел уже
    уводит текст на полный путь через _FAST_TRIGGER_RE, поэтому расхождение
    этой оценки с фактической группировкой невозможно в опасную сторону."""
    for m in _SPLIT_RUN_RE.finditer(base):
        groups = [len(g) for g in m.group(0).split(" ")]
        if (len(groups) >= _SPLIT_MIN_GROUPS
                and sum(groups) >= _SPLIT_MIN_DIGITS
                and not _is_thousands_grouping(groups)):
            return True
    return False


def _is_identity(base: str) -> bool:
    """Гарантированно ли normalize_for_detection вернёт вход без изменений."""
    return (_FAST_TRIGGER_RE.search(base) is None
            and not _has_split_digit_group(base)
            and base.translate(_DEL_LINE_WS).isprintable())


def normalize_for_detection(base: str) -> tuple[str, list[int]]:
    """Строит (norm_text, offset_map) — нормализованную копию текста и карту
    norm_idx → src_idx (индекс в base). Каждый символ norm происходит ровно из
    одного символа base (см. инвариант карты в docstring модуля).

    На неискажённом тексте функция — тождество (norm == base, offset_map ==
    range): свод срабатывает лишь при наличии омоглифов/невидимых/дефисов между
    цифрами. Это гарантирует, что recall_exact на каноническом корпусе не падает.
    """
    if not base:
        return "", []

    # ЭТАП O2: тождественный вход — четыре прохода ниже вернули бы ровно это.
    if _is_identity(base):
        return base, list(range(len(base)))

    # --- Проход 1: снять невидимые (Cf), пробельные привести к ' ', остальное
    # оставить как есть. Собираем параллельные списки chars/src (src[k] — индекс
    # символа chars[k] в base). ---
    chars: list[str] = []
    src: list[int] = []
    # soft[k] — символ chars[k] пришёл из ТИПОГРАФСКОГО пробела (NBSP, narrow
    # NBSP, thin space…), а не из обычного U+0020. Различие нужно проходу 3:
    # обычный пробел между числами — законный разделитель ЗНАЧЕНИЙ, а
    # неразрывный/узкий внутри числа — артефакт вёрстки того же значения.
    soft: list[bool] = []
    n = len(base)
    i = 0
    while i < n:
        ch = base[i]
        if ch in _SPACE_LIKE:
            chars.append(" ")
            src.append(i)
            soft.append(True)
            i += 1
            continue
        if ch in _HYPHEN_LIKE:
            chars.append(ch)
            src.append(i)
            soft.append(False)
        elif unicodedata.category(ch) == "Cf":
            # Zero-width/невидимые управляющие форматирования: ZWSP/ZWNJ/ZWJ/WJ/
            # SHY/BOM/LRM/RLM. Удаляем целиком — длина падает, карта это учитывает.
            i += 1
            continue
        else:
            chars.append(ch)
            src.append(i)
            soft.append(False)
        i += 1

    # --- Проход 1.5: пустая скобка-ноль, артефакт распознавания/OCR. «2()23»
    # (дата, пустая скобка = ноль), «500 ()()()» (хвостовые нули круглой суммы)
    # — НО «(495) 123-45-67» (код города, скобка С цифрами внутри) не
    # трогается: между '(' и ')' там не пусто, условие ниже просто не
    # выполняется, отдельного анти-правила не требуется. Гейт — цифра
    # (настоящая или двойник) НЕПОСРЕДСТВЕННО ПЕРЕД скобкой, пробелы можно
    # пропускать. Цифры ПОСЛЕ не требуем: «500 ()()()» — хвост числа, после
    # него в тексте не цифра, а слово («рублей») или конец значения. Пара уже
    # свёрнутая в «0» сама становится «цифрой перед» для следующей пары в
    # цепочке — так «500 ()()()» сводится как «500» + «0» + «0» + «0», без
    # отдельного прохода вперёд.
    # Односторонний гейт не портит прозу: «см. приложение ()» — перед скобкой
    # буква, не цифра, условие не выполняется. Опасные соседи защищены тем,
    # что у них между '(' и ')' не пусто: «(495) 123-45-67», «п. 5(2)»,
    # «(в том числе НДС)» — паттерн "()" там просто не встречается.
    # Длина падает («()» -> «0»): в карте остаётся исходный индекс открывающей
    # скобки, закрывающая выбрасывается как разделитель — тот же приём, что и
    # для невидимых Cf-символов выше.
    def _is_digitlike(c: str) -> bool:
        return _is_ascii_digit(c) or c in _DIGIT_LOOKALIKE

    chars2: list[str] = []
    src2: list[int] = []
    soft2: list[bool] = []
    ln = len(chars)
    i = 0
    while i < ln:
        if chars[i] == "(" and i + 1 < ln and chars[i + 1] == ")":
            li = len(chars2) - 1
            while li >= 0 and chars2[li] == " ":
                li -= 1
            prev_ok = li >= 0 and _is_digitlike(chars2[li])

            if prev_ok:
                chars2.append("0")
                src2.append(src[i])
                soft2.append(False)
                i += 2
                continue
        chars2.append(chars[i])
        src2.append(src[i])
        soft2.append(soft[i])
        i += 1
    chars, src, soft = chars2, src2, soft2

    m = len(chars)
    is_sep = [c == " " or c in _HYPHEN_LIKE for c in chars]
    is_dl = [_is_ascii_digit(c) or c in _DIGIT_LOOKALIKE for c in chars]

    # --- ЦИФРОВАЯ ЦЕПЬ (этап A5). Максимальный отрезок из цифровых токенов и
    # разделителей между ними, обрезанный по краям до цифрового символа:
    # «Ч 068 268 315» — одна цепь, «кв. 2б» — цепь из одного токена. Проход 2
    # ниже смотрит на цепь, а не только на токен: реквизит РАЗБИТ пробелами по
    # группам, и группа «Ч» или «2О» сама по себе порога «>=2 настоящих цифры»
    # не набирает — двойник на краю группы оставался буквой, и весь реквизит
    # уходил в LLM открытым (A5, класс mut:homoglyph). Порог цепи 6 настоящих
    # цифр — это уже не номер дома и не квартира, а реквизит/телефон.
    chain_digits = [0] * m         # для каждого символа — цифр в его цепи
    chain_len = [0] * m            # …и знаков цифрового вида в ней (CHAR-NORM)
    chain_bounds: list[tuple[int, int]] = [(-1, -1)] * m

    # Токены цифрового вида: (начало, конец, число настоящих цифр).
    toks: list[tuple[int, int, int]] = []
    k = 0
    while k < m:
        if not is_dl[k]:
            k += 1
            continue
        j = k
        while j < m and is_dl[j]:
            j += 1
        toks.append((k, j, sum(1 for t in range(k, j) if _is_ascii_digit(chars[t]))))
        k = j

    def _joins_chain(a: int, b: int, dc: int) -> bool:
        """Может ли токен [a:b) быть ГРУППОЙ разбитого пробелами реквизита.
        С настоящей цифрой — да. Совсем без цифр — только если это КОРОТКАЯ (1-2
        знака) группа из «сильных» двойников: «Ч», «І», «Чб». Ограничение не
        косметическое: без него цепь «7707083893 ООО «Ромашка»» затянула бы
        слово ООО и вернула бы «000» — свод обязан остаться сводом цифр, а не
        порчей прозы. Строчные о/з/ч/і исключены намеренно: «об», «за» —
        частотные слова, а искажение цифры печатают прописной."""
        if dc >= 1:
            return True
        if b - a > 2 or not all(chars[t] in _STRONG_LOOKALIKE for t in range(a, b)):
            return False
        # …и она не приклеена к букве: в «счёт 407… ЗАО» токен — одна «З», за
        # ней сразу «А», и без этой проверки аббревиатура стала бы «3АО».
        return not ((a > 0 and chars[a - 1].isalpha())
                    or (b < m and chars[b].isalpha()))

    def _chain_link(pb: int, na: int) -> bool:
        """Связка [pb:na) между соседними цифровыми токенами продолжает цепь.
        Разделители (пробел/дефис) — как раньше; ДОПОЛНИТЕЛЬНО допускается ОДИН
        знак из _WEAK_JOIN (запятая/точка): «525,0О» и «12.03.2023» — одно
        значение, а копейки и год оставались отдельной цепью длиной 2-4 и
        порога не набирали. Пустая связка (na == pb) невозможна по построению
        токенов, но проверяется явно — она означала бы слияние соседних
        токенов без разделителя вообще."""
        if na <= pb:
            return False
        weak = 0
        for t in range(pb, na):
            if is_sep[t]:
                continue
            if chars[t] in _WEAK_JOIN and weak == 0:
                weak = 1
                continue
            return False
        return True

    i0 = 0
    while i0 < len(toks):
        a, b, dc = toks[i0]
        if not _joins_chain(a, b, dc):
            i0 += 1
            continue
        i1 = i0
        while i1 + 1 < len(toks):
            na, nb, ndc = toks[i1 + 1]
            pb = toks[i1][1]
            if not _joins_chain(na, nb, ndc):
                break
            if not _chain_link(pb, na):
                break
            i1 += 1
        cs, ce = toks[i0][0], toks[i1][1]
        n_dig = sum(dcx for _, _, dcx in toks[i0:i1 + 1])
        n_len = sum(bx - ax for ax, bx, _ in toks[i0:i1 + 1])
        for t in range(cs, ce):
            chain_digits[t] = n_dig
            chain_len[t] = n_len
            chain_bounds[t] = (cs, ce)
        i0 = i1 + 1

    def _is_long_chain(t: int) -> bool:
        """Цепь вокруг символа t тянет на реквизит/телефон — см. _CHAIN_LEN_MIN."""
        return (chain_digits[t] >= _CHAIN_DIGIT_MIN
                or (chain_len[t] >= _CHAIN_LEN_MIN
                    and chain_digits[t] >= _CHAIN_REAL_MIN))

    # --- Проход 2: цифровые токены (максимальные прогоны из цифр/омоглифов-цифр
    # БЕЗ разделителей). Внутри токена с >=2 реальными цифрами сводим омоглифы в
    # цифры. Токен с >=1 реальной цифрой помечаем numeric — это разрешает
    # схлопывание разделителей вокруг него (см. проход 3). ---
    out_chars = list(chars)
    is_num = [False] * m           # символ принадлежит цифровому токену (>=1 цифра)
    k = 0
    while k < m:
        if not is_dl[k]:
            k += 1
            continue
        j = k
        while j < m and is_dl[j]:
            j += 1
        digit_count = sum(1 for t in range(k, j) if _is_ascii_digit(chars[t]))
        # A5: группа БЕЗ единой настоящей цифры («Ч», «І», «Чб») — тоже часть
        # реквизита, если цепь вокруг неё тянет на реквизит; иначе одиночный
        # двойник на краю реквизита оставался буквой и рвал весь номер.
        long_chain_k = _is_long_chain(k)
        if digit_count >= 1 or long_chain_k:
            for t in range(k, j):
                is_num[t] = True
            # Порог >=2 реальных цифр: защищает «2б»/«5о» (номер квартиры,
            # одиночная цифра рядом с буквой) от порчи. Реквизиты/телефоны — это
            # длинные прогоны, у них цифр заведомо больше.
            # A5: ИЛИ цепь целиком тянет на реквизит — тогда одиночная группа
            # («Ч», «2О», «О9») внутри неё тоже сводится. Условие только
            # РАСШИРЯЕТ прежний класс форм: всё, что сводилось раньше, сводится.
            long_chain = long_chain_k
            if digit_count >= 2 or long_chain:
                cs, ce = chain_bounds[k]
                for t in range(k, j):
                    c = chars[t]
                    repl = _DIGIT_LOOKALIKE.get(c)
                    if repl is None:
                        continue
                    if c in _LOOKALIKE_EDGE_UNSAFE and (t == k or t == j - 1):
                        # 'б' на краю токена: раньше — всегда мимо. Теперь мимо,
                        # если она на краю ЦЕПИ («630099 12б» — литера дома) либо
                        # цепь коротка; внутри длинной цепи («1 б99 905 88І 872»)
                        # это искажённая шестёрка.
                        # ЭТАП CHAR-NORM — два разрешения сверх этого, каждое
                        # отделяет литеру дома от искажённой цифры ПО ТЕКСТУ:
                        #   * НАЧАЛО цепи: литера — всегда СУФФИКС номера
                        #     («12б»), префиксом её не пишут, поэтому 'б' в
                        #     начале реквизитной цепи («б22-513», «б597769253»)
                        #     литерой быть не может;
                        #   * ДЛИННЫЙ СОБСТВЕННЫЙ ТОКЕН (>= _EDGE_TOKEN_MIN
                        #     знаков): «4Ч170335б», «34482б» — номера дома такой
                        #     длины не бывает, а «630099 12б» остаётся нетронут,
                        #     потому что его токен «12б» короткий.
                        edge_ok = (
                            (long_chain and cs < t < ce - 1)
                            or (long_chain and t == cs)
                            or (j - k) >= _EDGE_TOKEN_MIN
                        )
                        if not edge_ok:
                            continue
                    out_chars[t] = repl
        k = j

    # --- Проход 3: схлопывание разделителей МЕЖДУ цифровыми токенами. Убираем
    # прогон разделителей, если слева и справа — цифровой символ И прогон либо
    # содержит дефис, либо длиннее одного символа. Одиночный пробел/NBSP между
    # цифрами НЕ трогаем: его уже допускают паттерны реквизитов, а лишнее
    # схлопывание только повышает риск склейки соседних чисел. ---
    keep = [True] * m
    k = 0
    while k < m:
        if not is_sep[k]:
            k += 1
            continue
        j = k
        has_hyphen = False
        has_soft = False
        while j < m and is_sep[j]:
            if chars[j] in _HYPHEN_LIKE:
                has_hyphen = True
            if soft[j]:
                has_soft = True
            j += 1
        left_num = k - 1 >= 0 and is_num[k - 1]
        right_num = j < m and is_num[j]
        # A5: has_soft — типографский пробел (NBSP/узкий/тонкий) МЕЖДУ цифрами.
        # Обычный одиночный U+0020 по-прежнему не трогаем (он разделяет группы
        # и его допускают паттерны), а неразрывный внутри числа значений не
        # разделяет — он их склеивает при вёрстке, и оставленный на месте рвал
        # фиксированные группы паттернов («\d{6}» паспорта, «\d{3}» СНИЛС).
        if left_num and right_num and (has_hyphen or has_soft or (j - k) >= 2):
            for t in range(k, j):
                keep[t] = False
        elif has_soft:
            # ЭТАП CHAR-NORM — типографский пробел НА КРАЮ значения, у знака
            # пунктуации, а не между двумя цифрами. Ветка выше его не видит
            # (справа/слева не цифра), и он оставался пробелом ВНУТРИ значения:
            # «19.11<NBSP>.1962» — дата рождения, чей паттерн требует «\d\.\d»;
            # «+7<NBSP> (<NNBSP>495)» — телефон, чей паттерн требует «\(\d{3}».
            # Оба уходили в LLM открытыми (класс mut:invisible).
            # Условие узкое НАМЕРЕННО: выбрасываются ТОЛЬКО типографские
            # пробелы прогона (обычный U+0020 остаётся — он законный разделитель
            # слов), и только если цифра стоит с одной стороны прогона, а с
            # другой — НЕ БУКВА. Буква с любой стороны запрещает выброс: это и
            # есть отклонённый приём «удалить NBSP» («Иван<NBSP>Иванов» склеился
            # бы, «2023<NBSP>г.» тоже).
            left_ch = chars[k - 1] if k - 1 >= 0 else ""
            right_ch = chars[j] if j < m else ""
            left_dl = bool(left_ch) and is_dl[k - 1]
            right_dl = bool(right_ch) and is_dl[j]
            if ((left_dl or right_dl)
                    and not (left_ch and left_ch.isalpha())
                    and not (right_ch and right_ch.isalpha())):
                for t in range(k, j):
                    if soft[t]:
                        keep[t] = False
        k = j

    # --- Проход 3.5 (CHAR-NORM): обычный пробел ВНУТРИ цифровой группы.
    # Смотрим на текст ПОСЛЕ прохода 3 — дефисы и типографские пробелы уже
    # выброшены, поэтому «90 14 617-0-85» и «90 14 617085» разбираются как одна
    # и та же запись. Группа — прогон знаков цифрового вида, разделитель —
    # РОВНО один оставшийся обычный пробел. Условие приёма — в комментарии к
    # _SPLIT_MIN_GROUPS.
    #
    # ГРУППОЙ СЧИТАЕТСЯ НЕ ЛЮБОЙ ПРОГОН ЗНАКОВ ЦИФРОВОГО ВИДА. Требуется хотя бы
    # одна НАСТОЯЩАЯ цифра и отсутствие приклеенной буквы по краям — иначе
    # хвост слова становится «группой»: в «число 7707083893 без» и 'о', и 'б'
    # — знаки цифрового вида, запись читалась бы как три группы, и пробелы
    # вокруг числа были бы выброшены (слово склеилось бы с реквизитом).
    def _split_group_ok(a: int, b: int) -> bool:
        if not any(_is_ascii_digit(chars[t]) for t in range(a, b)):
            return False
        return not ((a > 0 and chars[a - 1].isalpha())
                    or (b < m and chars[b].isalpha()))

    alive = [k for k in range(m) if keep[k]]
    na = len(alive)
    # границы групп знаков цифрового вида в «живой» последовательности
    spans: list[tuple[int, int]] = []
    q = 0
    while q < na:
        if not is_dl[alive[q]]:
            q += 1
            continue
        r = q
        while r < na and is_dl[alive[r]]:
            r += 1
        spans.append((q, r))
        q = r

    gi = 0
    while gi < len(spans):
        if not _split_group_ok(alive[spans[gi][0]], alive[spans[gi][1] - 1] + 1):
            gi += 1
            continue
        groups = [spans[gi][1] - spans[gi][0]]
        seps: list[int] = []
        gj = gi
        while gj + 1 < len(spans):
            gap_a, gap_b = spans[gj][1], spans[gj + 1][0]
            if gap_b - gap_a != 1:
                break
            sep = alive[gap_a]
            if chars[sep] != " " or soft[sep]:
                break
            nx = spans[gj + 1]
            if not _split_group_ok(alive[nx[0]], alive[nx[1] - 1] + 1):
                break
            seps.append(sep)
            groups.append(nx[1] - nx[0])
            gj += 1
        if (len(groups) >= _SPLIT_MIN_GROUPS
                and sum(groups) >= _SPLIT_MIN_DIGITS
                and not _is_thousands_grouping(groups)):
            for t in seps:
                keep[t] = False
        gi = gj + 1

    out2_chars: list[str] = []
    offset_map: list[int] = []
    for k in range(m):
        if keep[k]:
            out2_chars.append(out_chars[k])
            offset_map.append(src[k])

    # --- Проход 4: свод алфавитных омоглифов латиница→кириллица ВНУТРИ смешанных
    # по алфавиту слов (есть и кириллица, и сводимая латиница). ---
    p = 0
    L = len(out2_chars)
    while p < L:
        if not out2_chars[p].isalpha():
            p += 1
            continue
        q = p
        while q < L and out2_chars[q].isalpha():
            q += 1
        token = out2_chars[p:q]
        has_cyr = any(_is_cyrillic(c) for c in token)
        has_lat_fold = any(c in _ALPHA_FOLD for c in token)
        if has_cyr and has_lat_fold:
            for t in range(p, q):
                repl = _ALPHA_FOLD.get(out2_chars[t])
                if repl is not None:
                    out2_chars[t] = repl
        p = q

    return "".join(out2_chars), offset_map


def norm_to_src(offset_map: list[int], n_start: int, n_end: int) -> tuple[int, int]:
    """Отображает спан [n_start, n_end) нормализованного текста в исходные
    координаты. Требует n_end > n_start (пустые спаны детекторы не создают)."""
    return offset_map[n_start], offset_map[n_end - 1] + 1


def src_to_norm(offset_map: list[int], s: int, e: int) -> tuple[int, int]:
    """Обратное отображение: исходный спан [s, e) → спан нормализованного текста.
    Нужно, чтобы координаты уже найденных (в исходных координатах) сущностей —
    напр. regex-реквизитов-барьеров для расширения адреса — привести к системе
    координат норм-текста, в которой работает NER. offset_map строго возрастает,
    поэтому bisect корректен. Выброшенные при нормализации исходные позиции
    отображаются на ближайшую сохранённую границу — для геометрии барьеров этого
    достаточно (барьер лишь останавливает расширение, точность до символа не
    критична)."""
    ns = bisect.bisect_left(offset_map, s)
    ne = bisect.bisect_left(offset_map, e)
    return ns, ne


def detection_view(segment) -> tuple[str, list[int]]:
    """Возвращает (norm_text, offset_map) для сегмента, кэшируя результат в
    segment.metadata. База нормализации — detection_text (регистро-нормализованная
    копия из extractor, равной длины с segment.text) при наличии, иначе сам
    segment.text. В обоих случаях offset_map индексирует segment.text.

    Детекторы (regex/ner) вызывают эту функцию вместо прямого чтения
    detection_text: normalize_for_detection на неискажённом тексте — тождество,
    поэтому для чистых сегментов поведение не меняется."""
    md = segment.metadata
    cached = md.get("_norm_cache")
    if cached is not None:
        return cached
    base = md.get("detection_text", segment.text)
    norm, offset_map = normalize_for_detection(base)
    md["_norm_cache"] = (norm, offset_map)
    return norm, offset_map
