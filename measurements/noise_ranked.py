# -*- coding: utf-8 -*-
"""Шумовой корпус: 11 классов искажения, ранжированные ПО РОСТУ УТЕЧКИ.

Решение техдиректора: эффект шума меряется УТЕЧКОЙ, не полнотой. На шумовом
корпусе они расходятся, и здесь это видно поимённо: класс, у которого полнота
не шелохнулась (или даже выросла), может при этом утроить утечку, и наоборот —
обвал полноты может означать не открытое значение, а маску чужого типа.
Числа взяты из вывода tests/corpus_v2/measure_noise.py этой сессии
(measurements/noise_measure2.log) — прибор чужой, здесь только сортировка.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "noise_measure2.log"), encoding="utf-8").read()
block = src.split("=== ПОТЕРИ ПО КЛАССАМ ИСКАЖЕНИЯ ===")[1].split("=== ПОТЕРИ ПО ВИДАМ")[0]
rows = []
for line in block.splitlines():
    m = re.match(r"\s+([a-z_]+)\s+(\d+)\s+([\d.]+)%\s+([\d.]+)%\s+(\d+)\s+(\d+)\s+"
                 r"([\d.]+)%\s+([\d.]+)%\s*(\S*)", line)
    if m and m.group(1) != "ВСЕГО":
        rows.append((m.group(1), int(m.group(2)), float(m.group(3)), float(m.group(4)),
                     int(m.group(5)), int(m.group(6)), float(m.group(7)),
                     float(m.group(8)), m.group(9) or "-"))

L = []
L.append("ШУМОВОЙ КОРПУС (tests/corpus_v2/noise, 32 документа = 16 пар «чистый/грязный»)")
L.append("Классов искажения 11, эталонных вхождений 948.")
L.append("")
L.append("ВЕРХНЯЯ ГРАНИЦА, НЕ ИЗМЕРЕНИЕ: искажения синтезированы генератором.")
L.append("Класс порчи распознавания, которого генератор не знает, здесь не появится,")
L.append("и его отсутствие будет невидимым.")
L.append("")
L.append("РАНГ ПО РОСТУ УТЕЧКИ (решение техдиректора: эффект меряется утечкой)")
L.append("-" * 106)
L.append("%-18s %5s %8s %8s %11s %9s %9s %11s %s" % (
    "класс", "n", "утеч.ч", "утеч.гр", "dУтечки", "полн.ч", "полн.гр", "dПолноты", "происх."))
L.append("-" * 106)
for r in sorted(rows, key=lambda r: -(r[7] - r[6])):
    L.append("%-18s %5d %7.1f%% %7.1f%% %+8.1f пп %8.1f%% %8.1f%% %+8.1f пп %s"
             % (r[0], r[1], r[6], r[7], r[7] - r[6], r[2], r[3], r[3] - r[2], r[8]))
L.append("-" * 106)
L.append("ВСЕГО по корпусу: утечка 6.8 -> 43.1 % (+36.3 пп); полнота 91.5 -> 65.3 % (-26.2 пп)")
L.append("")
L.append("ГДЕ ДВА КРИТЕРИЯ РАСХОДЯТСЯ — именно ради этого разрез и сделан:")
for r in sorted(rows, key=lambda r: -(r[7] - r[6])):
    dl, dr = r[7] - r[6], r[3] - r[2]
    if dr >= -1.0 and dl >= 1.0:
        L.append("  %-18s полнота %+.1f пп (НЕ пострадала), а утечка %+.1f пп — судить "
                 "здесь по полноте значит не увидеть дефект вовсе" % (r[0], dr, dl))
    elif dl >= 20.0 and dl > 2.0 * abs(dr):
        L.append("  %-18s утечка %+.1f пп при падении полноты всего %+.1f пп — полнота "
                 "показала бы лёгкий ущерб там, где значение уходит ОТКРЫТЫМ" % (r[0], dl, dr))
    elif dr <= -30.0 and dl < abs(dr) / 2.0:
        L.append("  %-18s полнота обвалилась %+.1f пп, а утечка выросла лишь %+.1f пп — "
                 "значение чаще закрыто маской ЧУЖОГО типа, чем открыто" % (r[0], dr, dl))
L.append("")
L.append("КЛАССЫ, ГДЕ ШУМ НЕ СТОИЛ НИЧЕГО (dУтечки < 2 пп): "
         + ", ".join(r[0] for r in rows if abs(r[7] - r[6]) < 2.0))
L.append("")
L.append("ПРОИСХОЖДЕНИЕ КЛАССА: observed-user — искажение наблюдалось у пользователя;")
L.append("inferred — выведено из устройства распознавания, у пользователя не наблюдалось.")
L.append("Единственный наблюдённый класс (paren_zero) оказался и самым дорогим.")

open(os.path.join(HERE, "noise_ranked.txt"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("ok")
