"""ЛОВУШКИ этапа MARKUP-SPREAD, дословно: что программа делает и почему.

Каждая проба — синтетический текст (реальные документы в репозиторий не
попадают, запрет 7), в котором помеченное человеком слово ВСТРЕЧАЕТСЯ ЕЩЁ РАЗ,
но означает там ДРУГОЕ.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from markup_spread import find_occurrences        # noqa: E402
from models import SourceDocument, TextSegment    # noqa: E402


def probe(title, why, lines, mark, entity_type):
    doc = SourceDocument(
        segments=[TextSegment(id="l%d" % i, text=t, source_type="txt_line",
                              metadata={"line_index": i})
                  for i, t in enumerate(lines)],
        source_format="txt", source_path="probe.txt")
    seg_id, needle = mark
    seg = next(s for s in doc.segments if s.id == seg_id)
    st = seg.text.index(needle)
    found = find_occurrences(doc, {}, seg_id, st, st + len(needle), entity_type)
    taken = {(f["segment_id"], f["start"]) for f in found}
    print("=" * 78)
    print(title)
    print("почему так: " + why)
    print("  ПОМЕЧЕНО человеком: %r (тип %s) в %s" % (needle, entity_type, seg_id))
    for s in doc.segments:
        if s.id == seg_id:
            print("    %-4s ЯКОРЬ      %s" % (s.id, s.text))
            continue
        mine = [f for f in found if f["segment_id"] == s.id]
        if mine:
            print("    %-4s ЗАКРЫТО    %s   -> %s"
                  % (s.id, s.text, ", ".join(repr(f["surface"]) for f in mine)))
        else:
            print("    %-4s не тронуто %s" % (s.id, s.text))
    print("  ИТОГО закрыто вхождений: %d" % len(taken))


