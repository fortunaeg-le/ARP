sub(
    "| **ЖИВ: 409 масок / 375 значений** (замер 2026-08-18, линия «и» гейта; "
    "прежняя цифра 379 — от 2026-08-10 разовым `experiments/cross_pairs.py`) |",
    "| **ЖИВ: 431 маска / 394 значения** (замер 2026-08-18 ПОСЛЕ этапа PER-SPREAD, "
    "линия «и» гейта). Класс ВЫРОС на 22 маски / 19 значений, и это ПРЯМАЯ ЦЕНА "
    "PER-SPREAD: люди, которых прежде не находили вовсе (Коваль, Мельник, Гусева и "
    "др.), теперь находятся, а `syntax_compound` склеивает «ИП + ФИО» в одну "
    "сущность и называет её `ORG` — то есть новонайденный человек попадает сразу в "
    "этот класс, минуя состояние «защищён своим типом». Реестр `known_single_guard.json` "
    "пересобран (394 случая, из класса не выпал НИ ОДИН — только в дампе 19, только в "
    "реестре 0). Прежние числа: 409/375 — 2026-08-18 до PER-SPREAD; 379 — 2026-08-10 "
    "разовым `experiments/cross_pairs.py` |",
)

