    "случайно накрывал фамилию следующей записи; PER-SPREAD этот перебег убрал, а "
    "подобрать вхождение штатным проходом 2 нельзя — `PerAnchorDetector.guard` "
    "требует ЗАГЛАВНОЙ буквы, а её в документе нет ни одной. То есть защита была "
    "побочным эффектом дефекта, и вместе с дефектом ушла | послабление guard'а там, "
